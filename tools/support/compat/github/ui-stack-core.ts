import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { createReadStream, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

/** Read private runner cores; never copy core memory or frame arguments to artifacts. */
export async function inspectUiCores(scratch: string, output: string): Promise<readonly object[]> {
  const cores = readdirSync(scratch).filter((name) => name.startsWith("core."));
  assert(cores.length <= 16, "unexpected number of private core files");
  const results: object[] = [];
  for (const [index, name] of cores.entries()) {
    const filename = path.join(scratch, name);
    const sha = createHash("sha256");
    for await (const chunk of createReadStream(filename)) sha.update(chunk);
    const identify = spawnSync(
      "gdb",
      [
        "-q",
        "-nx",
        "-batch",
        "-iex",
        "set auto-load off",
        "-iex",
        "set debuginfod enabled off",
        "-iex",
        "set print frame-arguments none",
        "-iex",
        "set print entry-values no",
        "-iex",
        "set width 0",
        "--core",
        filename,
        "-ex",
        "info proc exe",
      ],
      { encoding: "utf8", maxBuffer: 1024 * 1024, timeout: 60_000 },
    );
    const identityOutput = identify.stdout + identify.stderr;
    const executable = /^exe = '([^'\r\n]+)'$/m.exec(identityOutput)?.[1] ?? null;
    const argumentsList = [
      "-q",
      "-nx",
      "-batch",
      "-iex",
      "set auto-load off",
      "-iex",
      "set debuginfod enabled off",
      "-iex",
      "set print frame-arguments none",
      "-iex",
      "set print entry-values no",
      "-iex",
      "set width 0",
      "--core",
      filename,
      ...(executable === null ? [] : ["--exec", executable]),
      "-ex",
      "info files",
      "-ex",
      "info sharedlibrary",
      "-ex",
      "thread apply all bt 64",
    ];
    const backtrace = spawnSync("gdb", argumentsList, {
      encoding: "utf8",
      maxBuffer: 8 * 1024 * 1024,
      timeout: 120_000,
    });
    // Frame arguments are disabled before core loading, including automatic initial frames.
    const report = {
      name,
      bytes: statSync(filename).size,
      sha256: sha.digest("hex"),
      executable,
      identify: {
        status: identify.status,
        signal: identify.signal,
        error: identify.error?.message ?? null,
      },
      backtrace: {
        status: backtrace.status,
        signal: backtrace.signal,
        error: backtrace.error?.message ?? null,
      },
      coreRetainedInArtifact: false,
      scope:
        "private runner core only; bounded symbols/PCs, no frame arguments or environment dump",
    };
    writeFileSync(path.join(output, `core-${index}.json`), JSON.stringify(report, null, 2) + "\n");
    const withoutCommandLine = (value: string): string =>
      value
        .split("\n")
        .filter((line) => !line.startsWith("Core was generated by "))
        .join("\n");
    writeFileSync(
      path.join(output, `core-${index}.identity.txt`),
      withoutCommandLine(identityOutput),
    );
    writeFileSync(
      path.join(output, `core-${index}.backtrace.txt`),
      withoutCommandLine(backtrace.stdout + backtrace.stderr),
    );
    results.push(report);
  }
  return results;
}
