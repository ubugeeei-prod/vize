import assert from "node:assert/strict";
import test from "node:test";
import { publicEvent, publicFrames } from "./pack-stack-attribution.ts";

test("public executable identity excludes all private argv and environment content", () => {
  const secret = "PRIVATE_ARGUMENT_NEVER_PUBLISH";
  const line = `30388 10:39:55.123 execve("/managed/pnpm.native", ["pnpm", "${secret}"], ["TOKEN=${secret}"]) = 0`;
  assert.deepEqual(publicEvent(line), {
    event: "exec",
    pid: 30388,
    at: "10:39:55.123",
    executable: "/managed/pnpm.native",
    completed: true,
  });
  assert.equal(JSON.stringify(publicEvent(line)).includes(secret), false);
  assert.deepEqual(
    publicEvent(
      `30388 10:39:55.124 execveat(4, "/managed/pnpm.native", ["${secret}"], 0x123, 0) = 0`,
    ),
    {
      event: "exec",
      pid: 30388,
      at: "10:39:55.124",
      executable: "/managed/pnpm.native",
      completed: true,
    },
  );
});

test("bounded core frames retain only PCs and module names", () => {
  const raw =
    "Core was generated by PRIVATE\n#0  0x123abc in privateFunction (PRIVATE_ARGUMENT) from /tmp/fspy.so\n#1  0x456def in anotherFunction (PRIVATE_ENV) at secret:3\n";
  assert.deepEqual(publicFrames(raw), [
    { frame: 0, pc: "0x123abc", module: "/tmp/fspy.so" },
    { frame: 1, pc: "0x456def", module: null },
  ]);
  assert.equal(JSON.stringify(publicFrames(raw)).includes("PRIVATE"), false);
  assert.equal(publicFrames(raw.repeat(100)).length, 64);
});

test("only child lineage and terminal status escape syscall operands", () => {
  assert.deepEqual(
    publicEvent("30388 10:39:55.125 clone(child_stack=PRIVATE, flags=PRIVATE) = 30427"),
    { event: "child", parent: 30388, pid: 30427, at: "10:39:55.125" },
  );
  assert.deepEqual(publicEvent("30388 10:39:55.126 +++ killed by SIGABRT (core dumped) +++"), {
    event: "signal-exit",
    pid: 30388,
    at: "10:39:55.126",
    signal: "SIGABRT",
  });
  assert.deepEqual(publicEvent("30388 10:39:55.127 +++ exited with 0 +++"), {
    event: "exit",
    pid: 30388,
    at: "10:39:55.127",
    status: 0,
  });
  assert.equal(
    publicEvent("30388 10:39:55.128 wait4(30427, PRIVATE, 0, PRIVATE) = 30427"),
    undefined,
  );
  assert.deepEqual(
    publicEvent("30427 10:39:55.129 --- SIGABRT {si_pid=PRIVATE, si_uid=PRIVATE} ---"),
    { event: "signal", pid: 30427, at: "10:39:55.129", signal: "SIGABRT" },
  );
});
