/**
 * Vite config generation for the scale benchmark.
 *
 * The reference (`rolldown/benchmarks`) gives every tool "a minimal
 * configuration that enables production mode (minification, sourcemaps) and
 * disables gzip". The two configs written here are byte-identical apart from
 * the plugin line, so a difference in the result is a difference in the plugin.
 *
 * The metrics plugin is part of both configs on purpose: emitted module count
 * has to be collected under the same conditions it is compared under. A speed
 * win that drops modules is a correctness bug, and only the module list proves
 * it either way.
 */

import { writeFileSync } from "node:fs";
import { join } from "node:path";

const TOOLS = /** @type {const} */ (["vize", "vue"]);

function metricsPlugin(tool) {
  return `  {
    name: 'bench-metrics',
    generateBundle(_options, bundle) {
      const moduleIds = new Set()
      for (const item of Object.values(bundle)) {
        if (item.type !== 'chunk') continue
        for (const id of Object.keys(item.modules)) moduleIds.add(id)
      }
      writeFileSync(
        join(import.meta.dirname, '.metrics-${tool}.json'),
        JSON.stringify({ moduleCount: moduleIds.size, modules: [...moduleIds].sort() }, null, 0),
      )
    },
  }`;
}

function configSource({ tool, pluginImport, pluginExpression }) {
  return `// GENERATED by tools/benchmarks/scripts/scale — do not edit.
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { defineConfig } from 'vite'
${pluginImport}

export default defineConfig({
  root: import.meta.dirname,
  logLevel: 'silent',
  resolve: {
    alias: {
      '@bench-assets': join(import.meta.dirname, 'assets'),
    },
  },
  plugins: [
${pluginExpression},
${metricsPlugin(tool)},
  ],
  build: {
    outDir: 'dist-${tool}',
    emptyOutDir: true,
    minify: true,
    sourcemap: true,
    reportCompressedSize: false,
    rollupOptions: {
      input: join(import.meta.dirname, 'index.html'),
    },
  },
})
`;
}

/**
 * @param appDir generated app root
 * @param vizePluginEntry absolute path to the built `@vizejs/vite-plugin` entry
 */
export function writeConfigs(appDir, vizePluginEntry) {
  writeFileSync(
    join(appDir, "vite.vize.config.mjs"),
    configSource({
      tool: "vize",
      pluginImport: `import vize from ${JSON.stringify(vizePluginEntry)}`,
      pluginExpression: "    vize()",
    }),
  );

  writeFileSync(
    join(appDir, "vite.vue.config.mjs"),
    configSource({
      tool: "vue",
      pluginImport: "import vue from '@vitejs/plugin-vue'",
      pluginExpression: "    vue()",
    }),
  );
}

export function configPath(appDir, tool) {
  return join(appDir, `vite.${tool}.config.mjs`);
}

export { TOOLS };
