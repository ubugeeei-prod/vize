import { formatMs, renderDocument } from "./compare-tools.mjs";
import { formatSpeedup, getVariant, renderEngineClassSections } from "./compare-tools-report.mjs";
import { SNAPSHOT_LOCALES, SURFACE_ORDER, surfaceLabel } from "./published-snapshot-locales.mjs";
import { diagnosticText } from "./published-snapshot-diagnostics.mjs";

export const RESULT_PATH = "tools/benchmarks/results/tool-benchmark-latest.json";
const REPOSITORY = "https://github.com/ubugeeei-prod/vize";

export function table(headers, rows) {
  return [headers, headers.map(() => "---"), ...rows]
    .map((row) => `| ${row.join(" | ")} |`)
    .join("\n");
}

export function provenance(data, locale) {
  const t = SNAPSHOT_LOCALES[locale];
  return [
    t.source,
    table(
      [t.metadata[0], t.metadata[1], t.metadata[2], t.metadata[3]],
      [
        [
          `\`${data.runner.label}\` (${data.runner.cpuCount} CPU)`,
          data.generatedAt,
          data.settings.runs,
          data.settings.warmups,
        ],
      ],
    ),
    `[Actions](${data.commit.runUrl}) · [${data.commit.sha.slice(0, 12)}](${REPOSITORY}/commit/${data.commit.sha}) · [JSON](${REPOSITORY}/blob/main/${RESULT_PATH})`,
    `${t.metadata[4]}: ${["vize", "tsgo", "vueTsc", "verterTsc", "vue", "node"].map((key) => `${key}: \`${data.versions[key]}\``).join(" · ")}.`,
  ].join("\n\n");
}

export function summaryTable(data, locale, ids = SURFACE_ORDER) {
  return table(
    SNAPSHOT_LOCALES[locale].columns,
    ids.flatMap((id) => {
      const s = data.surfaces.find((surface) => surface.id === id);
      if (!s) return [];
      const baseline = getVariant(s, s.speedupBaselineId ?? s.baselineId);
      const single = getVariant(s, s.vizeSingleId);
      const max = getVariant(s, s.vizeMaxId);
      return [
        [
          surfaceLabel(s, locale),
          s.files.toLocaleString("en-US"),
          baseline?.label ?? "n/a",
          formatMs(baseline?.medianMs),
          single ? formatMs(single.medianMs) : "n/a",
          formatMs(max.medianMs),
          s.primarySpeedup == null ? "n/a" : `**${formatSpeedup(s.primarySpeedup)}**`,
        ],
      ];
    }),
  );
}

export function readmeSection(data) {
  const nuxt = data.surfaces.find((surface) => surface.id === "nuxt");
  const tools = {
    compile: "@vue/compiler-sfc",
    lint: "eslint-plugin-vue",
    fmt: "Prettier",
    check: "vue-tsc",
    vite: "@vitejs/plugin-vue",
    nuxt: "Nuxt compiler",
  };
  const rows = Object.entries(tools).map(([id, tool]) => {
    const s = data.surfaces.find((surface) => surface.id === id);
    return [
      surfaceLabel(s, "en"),
      s.files.toLocaleString("en-US"),
      tool,
      formatMs(getVariant(s, s.speedupBaselineId).medianMs),
      formatMs(getVariant(s, s.vizeMaxId).medianMs),
      `**${formatSpeedup(s.primarySpeedup).replace("x", "×")}**`,
    ];
  });
  return [
    "## Benchmarks",
    provenance(data, "en"),
    table(["Surface", "Files", "Existing tool", "Existing", "Vize", "Speedup"], rows),
    SNAPSHOT_LOCALES.en.note,
    `Nuxt measures the entire build pipeline, not isolated SFC compilation. Most build work is shared by both variants. Its ratio is ${formatSpeedup(nuxt.primarySpeedup)}; a ratio below 1 means Vize was slower in this run.`,
    "See the [Blacksmith benchmark snapshot](https://vizejs.dev/architecture/performance-blacksmith) for per-variant timings, diagnostic counts, rejected measurements and methodology.",
  ].join("\n\n");
}

export function snapshotPage(data, locale) {
  const t = SNAPSHOT_LOCALES[locale];
  if (locale === "en") {
    // Keep the detailed benchmark report's provenance, methods and raw samples.
    return renderDocument(data).replace("## Latest Result", `${t.note}\n\n## Latest Result`);
  }
  const lines = [
    "---",
    `title: ${t.title}`,
    "---",
    "",
    `# ${t.title}`,
    "",
    "<!-- Generated by tools/benchmarks/scripts/publish-snapshot.mjs. -->",
    "",
    provenance(data, locale),
    "",
    summaryTable(data, locale),
    "",
    t.note,
    "",
    `[${t.full}](/architecture/performance-blacksmith)`,
    "",
    `## ${t.diagnostics}`,
    "",
    ...renderEngineClassSections(data.surfaces, formatMs, diagnosticText(locale)),
    `## ${t.details}`,
    "",
  ];
  for (const surface of data.surfaces) {
    lines.push(
      `### ${surfaceLabel(surface, locale)}`,
      "",
      table(
        diagnosticText(locale).sampleColumns,
        surface.variants.map((variant) => [
          variant.label,
          variant.medianMs,
          variant.runs.join(", "),
        ]),
      ),
      "",
    );
  }
  return `${lines.join("\n")}\n`;
}

export function environmentSection(data, locale) {
  const t = SNAPSHOT_LOCALES[locale];
  const s = data.surfaces.find((surface) => surface.id === "compile");
  const pairs = [
    ["1T", s.baselineId, s.vizeSingleId],
    ["workers / max", "vue-compiler-sfc-workers", s.vizeMaxId],
    ["1T / max", s.baselineId, s.vizeMaxId],
  ];
  const rows = pairs.map(([label, baseline, vize]) => {
    const a = getVariant(s, baseline).medianMs;
    const b = getVariant(s, vize).medianMs;
    return [label, formatMs(a), formatMs(b), `**${(a / b).toFixed(1)}x**`];
  });
  return [
    `## ${t.environment}`,
    provenance(data, locale),
    t.history,
    `## ${t.compile}`,
    `${t.columns[1]}: **${s.files.toLocaleString("en-US")}** (${s.bytes.toLocaleString("en-US")} bytes).`,
    table(["", "@vue/compiler-sfc", "Vize", t.columns[6]], rows),
    `[${t.full}](./performance-blacksmith)`,
  ].join("\n\n");
}

