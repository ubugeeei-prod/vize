// The byte-custody registry: every first-party source whose current bytes are
// pinned by a digest somewhere in the tree.
//
//   node tools/commands/ci/byte-custody.ts --check
//   node tools/commands/ci/byte-custody.ts --write [--classes <pinned-classified.tsv>]
//
// A source is pinned when its sha256 or its git blob id is spelled anywhere in
// a tracked text file (other than this registry). Readability sweeps read the
// registry and leave `enforced` rows alone; `record-only` rows are pinned only
// by ledgers, so an edit leaves a stale record but breaks nothing.
//
// `--check` fails when a pinned source is missing from the registry (a new pin
// must register) or when an `enforced` file's bytes changed and nothing pins
// the new bytes (the edit skipped the custody procedure). A re-pinned file, a
// moved file, a file that is gone and a file no longer pinned are stale rows,
// which `--write` refreshes or drops. New rows are `enforced` until a person
// classifies them, which is the safe default for the sweeps.

import { execFileSync, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

import { isEntrypoint } from "../../support/command-runtime.ts";
import { gitTrackedFiles } from "../../support/git-tracked-files.ts";

export const registryPath = "tools/config/byte-custody.tsv";
// Digests per `git grep` call, which keeps the argument list well under the OS limit.
const patternsPerGrep = 500;

export type CustodyClass = "enforced" | "record-only";

export interface CustodyRow {
  readonly path: string;
  /** `sha256:<hex>` and/or `blob:<hex>`, whichever the tree pins. */
  readonly digests: readonly string[];
  readonly class: CustodyClass;
  /** Files that spell one of the digests. */
  readonly owners: readonly string[];
}

const sourceExtensions =
  /\.(?:rs|[cm]?[jt]s|[jt]sx|vue|pkl|sh|md|toml|json|css|scss|lua|scm|yml|yaml|html|el|vim|nix)$/u;
// Fixtures are oracles and `.github/` is generated from Pkl, so no sweep ever
// edits them; the registry covers hand-written sources only.
const fixturePath =
  /(?:^|\/)(?:_fixtures|__fixtures__|fixtures|snapshots|__snapshots__|expected)\/|^tests\/(?:differential|performance)\/|^(?:upstream|\.github)\//u;

const header = [
  "# Byte-custody registry: first-party sources whose current bytes a digest in the tree pins.",
  "# Generated by `node tools/commands/ci/byte-custody.ts --write`; edit only the class column.",
  "# enforced: a test reads the pin, so an edit needs the custody procedure (freeze or re-pin).",
  "# record-only: only a ledger carries the digest; an edit leaves a stale record.",
];

/** sha256 and git blob id of a file's bytes. */
export function digestsOf(bytes: Buffer): { sha256: string; blob: string } {
  return {
    sha256: createHash("sha256").update(bytes).digest("hex"),
    blob: createHash("sha1")
      .update(Buffer.concat([Buffer.from(`blob ${bytes.length}\0`), bytes]))
      .digest("hex"),
  };
}

function gitGrep(root: string, args: readonly string[]): string {
  const result = spawnSync(
    "git",
    [
      "-c",
      "grep.lineNumber=false",
      "-c",
      "grep.column=false",
      "grep",
      "--no-color",
      "-I",
      "-o",
      ...args,
      "--",
      ".",
      ":!upstream",
      `:!${registryPath}`,
    ],
    { cwd: root, encoding: "utf8", maxBuffer: 1 << 30 },
  );
  // Status 1 means "no match".
  if (result.status !== 0 && result.status !== 1)
    throw new Error(`git grep failed: ${result.stderr || result.error?.message}`);
  return result.stdout;
}

/** Every 40- and 64-digit lowercase hex run in tracked text files. */
export function spelledDigests(root: string): Set<string> {
  const found = new Set<string>();
  for (const match of gitGrep(root, ["-h", "-E", "[0-9a-f]{40,}"]).split("\n"))
    if (match.length === 40 || match.length === 64) found.add(match);
  return found;
}

/** Current digests of every first-party source, keyed by path. */
export function sourceDigests(root: string, tracked: readonly string[]) {
  const digests = new Map<string, { sha256: string; blob: string }>();
  for (const file of tracked) {
    if (!sourceExtensions.test(file) || fixturePath.test(file) || file === registryPath) continue;
    const absolute = path.join(root, file);
    const stat = fs.lstatSync(absolute, { throwIfNoEntry: false });
    if (!stat?.isFile()) continue;
    digests.set(file, digestsOf(fs.readFileSync(absolute)));
  }
  return digests;
}

/** Which tracked files spell each digest. */
function ownersOf(root: string, digests: readonly string[]): Map<string, Set<string>> {
  const owners = new Map<string, Set<string>>();
  for (let start = 0; start < digests.length; start += patternsPerGrep) {
    const patterns = digests
      .slice(start, start + patternsPerGrep)
      .flatMap((digest) => ["-e", digest]);
    for (const line of gitGrep(root, ["-F", ...patterns]).split("\n")) {
      const at = line.lastIndexOf(":");
      if (at < 0) continue;
      const digest = line.slice(at + 1);
      const set = owners.get(digest) ?? new Set<string>();
      set.add(line.slice(0, at));
      owners.set(digest, set);
    }
  }
  return owners;
}

export function parseRegistry(text: string): Map<string, CustodyRow> {
  const rows = new Map<string, CustodyRow>();
  for (const [index, line] of text.split("\n").entries()) {
    if (!line || line.startsWith("#") || line.startsWith("path\t")) continue;
    const [file, digests, kind, owners = ""] = line.split("\t");
    if (kind !== "enforced" && kind !== "record-only")
      throw new Error(`${registryPath}:${index + 1}: class must be enforced or record-only`);
    if (!/^(?:(?:sha256:[0-9a-f]{64}|blob:[0-9a-f]{40}),?)+$/u.test(digests ?? ""))
      throw new Error(`${registryPath}:${index + 1}: malformed digest list`);
    rows.set(file, {
      path: file,
      digests: digests.split(","),
      class: kind,
      owners: owners.split(" ").filter(Boolean),
    });
  }
  return rows;
}

export function renderRegistry(rows: Iterable<CustodyRow>): string {
  const body = [...rows]
    .sort((left, right) => (left.path < right.path ? -1 : 1))
    .map((row) => [row.path, row.digests.join(","), row.class, row.owners.join(" ")].join("\t"));
  return [...header, "path\tdigests\tclass\towners", ...body, ""].join("\n");
}

export interface CustodyReport {
  /** Failures: an unregistered pin or an enforced file whose bytes moved. */
  readonly problems: readonly string[];
  /** Registered sources whose reviewed bytes have changed without a replacement pin. */
  readonly unresolved: readonly string[];
  /** Rows `--write` would refresh or drop. */
  readonly stale: readonly string[];
  /** The registry as `--write` would leave it. */
  readonly next: readonly CustodyRow[];
}

// Historical admissions keep their original bytes after the live implementation moves on.
function hasFrozenCopy(root: string, row: CustodyRow): boolean {
  const fixture = `tests/_fixtures/byte-custody/${row.path}`;
  const file = path.join(root, fixture);
  if (!fs.lstatSync(file, { throwIfNoEntry: false })?.isFile()) return false;

  const entry = execFileSync(
    "git",
    [
      "--literal-pathspecs",
      "ls-files",
      "--format=%(objectmode) %(objectname) %(stage)",
      "--",
      fixture,
    ],
    { cwd: root, encoding: "utf8" },
  ).trimEnd();
  const regular = /^(?:100644|100755) ([0-9a-f]+) 0$/u.exec(entry);
  if (!regular) return false;
  const indexed = execFileSync("git", ["cat-file", "blob", regular[1]], {
    cwd: root,
    maxBuffer: 1 << 30,
  });
  if (!indexed.equals(fs.readFileSync(file))) return false;
  const { sha256, blob } = digestsOf(indexed);
  return row.digests.every((digest) => digest === `sha256:${sha256}` || digest === `blob:${blob}`);
}

/** Compare the registry with the tree. `classes` seeds the class of new rows. */
export function checkCustody(
  root: string,
  registry: ReadonlyMap<string, CustodyRow>,
  classes: ReadonlyMap<string, CustodyClass> = new Map(),
  options: { readonly owners?: boolean } = {},
): CustodyReport {
  const spelled = spelledDigests(root);
  const tracked = gitTrackedFiles(root);
  const current = sourceDigests(root, tracked);
  const pinned = new Map<string, string[]>();
  for (const [file, { sha256, blob }] of current) {
    const hits = [
      ...(spelled.has(sha256) ? [`sha256:${sha256}`] : []),
      ...(spelled.has(blob) ? [`blob:${blob}`] : []),
    ];
    if (hits.length) pinned.set(file, hits);
  }
  const problems: string[] = [];
  const unresolved: string[] = [];
  const stale: string[] = [];
  for (const row of registry.values()) {
    const now = current.get(row.path);
    if (!now) {
      stale.push(`${row.path}: gone; its row will be dropped`);
      continue;
    }
    const recorded = row.digests.map((digest) => digest.split(":")[1]);
    const unchanged = recorded.includes(now.sha256) || recorded.includes(now.blob);
    if (!unchanged && row.class === "enforced" && !pinned.has(row.path)) {
      if (hasFrozenCopy(root, row)) {
        stale.push(`${row.path}: its historical bytes are frozen; its live row will be dropped`);
        continue;
      }
      unresolved.push(row.path);
      problems.push(
        `${row.path}: its bytes are pinned by ${row.owners.join(", ") || "a test"} and changed. ` +
          "Release the pin through the custody procedure (freeze it under tests/_fixtures/byte-custody) " +
          `or re-pin it, then run --write to update ${registryPath}.`,
      );
    } else if (!unchanged || !pinned.has(row.path))
      stale.push(`${row.path}: ${unchanged ? "no longer pinned" : "re-pinned or edited"}`);
  }
  // A pinned file that moved keeps its gone row's class: the bytes are the same.
  const goneByDigest = new Map<string, CustodyRow | null>();
  for (const row of registry.values()) {
    if (current.has(row.path)) continue;
    for (const digest of row.digests) {
      goneByDigest.set(digest, goneByDigest.has(digest) ? null : row);
    }
  }
  const destinations = new Map<CustodyRow, string[]>();
  for (const [file, digests] of pinned) {
    if (registry.has(file)) continue;
    const matches = new Set(
      digests.map((digest) => goneByDigest.get(digest)).filter((row) => row !== undefined),
    );
    const [from] = matches;
    if (matches.size !== 1 || !from) continue;
    const paths = destinations.get(from) ?? [];
    paths.push(file);
    destinations.set(from, paths);
  }
  const movedFrom = new Map<string, CustodyRow>();
  for (const [from, paths] of destinations) {
    if (paths.length !== 1) continue;
    movedFrom.set(paths[0], from);
    stale.push(`${paths[0]}: moved from ${from.path}`);
  }
  const unregistered = [...pinned.keys()].filter(
    (file) => !registry.has(file) && !movedFrom.has(file),
  );
  // Finding owners greps the tree once more, so a clean `--check` skips it.
  const needOwners = options.owners === true || unregistered.length > 0;
  const owners = needOwners
    ? ownersOf(
        root,
        [...pinned.values()].flat().map((digest) => digest.split(":")[1]),
      )
    : new Map<string, Set<string>>();
  const ownerList = (file: string) =>
    needOwners
      ? [
          ...new Set(
            pinned.get(file)!.flatMap((digest) => [...(owners.get(digest.split(":")[1]) ?? [])]),
          ),
        ]
          .filter((owner) => owner !== file)
          .sort()
      : [...(registry.get(file)?.owners ?? [])];
  for (const file of unregistered)
    problems.push(
      `${file}: its current bytes are pinned by ${ownerList(file).join(", ")} but it is not in ` +
        `${registryPath}. Register it with --write, or pin a frozen copy under tests/_fixtures.`,
    );
  const next = [...pinned].map(([file, digests]) => {
    const previous = registry.get(file) ?? movedFrom.get(file);
    const unchangedRow = previous?.digests.join(",") === digests.join(",");
    return {
      path: file,
      digests,
      class:
        (unchangedRow ? previous?.class : undefined) ??
        classes.get(file) ??
        previous?.class ??
        "enforced",
      owners: ownerList(file),
    } satisfies CustodyRow;
  });
  return { problems, unresolved, stale, next };
}

function readClasses(file: string): Map<string, CustodyClass> {
  const classes = new Map<string, CustodyClass>();
  for (const line of fs.readFileSync(file, "utf8").split("\n").slice(1)) {
    const [entry, , kind] = line.split("\t");
    if (entry && kind) classes.set(entry, kind === "record-only" ? "record-only" : "enforced");
  }
  return classes;
}

export function main(argv: readonly string[], root = process.cwd()): number {
  const write = argv.includes("--write");
  const classesAt = argv.indexOf("--classes");
  const classes = classesAt >= 0 ? readClasses(argv[classesAt + 1]) : new Map();
  const file = path.join(root, registryPath);
  const registry = fs.existsSync(file) ? parseRegistry(fs.readFileSync(file, "utf8")) : new Map();
  const report = checkCustody(root, registry, classes, { owners: write });
  const enforced = report.next.filter((row) => row.class === "enforced").length;
  console.log(
    `byte custody: ${report.next.length} pinned sources (${enforced} enforced), ` +
      `${report.problems.length} problem(s), ${report.stale.length} stale row(s)`,
  );
  if (write) {
    if (report.unresolved.length) {
      for (const problem of report.problems) console.error(problem);
      return 1;
    }
    fs.writeFileSync(file, renderRegistry(report.next));
    console.log(`  wrote ${registryPath}`);
    return 0;
  }
  for (const note of report.stale.slice(0, 20)) console.log(`  stale: ${note}`);
  for (const problem of report.problems) console.error(`  ${problem}`);
  return report.problems.length ? 1 : 0;
}

if (isEntrypoint(import.meta.url)) process.exitCode = main(process.argv.slice(2));
