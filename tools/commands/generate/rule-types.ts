import fs from "node:fs";
import path from "node:path";

import { isEntrypoint, repositoryRoot, runEntrypoint } from "../../support/command-runtime.ts";

const lintRuleSnapshot =
  "crates/vize_patina/src/preset/snapshots/vize_patina__preset__tests__lint_preset_rule_membership.snap";
const lintRuleTypes = "npm/cli/src/types/rules.ts";

export function snapshotJsonBody(snapshot: string): string {
  const normalized = snapshot.replaceAll("\r\n", "\n");
  if (!normalized.startsWith("---\n")) {
    throw new Error("Invalid insta snapshot format for lint preset rule membership");
  }
  const delimiter = "\n---\n";
  const frontmatterEnd = normalized.indexOf(delimiter, 4);
  if (frontmatterEnd < 0) {
    throw new Error("Invalid insta snapshot format for lint preset rule membership");
  }
  return normalized.slice(frontmatterEnd + delimiter.length);
}

export function collectRuleNames(value: unknown): string[] {
  if (value === null || Array.isArray(value) || typeof value !== "object") {
    throw new Error("Expected lint preset snapshot root to be an object");
  }
  const names = new Set<string>();
  for (const [preset, entries] of Object.entries(value)) {
    if (!Array.isArray(entries)) throw new Error(`Expected ${preset} rules to be an array`);
    for (const entry of entries) {
      if (typeof entry !== "string") throw new Error(`Expected ${preset} rule name to be a string`);
      names.add(entry);
    }
  }
  return [...names].sort();
}

export function generateRuleTypes(ruleNames: readonly string[]): string {
  const entries = ruleNames.map((name) => `  ${JSON.stringify(name)},`).join("\n");
  return `// This file is generated by \`node tools/commands/generate/rule-types.ts\`.
// Do not edit it by hand.

import type { RuleSeverity } from "./generated.js";

export const LINT_RULE_NAMES = [
${entries}
] as const;

export type LintRuleName = (typeof LINT_RULE_NAMES)[number];

export type LintRulesConfig = Partial<Record<LintRuleName, RuleSeverity>>;
`;
}

export function generateRuleTypesFile(): number {
  const root = repositoryRoot(import.meta.url);
  const snapshot = fs.readFileSync(path.join(root, lintRuleSnapshot), "utf8");
  let parsed: unknown;
  try {
    parsed = JSON.parse(snapshotJsonBody(snapshot));
  } catch (error) {
    if (error instanceof SyntaxError) throw new Error("Failed to parse lint preset snapshot JSON");
    throw error;
  }
  const output = path.join(root, lintRuleTypes);
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, generateRuleTypes(collectRuleNames(parsed)));
  return 0;
}

if (isEntrypoint(import.meta.url)) runEntrypoint(generateRuleTypesFile);
