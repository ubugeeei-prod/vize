//! Generated per-file count ratchet for partial assertions in out-of-line test
//! modules. The file is written by `--write-ratchet` and never edited by hand;
//! a count may only go down.

use std::{collections::BTreeMap, fs, path::Path};

pub(super) const DEFAULT_PATH: &str = "docs/davinci/plan/assertion-ratchet.tsv";

const HEADER: &str = "# Generated by `rust-script tools/commands/davinci/assertion-lint.rs --write-ratchet`.\n\
# Partial assertions that already existed in out-of-line test modules, per file.\n\
# Counts may only go down: fix the assertion (exact oracles only), then regenerate.\n\
path\tcount\n";

pub(super) fn read(path: &Path) -> Result<BTreeMap<String, usize>, String> {
    if !path.exists() {
        return Ok(BTreeMap::new());
    }
    let text = fs::read_to_string(path)
        .map_err(|error| format!("cannot read {}: {error}", path.display()))?;
    let mut counts = BTreeMap::new();
    for (number, line) in text.lines().enumerate() {
        if line.starts_with('#') || line == "path\tcount" || line.is_empty() {
            continue;
        }
        let parsed = line
            .split_once('\t')
            .and_then(|(file, count)| Some((file.to_owned(), count.parse::<usize>().ok()?)));
        let Some((file, count)) = parsed else {
            return Err(format!(
                "{}:{}: expected `path<TAB>count`",
                path.display(),
                number + 1
            ));
        };
        if count == 0 || counts.insert(file, count).is_some() {
            return Err(format!(
                "{}:{}: counts must be positive and unique",
                path.display(),
                number + 1
            ));
        }
    }
    Ok(counts)
}

pub(super) fn write(path: &Path, counts: &BTreeMap<String, usize>) -> Result<(), String> {
    let mut text = HEADER.to_owned();
    for (file, count) in counts {
        text.push_str(&format!("{file}\t{count}\n"));
    }
    fs::write(path, text).map_err(|error| format!("cannot write {}: {error}", path.display()))
}
