import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const defaultPackageDir = path.resolve(scriptDir, "..");

function parseArguments(args) {
  const options = { generatedDir: undefined, packageDir: defaultPackageDir, profile: "ci" };
  for (let index = 0; index < args.length; index += 2) {
    const name = args[index];
    const value = args[index + 1];
    if (value == null) throw new Error(`${name} requires a value`);
    if (name === "--generated-dir") options.generatedDir = path.resolve(value);
    else if (name === "--package-dir") options.packageDir = path.resolve(value);
    else if (name === "--profile") options.profile = value;
    else throw new Error(`Unknown argument: ${name}`);
  }
  return options;
}

function nativeRuntimeExports(declaration) {
  return [
    ...declaration.matchAll(
      /^export declare (?:class|const|function) ([A-Za-z_$][A-Za-z0-9_$]*)\b/gm,
    ),
  ].map((match) => match[1]);
}

function loaderExports(loader, label) {
  const exports = [];
  for (const match of loader.matchAll(
    /^module\.exports\.([A-Za-z_$][A-Za-z0-9_$]*)\s*=\s*(?:nativeBinding\.)?([A-Za-z_$][A-Za-z0-9_$]*)\s*;?[ \t]*$/gm,
  )) {
    if (match[1] !== match[2]) {
      throw new Error(`${label} remaps ${match[1]} to ${match[2]}`);
    }
    exports.push(match[1]);
  }
  return exports;
}

function sortedUnique(values, label) {
  const sorted = [...values].sort((left, right) => left.localeCompare(right));
  for (let index = 1; index < sorted.length; index += 1) {
    if (sorted[index] === sorted[index - 1]) {
      throw new Error(`${label} contains duplicate export ${sorted[index]}`);
    }
  }
  return sorted;
}

function assertSameExports(actual, expected, label) {
  const actualJson = JSON.stringify(sortedUnique(actual, label));
  const expectedJson = JSON.stringify(sortedUnique(expected, "generated declaration"));
  if (actualJson !== expectedJson) {
    throw new Error(
      `${label} do not match generated declaration exports\nexpected ${expectedJson}\nactual   ${actualJson}`,
    );
  }
}

export function verifyGeneratedContract(packageDir, generatedDir) {
  const committedDeclaration = fs.readFileSync(path.join(packageDir, "index.d.ts"));
  const generatedDeclaration = fs.readFileSync(path.join(generatedDir, "index.d.ts"));
  if (!committedDeclaration.equals(generatedDeclaration)) {
    throw new Error(
      "generated index.d.ts differs byte-for-byte from npm/fresco-native/index.d.ts; regenerate and commit the NAPI declaration",
    );
  }

  const declaration = generatedDeclaration.toString("utf8");
  if (!declaration.includes("auto-generated by NAPI-RS")) {
    throw new Error("generated index.d.ts is missing the NAPI-RS generated header");
  }

  const declaredExports = nativeRuntimeExports(declaration);
  if (declaredExports.length === 0) {
    throw new Error("generated index.d.ts declares no native runtime exports");
  }
  assertSameExports(
    loaderExports(
      fs.readFileSync(path.join(generatedDir, "index.js"), "utf8"),
      "generated loader exports",
    ),
    declaredExports,
    "generated loader exports",
  );
  assertSameExports(
    loaderExports(
      fs.readFileSync(path.join(packageDir, "index.js"), "utf8"),
      "committed loader exports",
    ),
    declaredExports,
    "committed loader exports",
  );
}

function buildGeneratedContract(packageDir, profile) {
  if (!/^[A-Za-z0-9_-]+$/.test(profile)) throw new Error(`Invalid NAPI profile: ${profile}`);
  const generatedDir = fs.mkdtempSync(path.join(os.tmpdir(), "vize-fresco-native-generated-"));
  try {
    const command = process.platform === "win32" ? "vp.cmd" : "vp";
    const result = spawnSync(
      command,
      [
        "exec",
        "napi",
        "build",
        "--platform",
        "--profile",
        profile,
        "--manifest-path",
        "../../crates/vize_fresco/Cargo.toml",
        "-p",
        "vize_fresco",
        "--features",
        "napi",
        "--output-dir",
        generatedDir,
      ],
      {
        cwd: packageDir,
        encoding: "utf8",
        shell: process.platform === "win32",
      },
    );
    if (result.error != null) throw result.error;
    if (result.status !== 0) {
      throw new Error(`NAPI declaration build failed\n${result.stderr}\n${result.stdout}`.trim());
    }
    return generatedDir;
  } catch (error) {
    fs.rmSync(generatedDir, { recursive: true, force: true });
    throw error;
  }
}

const options = parseArguments(process.argv.slice(2));
let temporaryGeneratedDir;
try {
  const generatedDir =
    options.generatedDir ?? buildGeneratedContract(options.packageDir, options.profile);
  if (options.generatedDir == null) temporaryGeneratedDir = generatedDir;
  verifyGeneratedContract(options.packageDir, generatedDir);
  console.log("Fresco native declarations and loader exports match the Rust-generated contract.");
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
} finally {
  if (temporaryGeneratedDir != null) {
    fs.rmSync(temporaryGeneratedDir, { recursive: true, force: true });
  }
}
