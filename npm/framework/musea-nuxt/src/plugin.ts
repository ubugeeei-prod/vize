/**
 * Vite plugin that mocks Nuxt auto-imports and components for Musea galleries.
 */

import type { Plugin } from "vite";
import type { NuxtMuseaOptions } from "./types.js";

const VIRTUAL_IMPORTS_ID = "\0musea-nuxt:imports";
const VIRTUAL_NUXT_COMPONENTS_ID = "\0musea-nuxt:components";
const NUXT_IMPORT_IDS = new Set(["#imports", "#app", "#build", "nuxt/app"]);
const NUXT_COMPONENT_IDS = new Set([
  "#components",
  "#build/components",
  "nuxt/dist/app/components",
]);

export function createNuxtMuseaPlugin(options: NuxtMuseaOptions = {}): Plugin {
  return {
    name: "vite-plugin-musea-nuxt",
    enforce: "pre",

    resolveId(id) {
      // Resolve Nuxt component imports before the broad #build/* import alias.
      if (NUXT_COMPONENT_IDS.has(id)) {
        return VIRTUAL_NUXT_COMPONENTS_ID;
      }

      // Resolve #imports and related aliases
      if (NUXT_IMPORT_IDS.has(id) || id.startsWith("#app/") || id.startsWith("#build/")) {
        return VIRTUAL_IMPORTS_ID;
      }

      return null;
    },

    load(id) {
      if (id === VIRTUAL_IMPORTS_ID) {
        return generateImportsModule(options);
      }

      if (id === VIRTUAL_NUXT_COMPONENTS_ID) {
        return generateComponentsModule();
      }

      return null;
    },
  };
}

function generateImportsModule(options: NuxtMuseaOptions): string {
  const autoImportsUrl = JSON.stringify(new URL("./auto-imports.mjs", import.meta.url).href);
  const contextUrl = JSON.stringify(new URL("./context.mjs", import.meta.url).href);
  const configJson = JSON.stringify(options);

  return `
// Auto-generated by @vizejs/musea-nuxt
export * from ${autoImportsUrl};

// Configure mocks with provided options
import { configureNuxtMuseaMocks } from ${contextUrl};

const _config = ${configJson};
configureNuxtMuseaMocks(_config);
`;
}

function generateComponentsModule(): string {
  const componentsUrl = JSON.stringify(new URL("./mocks/components.mjs", import.meta.url).href);

  return `
// Auto-generated by @vizejs/musea-nuxt
export {
  NuxtLink,
  NuxtPage,
  ClientOnly,
  NuxtLayout,
  NuxtLoadingIndicator,
  NuxtErrorBoundary,
  NuxtRouteAnnouncer,
  NuxtWelcome,
  NuxtIsland,
  NuxtClientFallback,
  NuxtImg,
  NuxtPicture,
  RouterLink,
  RouterView,
} from ${componentsUrl};
`;
}
