import assert from "node:assert/strict";
import { format } from "oxfmt";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const helperRoot = "crates/vize_canon/src/virtual_ts/helpers";
const sources = [
  `${helperRoot}/declarations/core-types.d.ts.txt`,
  `${helperRoot}/declarations/vue3-types.d.ts.txt`,
  `${helperRoot}/declarations/prop-keys.d.ts.txt`,
  "crates/vize_canon/src/virtual_ts/component_prop_helpers.txt",
];
const contents = sources.map((source) => readFileSync(path.join(root, source), "utf8"));
const declarations = contents.join("\n");
const names = [...declarations.matchAll(/\btype\s+(__\w+)\b/gu)].map((match) => match[1]);
assert.equal(new Set(names).size, names.length, "shared helper aliases must be unique");
const rawGenerated = [
  "// Generated by npm/cli/scripts/generate-content-mapper-types.ts. Do not edit.",
  "// Context-free module types; no globals or compiler macros are declared here.",
  declarations,
  "export type {",
  ...names.map((name) => `  ${name},`),
  "};",
  "",
].join("\n");
const formatted = await format("content-mapper-types.d.ts", rawGenerated, { printWidth: 100 });
assert.deepEqual(formatted.errors, [], "generated helper types must parse");
const generated = formatted.code;
const imports = [
  "// Generated by npm/cli/scripts/generate-content-mapper-types.ts. Do not edit.",
  "import type {",
  ...names.map((name) => `  ${name},`),
  '} from "vize/content-mapper-helpers";',
  "",
].join("\n");
const outputs = new Map([
  ["npm/cli/generated/content-mapper-types.d.ts", generated],
  [`${helperRoot}/declarations/content-mapper-type-imports.d.ts.txt`, imports],
]);
for (const [relativePath, contents] of outputs) {
  const filePath = path.join(root, relativePath);
  if (process.argv.includes("--check")) {
    assert.equal(readFileSync(filePath, "utf8"), contents, `${relativePath} is stale`);
  } else {
    mkdirSync(path.dirname(filePath), { recursive: true });
    writeFileSync(filePath, contents);
  }
}
