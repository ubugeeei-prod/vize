interface OxContentModuleData {
  html: string;
  frontmatter: Record<string, unknown>;
  toc: unknown[];
}

function parseOxContentJsonExport(code: string, name: string): unknown {
  const match = code.match(new RegExp(`^export const ${name} = (.+);$`, "m"));
  if (!match) return undefined;
  try {
    return JSON.parse(match[1]);
  } catch {
    return undefined;
  }
}

function parseOxContentModule(code: string): OxContentModuleData | null {
  if (!code.includes("// Generated by @ox-content/vite-plugin")) return null;

  const html = parseOxContentJsonExport(code, "html");
  const frontmatter = parseOxContentJsonExport(code, "frontmatter");
  const toc = parseOxContentJsonExport(code, "toc");
  if (
    typeof html !== "string" ||
    !frontmatter ||
    typeof frontmatter !== "object" ||
    Array.isArray(frontmatter) ||
    !Array.isArray(toc)
  ) {
    return null;
  }
  return { html, frontmatter: frontmatter as Record<string, unknown>, toc };
}

function serializeInlineJson(value: unknown): string {
  return JSON.stringify(value)
    .replaceAll("<", "\\u003c")
    .replaceAll("\u2028", "\\u2028")
    .replaceAll("\u2029", "\\u2029");
}

function makeCodeFencesInert(html: string): string {
  return html.replace(/<pre\b[^>]*>\s*<code\b[^>]*>[\s\S]*?<\/code>\s*<\/pre>/gi, (block) =>
    block.replaceAll("{", "&#123;").replaceAll("}", "&#125;"),
  );
}

/** Convert the stable Ox Content module exports into an SFC for native compilation. */
export function oxContentModuleToSfc(code: string): string | null {
  const module = parseOxContentModule(code);
  if (!module) return null;

  const html = serializeInlineJson(module.html);
  const frontmatter = serializeInlineJson(module.frontmatter);
  const toc = serializeInlineJson(module.toc);
  const templateHtml = makeCodeFencesInert(module.html);
  return `<script>
export const html = ${html};
export const frontmatter = ${frontmatter};
export const toc = ${toc};
export default {
  setup() {
    return { frontmatter, toc };
  },
};
</script>

<template>
${templateHtml}</template>
`;
}
