import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import path from "node:path";

import { oxContentModuleToSfc } from "./markdown.ts";

const fixture = readFileSync(
  path.resolve(import.meta.dirname, "../test/fixtures/ox-content/Page.module.txt"),
  "utf8",
);
const source = oxContentModuleToSfc(fixture);

assert.ok(source, "Ox Content's generated module contract should produce an SFC");
assert.match(source, /export const frontmatter = \{"title":"Markdown fixture"/);
assert.match(source, /<h1 id="hello-frontmatter-title">Hello \{\{ frontmatter\.title \}\}<\/h1>/);
assert.match(source, /<table>/);
assert.match(source, /<section class="note">Inline HTML<\/section>/);
assert.match(
  source,
  /&#x3C;MyCard>&#123;&#123; mustStayInert &#125;&#125;&#x3C;\/MyCard>/,
  "Markdown code fences should remain escaped template text",
);
assert.equal(
  oxContentModuleToSfc('export const html = "<h1>untrusted</h1>";'),
  null,
  "Ordinary JavaScript modules must not be treated as Ox Content output",
);
assert.equal(
  oxContentModuleToSfc("// Generated by @ox-content/vite-plugin\nexport const html = nope;"),
  null,
  "Malformed Ox Content output must fail closed",
);

console.log("✅ Ox Content Markdown adapter tests passed!");
