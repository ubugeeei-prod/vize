//! Assemble prepared script and target fragments into one SFC module.
//!
//! The script lane rewrites its default export and supplies a component binding.
//! The target supplies hoists/cache declarations and either a declared render
//! function or an inline render expression. This module never parses or rewrites
//! JavaScript. It joins their writers, preserving every authored link, then
//! builds helper imports from the complete used-helper set. Runtime vocabulary
//! groups retain each export owner; target generation stays separate (#6840).

use crate::runtime::{Helper, Runtime, Vocabulary, vocabulary_for};
use crate::write::{Emitted, LinkSink, Writer};

/// The component field a declared render function implements.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RenderProperty {
    Render,
    SsrRender,
}

impl RenderProperty {
    const fn name(self) -> &'static str {
        match self {
            Self::Render => "render",
            Self::SsrRender => "ssrRender",
        }
    }
}

/// How the target's prepared render fragment joins the component.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RenderPlacement<'a> {
    /// No template; there must be no render fragment.
    None,
    /// A complete function declaration, attached to the component afterwards.
    /// `binding` is the generated JavaScript identifier of that declaration.
    Function {
        binding: &'a str,
        property: RenderProperty,
    },
    /// An expression inserted between the script lane's prepared fragments.
    /// The script lane owns `setup()`, `return` and all surrounding punctuation.
    Inline,
}

/// The authored script, already rewritten and linked by the script lane.
#[derive(Debug)]
pub enum ScriptPart<L: LinkSink> {
    /// A script defining the component binding, with no default export.
    Body(Writer<L>),
    /// Script output around the inline render expression. These fragments are
    /// concatenated without added whitespace, so `return` semantics are kept.
    Inline {
        before_render: Writer<L>,
        after_render: Writer<L>,
    },
}

/// Prepared pieces of one module, in their final emission order.
#[derive(Debug)]
pub struct ModuleParts<'a, L: LinkSink> {
    /// The vocabulary used by every fragment. Helpers are imported as `_name`.
    /// Names must be distinct JavaScript identifiers; fragments use that alias.
    pub vocabulary: &'a Vocabulary,
    /// Linked hoists and cache declarations, already generated by the target.
    pub prelude: Option<Writer<L>>,
    /// Rewritten script. Without one, assembly declares `const component = {}`.
    pub script: Option<ScriptPart<L>>,
    /// A complete declared function or an inline expression, as specified below.
    pub render: Option<Writer<L>>,
    pub placement: RenderPlacement<'a>,
    /// The generated JavaScript identifier defined by the script lane.
    pub component: &'a str,
    /// Validated Vue component scope identity, attached after complete fragments.
    pub scope_id: Option<ScopeId<'a>>,
}

impl<'a, L: LinkSink> ModuleParts<'a, L> {
    /// Start a module with the audited target vocabulary. Prepared fragments
    /// must use helper indices from this exact vocabulary.
    pub fn for_runtime(
        runtime: Runtime,
        version: &str,
        component: &'a str,
    ) -> Result<Self, AssemblyError> {
        Ok(Self {
            vocabulary: vocabulary_for(runtime, version)
                .ok_or(AssemblyError::UnsupportedRuntimeVersion)?,
            prelude: None,
            script: None,
            render: None,
            placement: RenderPlacement::None,
            component,
            scope_id: None,
        })
    }
}

