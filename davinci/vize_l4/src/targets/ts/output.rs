//! The checker document: text, one role per span link, and check-comment
//! ranges. Canon turns links and roles into its mapping rows without reading
//! the document again.

use alloc::vec::Vec;

use vize_l0::{Span, line_index::utf16_offset};

use super::MappingError;
use crate::write::{EmitDocument, Recorded, Writer};

/// The authored construct a link stands for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LinkRole {
    /// A run of authored script.
    Script,
    /// An authored expression, or a markup root in expression position.
    Expression,
    /// An authored name, such as an identifier read through a context.
    Name,
    /// A component tag name.
    ComponentTag,
    /// One attribute or binding of an owner.
    Attribute,
    /// One event listener of an owner.
    Event,
    /// A slot name or slot parameters.
    Slot,
    /// A directive name, value or argument.
    Directive,
    /// The component export.
    Export,
}

/// How offsets inside a link map back.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LinkMapping {
    /// Generated bytes are the authored bytes: offsets map one to one.
    Verbatim,
    /// Generated structure that owns an authored construct: any range inside
    /// it maps to the whole construct.
    Anchor,
}

/// The facts of one link, parallel to [`EmitDocument::links`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct LinkInfo {
    pub role: LinkRole,
    pub mapping: LinkMapping,
}

/// A check comment (`@vue-ignore`, `@vue-expect-error`, `@vue-skip`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DirectiveKind {
    Ignore,
    ExpectError,
    Skip,
}

/// The generated range a check comment governs, and the comment itself.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DirectiveRange {
    pub kind: DirectiveKind,
    pub generated: Span,
    pub comment: Span,
}

/// A projected checker document. It never declares a helper: every helper
/// it names is a shared ambient declaration ([`super::HELPERS`]).
#[derive(Debug)]
pub struct TsDocument {
    document: EmitDocument,
    facts: Vec<LinkInfo>,
    directives: Vec<DirectiveRange>,
}

impl TsDocument {
    /// The text and its span links, enclosing links before enclosed ones.
    #[must_use]
    pub fn document(&self) -> &EmitDocument {
        &self.document
    }

    /// One fact per link of [`Self::document`], in the same order.
    #[must_use]
    pub fn link_facts(&self) -> &[LinkInfo] {
        &self.facts
    }

    /// Check-comment ranges. JSX and TSX have none: their check comments
    /// are script comments that TypeScript reads in place.
    #[must_use]
    pub fn directives(&self) -> &[DirectiveRange] {
        &self.directives
    }

    /// Map a complete generated byte range through the innermost link that
    /// holds it. A range that partly overlaps a link crosses a boundary and
    /// never clamps; a point at a link's end belongs to that link.
    pub fn map_span(&self, generated: Span) -> Result<Span, MappingError> {
        if generated.start > generated.end
            || self
                .document
                .as_str()
                .get(generated.start as usize..generated.end as usize)
                .is_none()
        {
            return Err(MappingError::InvalidRange);
        }
        let mut innermost = None;
        for (link, fact) in self.document.links().iter().zip(&self.facts) {
            let span = link.generated;
            let crosses = (span.start < generated.start
                && generated.start < span.end
                && span.end < generated.end)
                || (generated.start < span.start
                    && span.start < generated.end
                    && generated.end < span.end);
            if crosses {
                return Err(MappingError::CrossesBoundary);
            }
            // Links are laminar and in pre-order, so the last holder is
            // the innermost one.
            if span.start <= generated.start && generated.end <= span.end {
                innermost = Some((link, fact.mapping));
            }
        }
        let (link, mapping) = innermost.ok_or(MappingError::GeneratedOnly)?;
        if mapping == LinkMapping::Anchor {
            return Ok(link.authored);
        }
        let start = link.authored.start + (generated.start - link.generated.start);
        Ok(Span::new(start, start + (generated.end - generated.start)))
    }

    /// Map TypeScript's UTF-16 offsets, rejecting mid-surrogate positions.
    pub fn map_utf16(&self, start: u32, length: u32) -> Result<Span, MappingError> {
        let end = start
            .checked_add(length)
            .ok_or(MappingError::InvalidUtf16Boundary)?;
        let text = self.document.as_str();
        let byte = |at| {
            utf16_offset(text, at)
                .and_then(|offset| u32::try_from(offset).ok())
                .ok_or(MappingError::InvalidUtf16Boundary)
        };
        self.map_span(Span::new(byte(start)?, byte(end)?))
    }
}

/// A recording writer that keeps one fact per link.
pub(super) struct Out {
    writer: Writer<Recorded>,
    facts: Vec<LinkInfo>,
}

impl Out {
    pub(super) fn with_capacity(capacity: usize) -> Self {
        Self {
            writer: Writer::with_capacity(capacity),
            facts: Vec::new(),
        }
    }

    #[cfg(feature = "component-projection")]
    pub(super) fn len(&self) -> usize {
        self.writer.len()
    }

    pub(super) fn push(&mut self, text: &str) {
        self.writer.push(text);
    }

    pub(super) fn push_char(&mut self, ch: char) {
        self.writer.push_char(ch);
    }

    /// Append authored bytes `text`, which are the source at `authored`.
    pub(super) fn verbatim(&mut self, text: &str, authored: Span, role: LinkRole) {
        self.writer.push_linked(text, authored);
        self.facts.push(LinkInfo {
            role,
            mapping: LinkMapping::Verbatim,
        });
    }

    #[cfg(feature = "component-projection")]
    pub(super) fn open_anchor(&mut self, role: LinkRole) -> crate::write::OpenLink {
        self.facts.push(LinkInfo {
            role,
            mapping: LinkMapping::Anchor,
        });
        self.writer.open_link()
    }

    #[cfg(feature = "component-projection")]
    pub(super) fn close_anchor(
        &mut self,
        open: crate::write::OpenLink,
        authored: Span,
    ) -> Result<(), super::ModuleProjectionError> {
        self.writer
            .close_link(open, authored)
            .ok_or(super::ModuleProjectionError::SourceTooLarge)
    }

    /// A rewritten leaf has one authored owner, including generated quotes.
    #[cfg(feature = "component-projection")]
    pub(super) fn rewritten(&mut self, text: &str, authored: Span, role: LinkRole) {
        self.writer.push_linked(text, authored);
        self.facts.push(LinkInfo {
            role,
            mapping: LinkMapping::Anchor,
        });
    }

    /// Append a finished fragment as one anchor unit owned by `authored`.
    pub(super) fn append_anchor(&mut self, fragment: Self, authored: Span, role: LinkRole) {
        self.writer.append_linked(fragment.writer, authored);
        self.facts.push(LinkInfo {
            role,
            mapping: LinkMapping::Anchor,
        });
        self.facts.extend(fragment.facts);
    }

    pub(super) fn finish(self) -> TsDocument {
        TsDocument {
            document: self.writer.finish().into_document(),
            facts: self.facts,
            directives: Vec::new(),
        }
    }
}
