//! Keep the existing public debug representation free of demand-only facts.

impl std::fmt::Debug for super::ScriptParseResult {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("ScriptParseResult")
            .field("bindings", &self.bindings)
            .field("unused_bindings", &self.unused_bindings)
            .field("macros", &self.macros)
            .field("reactivity", &self.reactivity)
            .field("race_conditions", &self.race_conditions)
            .field("types", &self.types)
            .field("type_exports", &self.type_exports)
            .field("invalid_exports", &self.invalid_exports)
            .field("scopes", &self.scopes)
            .field("provide_inject", &self.provide_inject)
            .field("inject_var_names", &self.inject_var_names)
            .field("inject_aliases", &self.inject_aliases)
            .field("provide_aliases", &self.provide_aliases)
            .field("reactivity_aliases", &self.reactivity_aliases)
            .field("reactive_value_origins", &self.reactive_value_origins)
            .field("reactive_getter_contexts", &self.reactive_getter_contexts)
            .field("setup_context", &self.setup_context)
            .field("is_non_setup_script", &self.is_non_setup_script)
            .field("skip_diagnostics", &self.skip_diagnostics)
            .field("import_statements", &self.import_statements)
            .field("re_exports", &self.re_exports)
            .field("re_export_forwards", &self.re_export_forwards)
            .field("component_registrations", &self.component_registrations)
            .field("component_shape", &self.component_shape)
            .field("binding_spans", &self.binding_spans)
            .field("import_sources", &self.import_sources)
            .field("module_value_bindings", &self.module_value_bindings)
            .field("type_export_typeof_refs", &self.type_export_typeof_refs)
            .field("type_export_type_refs", &self.type_export_type_refs)
            .field("runtime_object_literals", &self.runtime_object_literals)
            .field("options_descriptor", &self.options_descriptor)
            .field("inherit_attrs_disabled", &self.inherit_attrs_disabled)
            .field("reactive_assignment_root", &self.reactive_assignment_root)
            .finish()
    }
}
