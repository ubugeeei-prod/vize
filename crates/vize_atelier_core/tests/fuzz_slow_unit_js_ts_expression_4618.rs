fn decode_hex(hex: &str) -> Vec<u8> {
    let bytes = hex.as_bytes();
    assert_eq!(bytes.len() % 2, 0);
    bytes
        .chunks_exact(2)
        .map(|pair| {
            let high = char::from(pair[0]).to_digit(16).unwrap();
            let low = char::from(pair[1]).to_digit(16).unwrap();
            ((high << 4) | low) as u8
        })
        .collect()
}

#[test]
fn issue_4618_oom_reproducer_is_rejected_by_the_expression_guard() {
    let bytes = decode_hex(REPRODUCER_HEX);
    let source = std::str::from_utf8(&bytes).expect("fuzz input is valid UTF-8");

    assert_eq!(source.len(), 933);
    assert_eq!(source.matches('<').count(), 88);
    assert_eq!(source.matches('>').count(), 0);
    assert!(expression_has_balanced_delimiters(source));
    assert!(
        expression_nesting_depth(source) < source.matches('<').count(),
        "the per-segment depth score alone must not hide cumulative type-angle work"
    );
    assert!(!expression_is_safe_to_parse(source));
}
