use super::{EmitDocument, MapCoverage};
use oxc_sourcemap::SourceMap;
use serde::Deserialize;
use std::{collections::BTreeSet, fs::File, io::BufReader, path::Path};

#[derive(Deserialize)]
struct Case {
    id: String,
    history: String,
    entry: String,
    target: String,
    filename: String,
    source: String,
}

// Read the authored characters independently of the line indexes used by
// either serializer. The position between CR and LF is still on the first line.
fn position(text: &str, byte: u32) -> (u32, u32) {
    let byte = text.floor_char_boundary((byte as usize).min(text.len()));
    let (mut line, mut start) = (0, 0);
    for (at, terminator) in text.match_indices(['\r', '\n', '\u{2028}', '\u{2029}']) {
        let end = at + terminator.len();
        if end > byte {
            break;
        }
        if terminator == "\r" && text[end..].starts_with('\n') {
            continue;
        }
        line += 1;
        start = end;
    }
    (
        line,
        u32::try_from(text[start..byte].encode_utf16().count()).unwrap(),
    )
}

fn check_map(case: &Case, document: &EmitDocument, raw: &str) -> usize {
    let map = SourceMap::from_json_string(raw).unwrap();
    let id = &case.id;
    assert_eq!(map.get_file(), Some(case.filename.as_str()), "{id}");
    assert!(map.get_sources().eq([case.filename.as_str()]), "{id}");
    assert!(
        map.get_source_contents().eq([Some(case.source.as_str())]),
        "{id}"
    );

    let mut anchors: Vec<_> = document
        .links()
        .iter()
        .filter(|link| link.segment)
        .collect();
    anchors.sort_by_key(|link| link.generated.start);
    let tokens = map.get_source_view_tokens();
    assert_eq!(tokens.len(), anchors.len(), "{id}");
    let count = tokens.len();
    for (token, anchor) in tokens.zip(anchors) {
        assert_eq!(token.get_source_id(), Some(0), "{id}");
        assert_eq!(token.get_name(), anchor.name.as_deref(), "{id}");
        assert_eq!(
            (token.get_dst_line(), token.get_dst_col()),
            position(document.as_str(), anchor.generated.start),
            "{id}: generated byte {}",
            anchor.generated.start,
        );
        assert_eq!(
            (token.get_src_line(), token.get_src_col()),
            position(&case.source, anchor.authored.start),
            "{id}: authored byte {}",
            anchor.authored.start,
        );
    }
    count
}

#[test]
fn historical_dom_maps_keep_authored_paths_contents_and_utf16_positions() {
    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/compile-history/cases.json");
    let cases: Vec<Case> =
        serde_json::from_reader(BufReader::new(File::open(path).unwrap())).unwrap();
    let mut coverage = MapCoverage::default();
    let mut histories = BTreeSet::new();
    let mut filenames = BTreeSet::new();
    let mut segments = 0;
    for case in cases
        .iter()
        .filter(|case| case.entry == "sfc" && case.target == "dom")
    {
        // Keep the original path even when several historical revisions share it.
        coverage.compare(&case.filename, &case.source, None, |document, raw| {
            segments += check_map(case, document, raw);
        });
        histories.insert(&case.history);
        filenames.insert(&case.filename);
    }
    assert!(coverage.files > filenames.len() && filenames.len() > 1);
    assert!(coverage.stock_admitted > 0 && coverage.styles > 0);
    assert!(segments > 33 * coverage.files);
    println!(
        "historical_dom_maps cases={} histories={} filenames={} stock_admitted={} complete_js={} complete_css={} decoded_segments={segments}",
        coverage.files,
        histories.len(),
        filenames.len(),
        coverage.stock_admitted,
        coverage.modules,
        coverage.styles,
    );
}

#[test]
fn original_coordinates_handle_partial_utf8_and_crlf() {
    let text = "x\r\n🌸\r雪\u{2028}a\u{2029}";
    for (byte, expected) in [
        (2, (0, 2)),
        (3, (1, 0)),
        (6, (1, 0)),
        (7, (1, 2)),
        (8, (2, 0)),
        (12, (2, 1)),
        (14, (3, 0)),
        (15, (3, 1)),
        (18, (4, 0)),
    ] {
        assert_eq!(position(text, byte), expected, "byte {byte}");
    }
}
