/// Whether a character continues an identifier-like token.
fn is_word(ch: char) -> bool {
    ch.is_alphanumeric() || ch == '_' || ch == '$'
}

/// Offsets inside a verbatim run where a token starts: the run's first
/// non-whitespace character, every non-whitespace character after
/// whitespace, and every change between word and punctuation characters.
pub(crate) fn token_starts(generated: &str, run: Run) -> impl Iterator<Item = usize> + '_ {
    let text = &generated[run.out..run.out + run.len];
    let mut previous: Option<char> = None;
    text.char_indices().filter_map(move |(index, ch)| {
        let starts = !ch.is_whitespace()
            && match previous {
                None => true,
                Some(prev) => prev.is_whitespace() || is_word(prev) != is_word(ch) || !is_word(ch),
            };
        previous = Some(ch);
        starts.then_some(run.out + index)
    })
}

/// Serialize the provenance of `generated` into `.vue` offsets as a Source Map
/// v3 document naming `filename`, or `None` when no byte is accounted for.
pub(crate) fn build_module_map(
    generated: &str,
    provenance: Runs,
    filename: &str,
    source: &str,
) -> Option<String> {
    let provenance = provenance.verified(generated, source);
    let mut segments: Vec<(usize, usize)> = Vec::new();
    for &run in provenance.runs() {
        segments.extend(token_starts(generated, run).map(|out| (out, run.src + (out - run.out))));
    }
    segments.extend(provenance.points().iter().copied());
    if segments.is_empty() {
        return None;
    }
    // A verbatim token wins over a point anchor at the same generated byte.
    segments.sort_by_key(|&(out, _)| out);
    segments.dedup_by_key(|segment| segment.0);
    let mut builder = SourceMapBuilder::new();
    for (out, src) in segments {
        builder.add_raw(out, src as u32);
    }
    Some(builder.finish(generated, filename, source))
}

/// [`build_module_map`] as the `SfcCompileResult.map` field carries it.
pub(crate) fn module_map_value(
    generated: &str,
    provenance: Runs,
    filename: &str,
    source: &str,
) -> Option<serde_json::Value> {
    let json = build_module_map(generated, provenance, filename, source)?;
    serde_json::from_str(&json).ok()
}
