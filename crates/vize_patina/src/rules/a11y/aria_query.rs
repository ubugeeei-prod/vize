/// `dom.get(name)`: `Some(reserved)` for a known DOM element.
pub(crate) fn dom_element(name: &str) -> Option<bool> {
    match name {
        "base" | "col" | "colgroup" | "head" | "html" | "link" | "meta" | "noembed"
        | "noscript" | "param" | "picture" | "script" | "source" | "style" | "title" | "track" => {
            Some(true)
        }
        "a" | "abbr" | "acronym" | "address" | "applet" | "area" | "article" | "aside"
        | "audio" | "b" | "bdi" | "bdo" | "big" | "blink" | "blockquote" | "body" | "br"
        | "button" | "canvas" | "caption" | "center" | "cite" | "code" | "content" | "data"
        | "datalist" | "dd" | "del" | "details" | "dfn" | "dialog" | "dir" | "div" | "dl"
        | "dt" | "em" | "embed" | "fieldset" | "figcaption" | "figure" | "font" | "footer"
        | "form" | "frame" | "frameset" | "h1" | "h2" | "h3" | "h4" | "h5" | "h6" | "header"
        | "hgroup" | "hr" | "i" | "iframe" | "img" | "input" | "ins" | "kbd" | "keygen"
        | "label" | "legend" | "li" | "main" | "map" | "mark" | "marquee" | "menu" | "menuitem"
        | "meter" | "nav" | "object" | "ol" | "optgroup" | "option" | "output" | "p" | "pre"
        | "progress" | "q" | "rp" | "rt" | "rtc" | "ruby" | "s" | "samp" | "section" | "select"
        | "small" | "spacer" | "span" | "strike" | "strong" | "sub" | "summary" | "sup"
        | "table" | "tbody" | "td" | "textarea" | "tfoot" | "th" | "thead" | "time" | "tr"
        | "tt" | "u" | "ul" | "var" | "video" | "wbr" | "xmp" => Some(false),
        _ => None,
    }
}

