use serde_json::Value;
use vize_l0::{FxHashMap, String as CompactString};

/// One half-open generated range whose expression type the host needs.
pub(in crate::linter) struct ExpressionQuery {
    /// Generated byte offset of the expression start.
    pub start: u32,
    /// Generated byte offset of the expression end.
    pub end: u32,
    /// Load JSDoc `@deprecated` for the symbol at the start.
    pub symbols: bool,
    /// Load the first call signature's parameter type texts.
    pub signatures: bool,
    /// For a call-like node: argument positions whose resolved parameter types
    /// to load (0 loads none).
    pub call_positions: u32,
    /// For a function-like node: load its call signatures' return types.
    /// `Some(true)` reads them off the contextual type when there is one.
    pub function_returns: Option<bool>,
    /// Load the checker's contextual type at this node.
    pub contextual: bool,
    /// Load checker details (flags, constituents, constraint, references).
    pub detail: bool,
    /// Member paths into the type (destructuring patterns) whose types to load.
    pub paths: Vec<Vec<PathStep>>,
}

/// Facts a typescript-eslint rule reads off one expression.
#[derive(Clone)]
pub(in crate::linter) struct ExpressionFact {
    /// Rendered type texts. Empty when the checker has no type.
    pub type_texts: Vec<String>,
    /// Property names visible on the type.
    pub property_names: Vec<String>,
    /// Parameter type texts of the first call signature.
    pub parameter_type_texts: Vec<Vec<String>>,
    /// The symbol at this position carries `@deprecated`.
    pub deprecated: bool,
    /// Text of that `@deprecated` tag.
    pub deprecation_reason: String,
    /// Checker details of the type (flags, union parts, enum identity, constraint).
    pub detail: Option<Value>,
    /// Resolved-signature parameter types, for `ExpressionQuery::call_positions`.
    pub call: Option<Value>,
    /// Signature return types, for `ExpressionQuery::function_returns`.
    pub returns: Option<Value>,
    /// `(call, construct)` signature counts of a callee typed as `Function`.
    pub function_signatures: Option<(usize, usize)>,
    /// Contextual type for `ExpressionQuery::contextual`: `Some(Value::Null)`
    /// when the checker has none.
    pub contextual: Option<Value>,
    /// Details at `ExpressionQuery::paths`, aligned; `None` where a step fails.
    pub paths: Vec<Option<Value>>,
}

impl Default for ExpressionFact {
    fn default() -> Self {
        Self::empty()
    }
}

impl ExpressionFact {
    fn empty() -> Self {
        Self {
            type_texts: Vec::new(),
            property_names: Vec::new(),
            parameter_type_texts: Vec::new(),
            deprecated: false,
            deprecation_reason: String::new(),
            detail: None,
            call: None,
            returns: None,
            function_signatures: None,
            contextual: None,
            paths: Vec::new(),
        }
    }
}

impl CorsaTypeAwareSession {
    /// Resolve expression types for `queries`. Output order matches the input.
    pub(in crate::linter) fn expression_facts(
        &self,
        generated_source: &str,
        queries: &[ExpressionQuery],
    ) -> Result<Vec<ExpressionFact>, CompactString> {
        if queries.is_empty() {
            return Ok(Vec::new());
        }
        let rewritten = self.active_document().and_then(|document| {
            document
                .rewritten_source
                .as_deref()
                .map(|source| (source, &document.import_source_map))
        });
        let source = rewritten.map_or(generated_source, |(source, _)| source);
        let ranges = queries
            .iter()
            .map(|query| match rewritten {
                Some((_, map)) => {
                    let end = query.end.saturating_sub(1);
                    (
                        map.get_virtual_offset(query.start),
                        map.get_virtual_offset(end).saturating_add(1),
                    )
                }
                None => (query.start, query.end),
            })
            .collect::<Vec<_>>();
        block_on(load(
            &self.session,
            self.virtual_file_wire.as_str(),
            source,
            &ranges,
            queries,
        ))
        .map_err(|error| {
            vize_l0::cstr!(
                "Failed to query expression types: {}",
                error.to_compact_string()
            )
        })
    }
}

async fn load(
    session: &ProjectSession,
    file: &str,
    source: &str,
    ranges: &[(u32, u32)],
    queries: &[ExpressionQuery],
) -> corsa::Result<Vec<ExpressionFact>> {
    let utf16 = ranges
        .iter()
        .map(|&(start, end)| {
            (
                byte_offset_to_utf16_offset(source, start),
                byte_offset_to_utf16_offset(source, end),
            )
        })
        .collect::<Vec<_>>();
    let (responses, locations) = type_responses(session, file, source, &utf16).await?;
    if responses.len() != queries.len() {
        return Err(corsa::CorsaError::Protocol(
            "Incomplete expression type batch".into(),
        ));
    }
    let mut properties: FxHashMap<TypeHandle, Vec<String>> = FxHashMap::default();
    let mut signatures: FxHashMap<TypeHandle, Vec<Vec<String>>> = FxHashMap::default();
    let mut details = DetailCache::default();
    let mut facts = Vec::with_capacity(responses.len());
    for (index, (response, query)) in responses.into_iter().zip(queries).enumerate() {
        let location = locations
            .as_ref()
            .and_then(|locations| locations.get(index))
            .cloned();
        let Some(response) = response else {
            facts.push(ExpressionFact::empty());
            continue;
        };
        let type_texts = session
            .render_type_texts(&response)
            .await
            .unwrap_or_default()
            .into_iter()
            .map(|text| text.to_string())
            .collect::<Vec<_>>();
        let property_names = property_names(session, &response, &mut properties).await?;
        let (parameter_type_texts, function_signatures) = if query.signatures {
            (
                parameter_types(session, &response, &mut signatures).await?,
                signatures::function_signature_counts(
                    session,
                    &response,
                    &type_texts,
                    &property_names,
                )
                .await,
            )
        } else {
            (Vec::new(), None)
        };
        let detail = if query.detail {
            Some(type_detail(session, &response, &mut details).await?)
        } else {
            None
        };
        let call = match (&location, query.call_positions) {
            (Some(location), positions) if positions > 0 => {
                signatures::resolved_parameters(session, location.clone(), positions, &mut details)
                    .await?
            }
            _ => None,
        };
        let returns = match query.function_returns {
            Some(contextual) => Some(
                signatures::function_returns(
                    session,
                    &response,
                    location.clone().filter(|_| contextual),
                    &mut details,
                )
                .await?,
            ),
            None => None,
        };
        let contextual = match (&location, query.contextual) {
            (Some(location), true) => {
                Some(signatures::contextual_type(session, location.clone(), &mut details).await?)
            }
            _ => None,
        };
        let mut path_details = Vec::with_capacity(query.paths.len());
        for path in &query.paths {
            path_details.push(paths::detail_at(session, &response, path, &mut details).await?);
        }
        facts.push(ExpressionFact {
            type_texts,
            property_names,
            parameter_type_texts,
            deprecated: false,
            deprecation_reason: String::new(),
            detail,
            call,
            returns,
            function_signatures,
            contextual,
            paths: path_details,
        });
    }
    if queries.iter().any(|query| query.symbols) {
        apply_deprecated(session, file, &utf16, queries, &mut facts).await?;
    }
    Ok(facts)
}

type Responses = (Vec<Option<TypeResponse>>, Option<Vec<NodeHandle>>);

async fn type_responses(
    session: &ProjectSession,
    file: &str,
    source: &str,
    ranges: &[(u32, u32)],
) -> corsa::Result<Responses> {
    let usable = ranges.iter().all(|&(start, end)| start < end);
    if usable {
        if let Some((responses, locations)) = node_types(session, file, source, ranges).await? {
            return Ok((responses, Some(locations)));
        }
    }
    let positions = ranges.iter().map(|&(start, _)| start).collect();
    let responses = session
        .client()
        .get_types_at_positions(
            session.snapshot().handle.clone(),
            session.project_handle(),
            file,
            positions,
        )
        .await?;
    Ok((responses, None))
}

async fn node_types(
    session: &ProjectSession,
    file: &str,
    source: &str,
    ranges: &[(u32, u32)],
) -> corsa::Result<Option<(Vec<Option<TypeResponse>>, Vec<NodeHandle>)>> {
    let encoded = session
        .client()
        .get_source_file(
            session.snapshot().handle.clone(),
            session.project_handle(),
            file,
        )
        .await?;
    let Some(encoded) = encoded else {
        return Ok(None);
    };
    let locations = match checker_node_locations(encoded.as_bytes(), source, ranges) {
        Ok(locations) => locations,
        Err(_) => return Ok(None),
    };
    let responses = session
        .client()
        .get_type_at_locations(
            session.snapshot().handle.clone(),
            session.project_handle(),
            locations.clone(),
        )
        .await?;
    Ok(Some((responses, locations)))
}

async fn property_names(
    session: &ProjectSession,
    response: &TypeResponse,
    cache: &mut FxHashMap<TypeHandle, Vec<String>>,
) -> corsa::Result<Vec<String>> {
    if let Some(names) = cache.get(&response.id) {
        return Ok(names.clone());
    }
    let names = session
        .get_properties_of_type(response.id.clone())
        .await
        .unwrap_or_default()
        .into_iter()
        .map(|property| property.name)
        .collect::<Vec<_>>();
    cache.insert(response.id.clone(), names.clone());
    Ok(names)
}

async fn parameter_types(
    session: &ProjectSession,
    response: &TypeResponse,
    cache: &mut FxHashMap<TypeHandle, Vec<Vec<String>>>,
) -> corsa::Result<Vec<Vec<String>>> {
    if let Some(texts) = cache.get(&response.id) {
        return Ok(texts.clone());
    }
    let signatures = session
        .get_signatures_of_type(response.id.clone(), 0)
        .await
        .unwrap_or_default();
    let texts = signatures
        .into_iter()
        .next()
        .map(|signature| signature.parameter_type_texts)
        .unwrap_or_default();
    cache.insert(response.id.clone(), texts.clone());
    Ok(texts)
}

async fn apply_deprecated(
    session: &ProjectSession,
    file: &str,
    ranges: &[(u32, u32)],
    queries: &[ExpressionQuery],
    facts: &mut [ExpressionFact],
) -> corsa::Result<()> {
    let positions = ranges.iter().map(|&(start, _)| start).collect();
    let symbols = session
        .client()
        .get_symbols_at_positions(
            session.snapshot().handle.clone(),
            session.project_handle(),
            file,
            positions,
        )
        .await
        .unwrap_or_default();
    for (index, symbol) in symbols.into_iter().enumerate() {
        if !queries.get(index).is_some_and(|query| query.symbols) {
            continue;
        }
        let Some(symbol) = symbol else {
            continue;
        };
        let tags = session
            .client()
            .get_js_doc_tags(
                session.snapshot().handle.clone(),
                session.project_handle(),
                symbol.id,
            )
            .await
            .unwrap_or_default();
        let Some(tag) = tags.into_iter().find(|tag| tag.name == "deprecated") else {
            continue;
        };
        if let Some(fact) = facts.get_mut(index) {
            fact.deprecated = true;
            fact.deprecation_reason = tag.text;
        }
    }
    Ok(())
}

fn byte_offset_to_utf16_offset(source: &str, byte_offset: u32) -> u32 {
    let mut clamped = usize::min(byte_offset as usize, source.len());
    while clamped > 0 && !source.is_char_boundary(clamped) {
        clamped -= 1;
    }
    let prefix = source.get(..clamped).unwrap_or_default();
    prefix.encode_utf16().count() as u32
}
