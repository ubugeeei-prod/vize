/// One half-open generated range and the facts the enabled rules read there.
///
/// Every field but the range is a request; [`ExpressionQuery::merge`] folds
/// two requests for one range into one, so each range is answered once.
#[derive(Clone, Default)]
pub(in crate::linter) struct ExpressionQuery {
    /// Generated byte offset of the expression start.
    pub start: u32,
    /// Generated byte offset of the expression end.
    pub end: u32,
    /// Resolve the symbol at the start (whether it is declared in this file).
    pub symbols: bool,
    /// Load the first call signature's parameter type texts, and the
    /// call/construct signature counts of a `Function`-typed callee.
    pub signatures: bool,
    /// Promise and thenable facts to load for the expression type.
    pub promise: Facets,
    /// Load whether the contextual type is a void- or thenable-returning
    /// function.
    pub contextual_function: bool,
    /// For a callee: `(is_new, argument_count)` to resolve the argument
    /// positions that expect a void-returning function.
    pub void_arguments: Option<(bool, usize)>,
    /// For an object literal: method names to resolve against its
    /// contextual type.
    pub contextual_methods: Vec<CompactString>,
    /// For a class, an interface or an `implements` clause: member names to
    /// look up on the heritage types.
    pub heritage: Option<HeritageQuery>,
    /// For a call-like node: argument positions whose resolved parameter types
    /// to load (0 loads none).
    pub call_positions: u32,
    /// For a function-like node: load its call signatures' return types.
    /// `Some(true)` reads them off the contextual type when there is one.
    pub function_returns: Option<bool>,
    /// Load the checker's contextual type at this node, with its detail.
    pub contextual: bool,
    /// Load checker details (flags, constituents, constraint, references).
    pub detail: bool,
    /// Member paths into the type (destructuring patterns) whose types to load.
    pub paths: Vec<Vec<PathStep>>,
    /// Describe the constrained type as a `__typeShape` fact.
    pub shape: Option<ShapeRequest>,
    /// Type tree details to load (`detail::*`); `0` for none.
    pub tree: u8,
    /// Property names whose method declarations to describe on this type.
    pub member_methods: Vec<CompactString>,
    /// Load the union constituents of a type node's type.
    pub parts: bool,
    /// Probe whether a type node's type is (or holds) the empty object type.
    pub empty_object: bool,
}

impl ExpressionQuery {
    /// A query for `start..end` that asks only for the type texts.
    pub(in crate::linter) fn at(start: u32, end: u32) -> Self {
        Self {
            start,
            end,
            ..Self::default()
        }
    }

    /// Fold `other` (for the same range) into this query.
    pub(in crate::linter) fn merge(&mut self, other: Self) {
        self.symbols |= other.symbols;
        self.signatures |= other.signatures;
        self.promise = Facets(self.promise.0 | other.promise.0);
        self.contextual_function |= other.contextual_function;
        if self.void_arguments.is_none() {
            self.void_arguments = other.void_arguments;
        }
        for name in other.contextual_methods {
            if !self.contextual_methods.contains(&name) {
                self.contextual_methods.push(name);
            }
        }
        if self.heritage.is_none() {
            self.heritage = other.heritage;
        }
        self.call_positions = self.call_positions.max(other.call_positions);
        self.function_returns = match (self.function_returns, other.function_returns) {
            (Some(left), Some(right)) => Some(left || right),
            (left, right) => left.or(right),
        };
        self.contextual |= other.contextual;
        self.detail |= other.detail;
        if self.paths.is_empty() {
            self.paths = other.paths;
        }
        self.shape = match (self.shape.take(), other.shape) {
            (Some(mut left), Some(right)) => {
                left.merge(right);
                Some(left)
            }
            (left, right) => left.or(right),
        };
        self.tree |= other.tree;
        for name in other.member_methods {
            if !self.member_methods.contains(&name) {
                self.member_methods.push(name);
            }
        }
        self.parts |= other.parts;
        self.empty_object |= other.empty_object;
    }

    /// Resolve this range to the outermost node with the same span: a type
    /// reference and its name share one, and only the reference is typed.
    fn widens(&self) -> bool {
        self.parts || self.empty_object
    }
}

/// Heritage lookups for no-misused-promises' `checksVoidReturn.inheritedMethods`.
#[derive(Clone, Debug)]
pub(in crate::linter) struct HeritageQuery {
    /// Read the heritage types as the base types of the declared type
    /// (`extends`); otherwise the expression type is the heritage type.
    pub base_types: bool,
    /// Non-static member names of the class or interface.
    pub members: Vec<CompactString>,
}

/// Facts a typescript-eslint rule reads off one expression.
#[derive(Clone, Default)]
pub(in crate::linter) struct ExpressionFact {
    /// Rendered type texts. Empty when the checker has no type.
    pub type_texts: Vec<CompactString>,
    /// Property names visible on the type.
    pub property_names: Vec<CompactString>,
    /// Checker identity of the type (equal handles are the same type).
    pub type_id: Option<CompactString>,
    /// TypeScript 7 `TypeFlags` of the type. `None` when the checker has no type.
    pub type_flags: Option<u32>,
    /// Parameter type texts of the first call signature.
    pub parameter_type_texts: Vec<Vec<CompactString>>,
    /// `(call, construct)` signature counts of a callee typed as `Function`.
    pub function_signatures: Option<(usize, usize)>,
    /// The symbol at this position has a declaration in the queried file.
    /// `None` when no symbol resolves there.
    pub declared_in_file: Option<bool>,
    /// Promise and thenable facts of the expression type.
    pub promise: Option<PromiseFacts>,
    /// The contextual type is a void-returning function.
    pub contextual_void: Option<bool>,
    /// The contextual type is a thenable-returning function.
    pub contextual_thenable: Option<bool>,
    /// Argument positions that expect a void-returning function, and those
    /// that accept a thenable-returning one.
    pub void_arguments: Option<(Vec<usize>, Vec<usize>)>,
    /// Method name to "the contextual property is a void-returning function".
    pub contextual_members: Vec<(CompactString, bool)>,
    /// `(member, heritage type text)` for heritage members that return void.
    pub heritage_voids: Vec<(CompactString, CompactString)>,
    /// Checker details of the type (flags, union parts, enum identity, constraint).
    pub detail: Option<Value>,
    /// Resolved-signature parameter types, for `ExpressionQuery::call_positions`.
    pub call: Option<Value>,
    /// Signature return types, for `ExpressionQuery::function_returns`.
    pub returns: Option<Value>,
    /// Contextual type for `ExpressionQuery::contextual`: `Some(Value::Null)`
    /// when the checker has none.
    pub contextual: Option<Value>,
    /// Details at `ExpressionQuery::paths`, aligned; `None` where a step fails.
    pub paths: Vec<Option<Value>>,
    /// Constrained type flags, literal values and union parts (`__typeShape`).
    pub shape: Option<Value>,
    /// Recursive type tree (`__typeTree`), when the query asked for one.
    pub tree: Option<Value>,
    /// Method facts per requested member name, when the query asked for any.
    pub member_methods: Option<Value>,
    /// The type is the checker's `error` type. Set for `parts` queries.
    pub error_type: bool,
    /// Union constituents (`boolean` kept whole). Set for `parts` queries.
    pub type_parts: Vec<TypePartFact>,
    /// The type is, or holds, the empty object type. Set for `empty_object`.
    pub empty_object: Option<bool>,
}

impl CorsaTypeAwareSession {
    /// Resolve the facts `queries` ask for, plus the checker relations of
    /// `request`, in one node-location and type batch. Output order matches
    /// `queries`.
    pub(in crate::linter) fn expression_facts(
        &self,
        generated_source: &str,
        queries: &[ExpressionQuery],
        request: Option<&RelationRequest>,
    ) -> Result<(Vec<ExpressionFact>, Option<RelationReply>), CompactString> {
        let rewritten = self.active_document().and_then(|document| {
            document
                .rewritten_source
                .as_deref()
                .map(|source| (source, &document.import_source_map))
        });
        let source = rewritten.map_or(generated_source, |(source, _)| source);
        let to_virtual = |(start, end): (u32, u32)| match rewritten {
            Some((_, map)) => (
                map.get_virtual_offset(start),
                map.get_virtual_offset(end.saturating_sub(1))
                    .saturating_add(1),
            ),
            None => (start, end),
        };
        let translate = |span: (u32, u32)| {
            let (start, end) = to_virtual(span);
            (
                byte_offset_to_utf16_offset(source, start),
                byte_offset_to_utf16_offset(source, end),
            )
        };
        let extra = request.map_or_else(Vec::new, |request| relations::spans(request, &translate));
        if queries.is_empty() && extra.is_empty() {
            return Ok((Vec::new(), request.map(RelationReply::empty)));
        }
        let ranges = queries
            .iter()
            .map(|query| translate((query.start, query.end)))
            .collect::<Vec<_>>();
        let file = self.virtual_file_wire.as_str();
        block_on(async {
            let memo = CheckerMemo::new(&self.session);
            let (facts, located) = load(&memo, file, source, &ranges, queries, &extra).await?;
            let reply = match (request, located) {
                (Some(request), Some((spans, handles, types))) => {
                    Some(relations::answer(&memo, request, &translate, spans, handles, types).await)
                }
                (Some(request), None) => Some(RelationReply::empty(request)),
                (None, _) => None,
            };
            Ok::<_, corsa::CorsaError>((facts, reply))
        })
        .map_err(|error| {
            vize_l0::cstr!(
                "Failed to query expression types: {}",
                error.to_compact_string()
            )
        })
    }
}

/// Node-located spans with their handles and types, in batch order.
type Located = (
    Vec<(u32, u32)>,
    Vec<Option<NodeHandle>>,
    Vec<Option<TypeResponse>>,
);

/// Query ranges are UTF-16 offsets into `source`; `extra` are more UTF-16
/// spans (relation operands) typed in the same batch.
async fn load(
    memo: &CheckerMemo<'_>,
    file: &str,
    source: &str,
    ranges: &[(u32, u32)],
    queries: &[ExpressionQuery],
    extra: &[(u32, u32)],
) -> corsa::Result<(Vec<ExpressionFact>, Option<Located>)> {
    let session = memo.session();
    let mut spans = ranges.to_vec();
    spans.extend_from_slice(extra);
    let mut widen = queries
        .iter()
        .map(ExpressionQuery::widens)
        .collect::<Vec<_>>();
    widen.resize(spans.len(), false);
    let (responses, handles) = type_responses(memo, file, source, &spans, &widen).await?;
    if responses.len() != spans.len() {
        return Err(corsa::CorsaError::Protocol(
            "Incomplete expression type batch".into(),
        ));
    }
    let located = handles.map(|handles| (spans.clone(), handles, responses.clone()));
    let mut responses = responses;
    responses.truncate(queries.len());
    let handles = located
        .as_ref()
        .map(|(_, handles, _)| handles.get(..queries.len()).unwrap_or_default());
    let by_range = queries
        .iter()
        .enumerate()
        .map(|(index, query)| ((query.start, query.end), index))
        .collect::<FxHashMap<_, _>>();
    let response_at = |range: &(u32, u32)| {
        by_range
            .get(range)
            .and_then(|&index| responses.get(index))
            .and_then(Option::as_ref)
    };
    let mut details = DetailCache::default();
    let mut shapes = ShapeCache::default();
    let mut trees = shape::Shapes::new(memo, file);
    let mut promises = PromiseChecker::new(memo);
    let mut probe = TypeNodeProbe::new(
        memo,
        queries.iter().any(|query| query.parts),
        queries.iter().any(|query| query.empty_object),
    )
    .await?;
    let mut facts = Vec::with_capacity(queries.len());
    for (index, query) in queries.iter().enumerate() {
        let location = handles
            .and_then(|handles| handles.get(index))
            .and_then(Option::as_ref);
        let Some(response) = responses.get(index).and_then(Option::as_ref) else {
            facts.push(ExpressionFact::default());
            continue;
        };
        let mut fact = ExpressionFact {
            type_texts: memo.type_texts(response).await,
            property_names: memo.property_names(response).await,
            type_id: Some(CompactString::from(response.id.as_str())),
            type_flags: Some(response.flags),
            ..ExpressionFact::default()
        };
        if query.signatures {
            fact.parameter_type_texts = parameter_types(memo, response).await;
            fact.function_signatures = signatures::function_signature_counts(
                memo,
                response,
                &fact.type_texts,
                &fact.property_names,
            )
            .await;
        }
        // Each fact family below fails on its own: a query the checker
        // cannot answer leaves that family unset for this expression only.
        if query.detail {
            fact.detail = local(type_detail(memo, response, &mut details).await)?;
        }
        if let Some(location) = location {
            if query.call_positions > 0 {
                fact.call = local(
                    signatures::resolved_parameters(
                        memo,
                        location.clone(),
                        query.call_positions,
                        &mut details,
                    )
                    .await,
                )?
                .flatten();
            }
            if query.contextual {
                fact.contextual =
                    local(signatures::contextual_type(memo, location.clone(), &mut details).await)?;
            }
        }
        if let Some(contextual) = query.function_returns {
            fact.returns = local(
                signatures::function_returns(
                    memo,
                    response,
                    location.filter(|_| contextual).cloned(),
                    &mut details,
                )
                .await,
            )?;
        }
        for path in &query.paths {
            let detail = local(paths::detail_at(memo, response, path, &mut details).await)?;
            fact.paths.push(detail.flatten());
        }
        if let Some(request) = &query.shape {
            let key = request.keys_from.as_ref().and_then(response_at);
            let mut described =
                local(describe_shape(memo, response, request, key, &mut shapes).await)?;
            if let Some(map) = described.as_mut().and_then(Value::as_object_mut)
                && let Some(call) = &request.predicate
                && let Some(callee) = response_at(&call.callee)
            {
                let arguments = call.arguments.iter().map(response_at).collect::<Vec<_>>();
                if let Some(predicate) =
                    local(predicate_fact(memo, callee, &arguments, &mut shapes).await)?.flatten()
                {
                    map.insert("predicate".into(), predicate);
                }
            }
            fact.shape = described;
        }
        if query.tree != 0 {
            fact.tree = Some(trees.shape(response, query.tree).await);
        }
        if !query.member_methods.is_empty() {
            fact.member_methods = Some(trees.member_methods(response, &query.member_methods).await);
        }
        if query.parts {
            fact.type_parts = local(probe.parts(memo, response).await)?.unwrap_or_default();
            fact.error_type = probe.is_error(response);
        }
        if query.empty_object {
            fact.empty_object = local(probe.contains_empty_object(memo, response).await)?;
        }
        // Promise facts refine the rules; a failed walk leaves them unset
        // rather than failing the whole lint.
        let _ = promise_fact(memo, &mut promises, response, location, query, &mut fact).await;
        facts.push(fact);
    }
    if queries.iter().any(|query| query.symbols) {
        apply_symbols(session, file, ranges, queries, &mut facts).await;
    }
    Ok((facts, located))
}

fn byte_offset_to_utf16_offset(source: &str, byte_offset: u32) -> u32 {
    let mut clamped = usize::min(byte_offset as usize, source.len());
    while clamped > 0 && !source.is_char_boundary(clamped) {
        clamped -= 1;
    }
    let prefix = source.get(..clamped).unwrap_or_default();
    prefix.encode_utf16().count() as u32
}
