//! Expression types from checker syntax nodes.
//! Symbol types at a caret describe the callee, not the expression.
//!
//! One pass per script: one source-file fetch, one node-location batch and one
//! type batch for every distinct range, then the fact families each query asks
//! for, all answered through one [`CheckerMemo`] so a type's constituents,
//! constraint or contextual type are fetched once whichever family asks.
