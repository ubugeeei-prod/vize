pub(super) fn static_rule(corsa_name: &str) -> Option<&'static str> {
    RULES
        .iter()
        .map(|(name, _)| *name)
        .find(|name| name.strip_prefix("type/") == Some(corsa_name))
}

pub(super) fn corsa_name(vize_name: &'static str) -> Option<&'static str> {
    let bare = vize_name.strip_prefix("type/")?;
    if bare == "no-generated-empty-object-type" {
        return None;
    }
    Some(bare)
}
