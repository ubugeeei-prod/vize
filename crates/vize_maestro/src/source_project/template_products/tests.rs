use super::*;
use crate::{runtime::block_on, source_project::SourceSnapshotCache};
use std::sync::atomic::{AtomicBool, Ordering};
use tower_lsp::lsp_types::{TextDocumentContentChangeEvent, Url};
use vize_l0::config::{VueDialect, VueVersion};

const SOURCE: &str = "<script setup>const fj=1;const 作者=2;const unused=0;</script>\r\n<template><p :title='&fjlig;'>{{ 作者 + fj }}</p></template>";

fn options() -> DescriptorOptions {
    DescriptorOptions {
        version: VueVersion::V3,
        dialect: VueDialect::Vue,
        template: Default::default(),
    }
}

fn open() -> (DocumentStore, SourceSnapshotCache, Url) {
    let documents = DocumentStore::new();
    let uri = Url::parse("file:///project/Example雪.vue").unwrap();
    documents.open(uri.clone(), SOURCE.into(), 1, "vue".into());
    (documents, SourceSnapshotCache::default(), uri)
}

#[test]
fn original_buffer_products_keep_complete_public_script_bytes_uris_and_mappings() {
    let (documents, cache, uri) = open();
    let (query, _) = cache.begin_query(&documents, &uri).unwrap();
    let source = query.snapshot().source().to_owned();
    let result = block_on(query.run_native_template_products(&documents, options())).unwrap();
    let products = result.publish(&documents, |products| products).unwrap();
    assert_eq!(products.checker.as_str(), "fj\n作者 + fj");
    assert_eq!(products.checker.links().len(), 2);
    assert_eq!(products.expressions.len(), 2);
    assert_eq!(
        products.checker.links()[0].authored.slice(&source),
        "&fjlig;"
    );
    let script = products.script_setup.unwrap();
    let descriptor = vize_atelier_sfc::parse_sfc(&source, Default::default()).unwrap();
    let expected = VirtualCodeGenerator::new()
        .generate(&descriptor, uri.as_str())
        .script_setup
        .unwrap();
    assert_eq!(
        (
            &script.uri,
            &script.content,
            script.language,
            &script.source_map
        ),
        (
            &expected.uri,
            &expected.content,
            expected.language,
            &expected.source_map
        )
    );
    assert_eq!(
        script.content,
        concat!(
            "// Virtual TypeScript for <script setup> with exports\n",
            "// Generated by vize_maestro\n\n",
            "const fj=1;const 作者=2;const unused=0;\n\n",
            "// Exports for template\nexport { fj, 作者 };\n"
        )
    );
}

#[test]
fn edits_and_equal_version_reopen_cannot_publish_prepared_original_products() {
    for reopen in [false, true] {
        let (documents, cache, uri) = open();
        let (query, _) = cache.begin_query(&documents, &uri).unwrap();
        let result = block_on(query.run_native_template_products(&documents, options())).unwrap();
        if reopen {
            documents.close(&uri);
            documents.open(uri.clone(), SOURCE.into(), 1, "vue".into());
        } else {
            assert!(documents.apply_changes(
                &uri,
                vec![TextDocumentContentChangeEvent {
                    range: None,
                    range_length: None,
                    text: SOURCE.replace("作者=2", "作者=3")
                }],
                2
            ));
        }
        let published = AtomicBool::new(false);
        assert!(matches!(
            result.publish(&documents, |_| published.store(true, Ordering::Relaxed)),
            Err(SnapshotRefusal::Superseded)
        ));
        assert!(!published.load(Ordering::Relaxed));
    }
}

#[test]
fn cancellation_before_construction_or_after_preparation_never_publishes_products() {
    let (documents, cache, uri) = open();
    let (query, cancel) = cache.begin_query(&documents, &uri).unwrap();
    cancel.abort();
    assert!(matches!(
        block_on(query.run_native_template_products(&documents, options())),
        Err(NativeTemplateQueryError::Host(SnapshotRefusal::Cancelled))
    ));
    let (query, cancel) = cache.begin_query(&documents, &uri).unwrap();
    let result = block_on(query.run_native_template_products(&documents, options())).unwrap();
    cancel.abort();
    let published = AtomicBool::new(false);
    assert!(matches!(
        result.publish(&documents, |_| published.store(true, Ordering::Relaxed)),
        Err(SnapshotRefusal::Cancelled)
    ));
    assert!(!published.load(Ordering::Relaxed));
}

#[test]
fn closing_or_renaming_the_original_document_invalidates_prepared_products() {
    for rename in [false, true] {
        let (documents, cache, uri) = open();
        let (query, _) = cache.begin_query(&documents, &uri).unwrap();
        let result = block_on(query.run_native_template_products(&documents, options())).unwrap();
        if rename {
            assert!(documents.rename(&uri, Url::parse("file:///project/Renamed.vue").unwrap()));
        } else {
            documents.close(&uri);
        }
        let published = AtomicBool::new(false);
        assert!(matches!(
            result.publish(&documents, |_| published.store(true, Ordering::Relaxed)),
            Err(SnapshotRefusal::MissingDocument)
        ));
        assert!(!published.load(Ordering::Relaxed));
    }
}

#[test]
fn unsupported_original_files_and_foreign_languages_have_explicit_refusals() {
    let (documents, cache, uri) = open();
    assert!(documents.apply_changes(
        &uri,
        vec![TextDocumentContentChangeEvent {
            range: None,
            range_length: None,
            text: "<template><p>".into()
        }],
        2
    ));
    let (query, _) = cache.begin_query(&documents, &uri).unwrap();
    let Err(NativeTemplateQueryError::File(issues)) =
        block_on(query.run_native_template_products(&documents, options()))
    else {
        panic!("an incomplete original file must refuse")
    };
    assert!(!issues.is_empty());
    documents.close(&uri);
    documents.open(uri.clone(), SOURCE.into(), 3, "typescript".into());
    let (query, _) = cache.begin_query(&documents, &uri).unwrap();
    assert!(matches!(
        block_on(query.run_native_template_products(&documents, options())),
        Err(NativeTemplateQueryError::Language)
    ));
}
