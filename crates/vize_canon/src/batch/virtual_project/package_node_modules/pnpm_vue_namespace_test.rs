use crate::batch::runtime_deps::with_test_env_overrides;

use super::{case_dir, materialize_package_node_modules, package_node_modules_links};

#[test]
fn pnpm_vue_namespace_without_runtime_core_keeps_direct_vue_package_links() {
    let root = case_dir("pnpm-vue-namespace");
    let namespace = root.join("store/vue/node_modules/@vue");
    let vue = root.join("store/vue/node_modules/vue");
    std::fs::create_dir_all(&vue).unwrap();
    for name in ["runtime-dom", "shared", "compiler-dom", "compiler-sfc"] {
        std::fs::create_dir_all(namespace.join(name)).unwrap();
        std::fs::create_dir_all(root.join("node_modules/@vue").join(name)).unwrap();
        std::fs::write(
            root.join("node_modules/@vue").join(name).join("index.d.ts"),
            "export declare const available: true;",
        )
        .unwrap();
    }
    let virtual_root = crate::batch::project_virtual_root(&root);
    let file = virtual_root.join("src/main.ts");
    with_test_env_overrides(
        &[
            ("VIZE_VUE_PACKAGE", Some(vue.as_path())),
            ("VIZE_VUE_NAMESPACE_PACKAGE", Some(namespace.as_path())),
            ("VIZE_VUE_RUNTIME_DOM_PACKAGE", None),
            ("VIZE_RUNTIME_NODE_MODULES", None),
            (
                "VIZE_TEST_WORKSPACE_NODE_MODULES",
                Some(std::path::Path::new("__none__")),
            ),
        ],
        || {
            let links =
                package_node_modules_links(&root, &virtual_root, [file.as_path()].into_iter());
            for name in ["shared", "compiler-dom", "compiler-sfc"] {
                assert!(
                    links.iter().any(|link| link.virtual_dir
                        == virtual_root.join("node_modules/@vue").join(name)),
                    "the direct pnpm dependency @vue/{name} must stay visible: {links:#?}"
                );
            }
            crate::batch::runtime_deps::materialize_runtime_dependencies(&root, &virtual_root, &[])
                .unwrap();
            materialize_package_node_modules(&links);
            for name in ["shared", "compiler-dom", "compiler-sfc"] {
                assert_eq!(
                    std::fs::read_to_string(
                        virtual_root
                            .join("node_modules/@vue")
                            .join(name)
                            .join("index.d.ts")
                    )
                    .unwrap(),
                    "export declare const available: true;"
                );
            }
        },
    );
    let _ = std::fs::remove_dir_all(&root);
}
