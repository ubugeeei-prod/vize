//! Sorted path index so package membership is a range, not a scan of every file.

use std::path::Path;

use super::super::canonical_paths::record_membership_probes;

/// Materialized files ordered so every descendant of a directory is one range.
pub(in super::super) struct MaterializedPrefixIndex<'a> {
    files: Vec<&'a Path>,
}

impl<'a> MaterializedPrefixIndex<'a> {
    pub(in super::super) fn from_files(files: impl IntoIterator<Item = &'a Path>) -> Self {
        let mut files: Vec<&Path> = files.into_iter().collect();
        files.sort_unstable();
        files.dedup();
        Self { files }
    }

    /// Files under `prefix`, including `prefix` itself.
    ///
    /// Component order places that set in `[prefix, successor)`. Binary search
    /// finds the bounds; it does not compare `prefix` with every file.
    pub(in super::super) fn descendants(&self, prefix: &Path) -> &[&'a Path] {
        let mut probes = 0usize;
        let start = self.files.partition_point(|path| {
            probes += 1;
            *path < prefix
        });
        let tail = self.files.get(start..).unwrap_or(&[]);
        let matched = tail.partition_point(|path| {
            probes += 1;
            path.starts_with(prefix)
        });
        record_membership_probes(probes);
        self.files
            .get(start..start.saturating_add(matched))
            .unwrap_or(&[])
    }
}
