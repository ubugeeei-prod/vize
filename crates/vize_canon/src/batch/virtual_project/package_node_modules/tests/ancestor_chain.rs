use std::path::Path;

use super::super::{PackageNodeModulesLink, package_node_modules_links};
use super::case_dir;

/// TypeScript takes each bare specifier and `types` entry from the nearest
/// ancestor `node_modules` that has it. The flattened mirror root keeps that
/// order: a package installed only above the app still links, a duplicate name
/// links the nearest install, and a nearer partial `@types` scope does not hide
/// a farther package.
#[test]
fn the_mirror_root_keeps_the_nearest_ancestor_install_of_each_name() {
    let root = case_dir("ancestor-chain");
    let project = root.join("apps/web");
    for entry in [
        "@types/far-globals",
        "@types/shared-globals",
        "above-only",
        "dup",
    ] {
        std::fs::create_dir_all(root.join("node_modules").join(entry)).unwrap();
    }
    for entry in ["@types/shared-globals", "dup"] {
        std::fs::create_dir_all(project.join("node_modules").join(entry)).unwrap();
    }
    std::fs::create_dir_all(project.join("src")).unwrap();
    let virtual_root = crate::batch::project_virtual_root(&project);
    let file = virtual_root.join("src/main.ts");

    let links = package_node_modules_links(&project, &virtual_root, [file.as_path()].into_iter());

    let link = |name: &str, install: &Path| PackageNodeModulesLink {
        virtual_dir: virtual_root.join("node_modules").join(name),
        real_dir: install.join("node_modules").join(name),
    };
    assert_eq!(
        links,
        vec![
            link("@types/shared-globals", &project),
            link("dup", &project),
            link("@types/far-globals", &root),
            link("above-only", &root),
        ]
    );
    let _ = std::fs::remove_dir_all(&root);
}
