//! Mirroring the real `node_modules` chain of nested packages into the virtual
//! project so bare specifiers keep resolving.
//!
//! Corsa resolves a bare specifier by walking the `node_modules` directories on
//! the ancestor chain of the *materialized* file. The virtual root lives in a
//! project-keyed namespace outside `node_modules`, so the project-root install
//! is reproduced at the mirror root. Editor roots are also session-private.
//! Every real `node_modules` *between* the project root and the importing file
//! is also missing from either virtual ancestor chain.
//!
//! That gap is invisible in a single-package project but not in a workspace
//! whose `tsconfig.json` sits at the root: with pnpm's default isolated linker
//! a dependency declared by `apps/app` is linked only into
//! `apps/app/node_modules`, which the mirrored chain never reaches, so a
//! specifier that `tsc`/`tsgo` resolve cleanly reports `TS2307` (#3366).
//!
//! The fix mirrors those directories as symlinks at their rebased location, so
//! the mirrored ancestor chain matches the real one. A directory the mirror also
//! materializes files into is reproduced entry by entry rather than as one link;
//! [`merged`] explains that case.

mod merged;

#[cfg(test)]
mod tests;

use std::path::{Path, PathBuf};

use vize_carton::{FxHashMap, FxHashSet};

use crate::batch::runtime_deps::symlink_package_dir;

use merged::{MirroredEntries, merged_links};

/// A real `node_modules` directory and the mirrored path it is linked from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) struct PackageNodeModulesLink {
    /// Path inside the virtual root that must resolve to `real_dir`.
    pub(super) virtual_dir: PathBuf,
    /// The real `node_modules` directory being mirrored.
    pub(super) real_dir: PathBuf,
}

/// The `node_modules` directories to mirror for `materialized_files`.
///
/// Candidates are the ancestors of every materialized file, relative to the
/// virtual root, that have a real `node_modules` sibling. When the virtual root
/// is outside `<project_root>/node_modules` (the session-private editor shape),
/// the project-root install is merged entry-by-entry at `<canon>/node_modules`.
/// Canon's `vue`, `@vue`, and `vite` runtime entries and any package shadows
/// remain owned by the mirror.
///
/// A candidate whose mirrored `node_modules` holds materialized files of its own
/// cannot be linked as a whole: those files are the mirror's copies of a
/// dependency, and linking the real directory over them would both bury them and
/// make every write inside the virtual project land in the user's real
/// `node_modules`. Such a candidate is merged entry by entry instead — see
/// [`merged`] for why that shape is reachable at all and what it links.
pub(super) fn package_node_modules_links<'a>(
    project_root: &Path,
    virtual_root: &Path,
    materialized_files: impl Iterator<Item = &'a Path>,
) -> Vec<PackageNodeModulesLink> {
    let mut candidates: Vec<PathBuf> = Vec::new();
    let mut seen: FxHashSet<PathBuf> = FxHashSet::default();
    let mut mirrored: FxHashMap<PathBuf, MirroredEntries> = FxHashMap::default();

    let project_node_modules = project_root.join(NODE_MODULES);
    let root_install = nearest_node_modules(project_root);
    if !virtual_root.starts_with(&project_node_modules) {
        let root = PathBuf::new();
        candidates.push(root.clone());
        seen.insert(root.clone());
        let root_entries = mirrored.entry(root).or_default();
        for runtime_entry in ["vue", "@vue", "vite"] {
            root_entries.record(std::iter::once(runtime_entry));
        }
    }

    for file in materialized_files {
        let Some(relative) = file
            .strip_prefix(virtual_root)
            .ok()
            .and_then(Path::parent)
            .filter(|relative| !relative.as_os_str().is_empty())
        else {
            continue;
        };

        let mut ancestor = PathBuf::new();
        let mut components = relative.components();
        let mut inside_node_modules = false;
        for component in components.by_ref() {
            if component.as_os_str() == NODE_MODULES {
                inside_node_modules = true;
                break;
            }
            ancestor.push(component);
            if seen.insert(ancestor.clone()) {
                candidates.push(ancestor.clone());
            }
        }
        if inside_node_modules {
            mirrored
                .entry(ancestor)
                .or_default()
                .record(components.filter_map(|component| component.as_os_str().to_str()));
        }
    }

    candidates.sort();
    candidates
        .into_iter()
        .filter_map(|relative| {
            let real_dir = if relative.as_os_str().is_empty() {
                root_install
                    .clone()
                    .unwrap_or_else(|| project_node_modules.clone())
            } else {
                project_root.join(&relative).join(NODE_MODULES)
            };
            if !real_dir.is_dir() {
                return None;
            }
            let virtual_dir = virtual_root.join(&relative).join(NODE_MODULES);
            Some(match mirrored.get(&relative) {
                Some(mirrored) => merged_links(&real_dir, &virtual_dir, mirrored),
                None => vec![PackageNodeModulesLink {
                    virtual_dir,
                    real_dir,
                }],
            })
        })
        .flatten()
        .collect()
}

fn nearest_node_modules(project_root: &Path) -> Option<PathBuf> {
    let mut package_context = false;
    for ancestor in project_root.ancestors() {
        package_context |= ancestor.join("package.json").is_file();
        let candidate = ancestor.join(NODE_MODULES);
        if (ancestor == project_root || package_context) && candidate.is_dir() {
            return Some(candidate);
        }
    }
    None
}

/// Mirror one package-local dependency directory without ever linking over
/// shadow files that Canon owns below the same `node_modules` path.
pub(super) fn merge_aware_node_modules_links<'a>(
    real_dir: &Path,
    virtual_dir: &Path,
    materialized_files: impl Iterator<Item = &'a Path>,
) -> Vec<PackageNodeModulesLink> {
    let mut mirrored = MirroredEntries::default();
    let mut owns_entries = false;
    for file in materialized_files {
        let Some(relative_parent) = file.strip_prefix(virtual_dir).ok().and_then(Path::parent)
        else {
            continue;
        };
        owns_entries = true;
        mirrored.record(
            relative_parent
                .components()
                .filter_map(|component| component.as_os_str().to_str()),
        );
    }
    if !owns_entries {
        return vec![PackageNodeModulesLink {
            virtual_dir: virtual_dir.to_path_buf(),
            real_dir: real_dir.to_path_buf(),
        }];
    }
    merged_links(real_dir, virtual_dir, &mirrored)
}

/// Link every mirrored `node_modules` directory into the virtual project.
///
/// Linking is best-effort for the same reason the Vue and Vite mirrors are: a
/// platform that refuses to create the symlink degrades to the pre-existing
/// resolution behavior instead of failing the whole check. That degradation
/// reintroduces the `TS2307` of #3366, so each failure records a structured
/// `tracing::warn!` event naming the directory that stayed unmirrored; a run
/// where every link succeeds stays silent.
pub(super) fn materialize_package_node_modules(links: &[PackageNodeModulesLink]) {
    for link in links {
        if let Err(error) = symlink_package_dir(&link.real_dir, &link.virtual_dir) {
            tracing::warn!(
                target: "vize_canon::canon::package_node_modules",
                real_dir = %link.real_dir.display(),
                virtual_dir = %link.virtual_dir.display(),
                error = %error,
                "could not mirror a nested package `node_modules`; bare specifiers \
                 resolved from it may report TS2307",
            );
        }
    }
}

const NODE_MODULES: &str = "node_modules";
