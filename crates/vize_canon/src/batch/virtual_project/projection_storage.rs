//! Immutable projection storage shared by independently cached editor revisions.

use std::sync::Arc;

use super::{VirtualFile, VirtualProject};

fn has_same_storage(left: &VirtualFile, right: &VirtualFile) -> bool {
    left.content == right.content
        && left.original_path == right.original_path
        && left.virtual_path == right.virtual_path
        && left.source_map.sfc_map == right.source_map.sfc_map
        && left
            .source_map
            .import_map
            .has_same_storage(&right.source_map.import_map)
}

impl VirtualProject {
    /// Reuse structurally identical virtual files already retained by another
    /// editor revision. Workspace and host-only revisions keep independent
    /// indexes and lifetimes, but their immutable projections need only one
    /// allocation while their generated bytes and mappings are identical.
    pub(crate) fn share_projection_storage_from(&mut self, other: &Self) {
        for (path, current) in &mut self.virtual_files {
            let Some(retained) = other.virtual_files.get(path) else {
                continue;
            };
            if Arc::ptr_eq(current, retained) || !has_same_storage(current, retained) {
                continue;
            }

            vize_carton::micro_count!("canon.editor.projection_storage_shared.files", 1);
            vize_carton::micro_count!(
                "canon.editor.projection_storage_shared.bytes",
                current
                    .content
                    .len()
                    .saturating_add(current.source_map.import_map.retained_bytes())
            );
            current.clone_from(retained);
        }
    }

    #[cfg(test)]
    pub(crate) fn shared_projection_files_with(&self, other: &Self) -> usize {
        self.virtual_files
            .iter()
            .filter(|(path, file)| {
                other
                    .virtual_files
                    .get(*path)
                    .is_some_and(|other| Arc::ptr_eq(file, other))
            })
            .count()
    }
}
