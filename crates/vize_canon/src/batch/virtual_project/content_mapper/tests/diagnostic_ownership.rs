//! Complete mapper packets retain all navigation and only add proven echo policy.

use super::super::{ContentMapperTransformOptions, transform_with_diagnostic_ownership};
use serde_json::Value;
use std::path::Path;

const MIN: &str = include_str!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../tests/_fixtures/content-mapper/diagnostic-ownership-10607-10618/Min.vue.txt"
));
const FORM: &str = include_str!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../tests/_fixtures/content-mapper/diagnostic-ownership-10607-10618/Form.art.vue.txt"
));

fn packet(path: &str, source: &str, collect: bool) -> Value {
    serde_json::to_value(
        transform_with_diagnostic_ownership(
            Path::new(path),
            source,
            ContentMapperTransformOptions::default(),
            collect.then(Default::default),
        )
        .expect("complete transform"),
    )
    .expect("complete protocol DTO")
}

fn added_echoes(before: &Value, after: &Value) -> Vec<[usize; 6]> {
    let old = before
        .get("diagnosticDirectives")
        .and_then(|table| table["directives"].as_array())
        .map_or(0, Vec::len);
    let new = after
        .get("diagnosticDirectives")
        .and_then(|table| table["directives"].as_array())
        .map_or(0, Vec::len);
    assert!(new >= old);
    let added = new - old;
    let mut restored = after.clone();
    if old == 0 && before.get("diagnosticDirectives").is_none() {
        restored
            .as_object_mut()
            .expect("DTO object")
            .remove("diagnosticDirectives");
    } else if let Some(table) = restored.get_mut("diagnosticDirectives") {
        table["directives"]
            .as_array_mut()
            .expect("directive tuples")
            .drain(..added);
    }
    assert_eq!(
        restored, *before,
        "all generated bytes, mappings, features, links and authored diagnostics must be unchanged"
    );
    after
        .get("diagnosticDirectives")
        .and_then(|table| table["directives"].as_array())
        .into_iter()
        .flatten()
        .take(added)
        .map(|row| serde_json::from_value(row.clone()).expect("six-element tuple"))
        .collect()
}

#[test]
fn each_slot_inference_copy_has_an_expression_owner_without_changing_navigation() {
    for newline in ["\n", "\r\n"] {
        for prefix in ["", "<!-- 日本 🧭 -->"] {
            for (children, slots) in [
                ("", 0),
                ("<span>x</span>", 0),
                ("<template #header><span>x</span></template>", 1),
                (
                    "<template #footer=\"{ total }\"><span>{{total}}</span></template>",
                    1,
                ),
                (
                    "<template #header><span>x</span></template><template #footer=\"{ total }\"><span>{{total}}</span></template>",
                    2,
                ),
            ] {
                let source = MIN
                    .replace("    <template #header><span>x</span></template>", children)
                    .replace("  <Child3", &format!("  {prefix}<Child3"))
                    .replace('\n', newline);
                let before = packet("src/Min.vue", &source, false);
                let after = packet("src/Min.vue", &source, true);
                let echoes = added_echoes(&before, &after);
                assert_eq!(
                    echoes.len(),
                    1 + 8 * slots,
                    "one bare navigation echo and four per-field slot copies"
                );
                for [original, length, generated, end, policy, _] in echoes {
                    assert_eq!(policy, 0);
                    let owner = source
                        .get(original..original + length)
                        .expect("authored UTF8 boundary");
                    assert!(matches!(owner, "count" | "items[0].length"));
                    let text = after["text"].as_str().expect("virtual text");
                    assert!(text.is_char_boundary(generated) && text.is_char_boundary(end));
                }
            }
        }
    }
}

#[test]
fn form_events_and_callback_inference_keep_one_binding_ownership_role() {
    for newline in ["\n", "\r\n"] {
        for callback in ["", " :validate-form-field-on=\"(field) => !!field\""] {
            let source = FORM
                .replace(
                    ":schema=\"schema\"",
                    &format!(":schema=\"schema\"{callback}"),
                )
                .replace('\n', newline);
            let before = packet("Form.art.vue", &source, false);
            let after = packet("Form.art.vue", &source, true);
            let echoes = added_echoes(&before, &after);
            assert!(!echoes.is_empty());
            let fields = [
                [
                    "initial-state",
                    "{ role: 'ok', tags: [] }",
                    "schema",
                    "schema",
                ],
                [
                    "initial-state",
                    "{ role: null, tags: [] }",
                    "schema",
                    "schema",
                ],
                [
                    "initial-state",
                    "{ role: 'ok', tags: [] }",
                    "schema",
                    "schema",
                ],
            ];
            let mut expected = fields.iter().flatten().copied().collect::<Vec<_>>();
            expected.extend([
                "{ role: 'ok', tags: [] }",
                "schema",
                "{ role: null, tags: [] }",
                "schema",
                "{ role: 'ok', tags: [] }",
                "schema",
            ]);
            if !callback.is_empty() {
                for field in fields {
                    expected.extend(field);
                    expected.extend(field);
                }
            }
            let actual = echoes
                .into_iter()
                .map(|[original, length, _, _, _, _]| {
                    source
                        .get(original..original + length)
                        .expect("exact authored binding")
                })
                .collect::<Vec<_>>();
            assert_eq!(
                actual, expected,
                "the complete ownership vector must contain only the independently enumerated ordinary sibling bindings"
            );
        }
    }
}

#[test]
fn contextual_callback_errors_do_not_acquire_synthetic_ignore_rows() {
    let source = "<script setup lang=\"ts\">import Child from './Child.vue'</script><template><Child :pick=\"(item: number) => item.missing\" /></template>";
    assert_eq!(
        packet("Callback.vue", source, true),
        packet("Callback.vue", source, false)
    );
}

#[test]
fn deferred_expect_buffers_prepend_echo_policy_without_changing_authored_expectations() {
    for newline in ["\n", "\r\n"] {
        let source = MIN
            .replace("  <Child3", "  <!-- @vue-expect-error -->\n  <Child3")
            .replace('\n', newline);
        let before = packet("src/Min.vue", &source, false);
        let after = packet("src/Min.vue", &source, true);
        let echoes = added_echoes(&before, &after);
        assert_eq!(echoes.len(), 9);
        let text = after["text"].as_str().expect("virtual source");
        for [_, _, start, end, _, _] in echoes {
            let generated = text.get(start..end).expect("real rebased generated row");
            assert!(matches!(generated, "\"count\"" | "items[0].length"));
        }
    }
}
