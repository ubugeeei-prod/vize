#[test]
fn proved_expected_callback_geometry_never_hides_its_contextual_body() {
    let source = "<script setup lang=\"ts\">import Comp from './Comp.vue'; const noop = () => {};</script><template><!-- @vue-expect-error --><Comp :id=\"{ a: 1 }\" :pick=\"(field) => !!field\" @save=\"noop\" /></template>";
    let mut before = packet("Callback.vue", source, false);
    let mut after = packet("Callback.vue", source, true);
    let table = after
        .as_object_mut()
        .unwrap()
        .remove("diagnosticDirectives")
        .unwrap();
    before
        .as_object_mut()
        .unwrap()
        .remove("diagnosticDirectives");
    assert_eq!(
        after, before,
        "all text, mappings, editor features, links and authored diagnostics remain exact"
    );
    let callback = source.find("(field) => !!field").unwrap();
    let rows = table["directives"]
        .as_array()
        .unwrap()
        .iter()
        .map(|row| serde_json::from_value::<[usize; 6]>(row.clone()).unwrap())
        .collect::<Vec<_>>();
    let expects = rows.iter().filter(|row| row[4] == 1).collect::<Vec<_>>();
    assert_eq!(expects.len(), 1, "unused EXPECT remains one aggregate");
    assert!(
        rows.iter()
            .filter(|row| row[4] == 0)
            .all(|row| row[0] + row[1] <= callback
                || callback + "(field) => !!field".len() <= row[0]),
        "no contextual callback IGNORE is emitted"
    );
    let [_, _, start, end, _, _] = *expects[0];
    let body_rows = after["mappings"]
        .as_array()
        .unwrap()
        .iter()
        .filter(|row| row[2] == callback && row[3] == "(field) => !!field".len())
        .collect::<Vec<_>>();
    assert_eq!(
        body_rows.len(),
        2,
        "one inference copy and one authored contextual check"
    );
    for row in body_rows {
        let generated = row[0].as_u64().unwrap() as usize;
        let length = row[1].as_u64().unwrap() as usize;
        let editor_features = row[5].as_u64().unwrap();
        assert_eq!(
            start <= generated && generated + length <= end,
            editor_features != 0,
            "only the actual authored body belongs to EXPECT"
        );
    }
}

#[test]
fn expect_owns_one_late_packet_and_navigation_echoes_do_not_widen_it() {
    for newline in ["\n", "\r\n"] {
        let source = MIN
            .replace("  <Child3", "  <!-- @vue-expect-error -->\n  <Child3")
            .replace('\n', newline);
        let mut before = packet("src/Min.vue", &source, false);
        let after = packet("src/Min.vue", &source, true);
        let text = after["text"].as_str().expect("virtual source");
        let start = text.find("void Child3;").expect("mapped component tag") + "void ".len();
        // Required-slot checks are diagnostics owned by the same opening tag,
        // after its props call. Do not truncate EXPECT at the last prop entry.
        let required_slot_check = "  const __vize_required_slots_0: __VizeRequiredSlots<__VizeSlotContract_0, { readonly \"header\": true; }> = {};\n  void __vize_required_slots_0;\n";
        let end = text
            .find(required_slot_check)
            .expect("complete independently authored required-slot check")
            + required_slot_check.len();
        let authored = before["diagnosticDirectives"]["directives"][0]
            .as_array_mut()
            .expect("one authored expectation");
        assert_eq!(authored[4], 1);
        authored[2] = start.into();
        authored[3] = end.into();
        let echoes = added_echoes(&before, &after);
        assert_eq!(echoes.len(), 9);
        for [_, _, echo_start, echo_end, _, _] in echoes {
            let generated = text
                .get(echo_start..echo_end)
                .expect("real rebased generated row");
            assert!(matches!(generated, "\"count\"" | "items[0].length"));
            assert!(
                echo_end <= start || end <= echo_start,
                "protocol intervals must be disjoint"
            );
        }
    }
}

#[test]
fn merged_class_and_style_values_keep_one_visible_copy() {
    // #10788: a static and a bound class/style merge into one props-call entry
    // that repeats each value its own prop assignment already checks.
    let source = r#"<script setup lang="ts">
import Child from './Child.vue';
const { href = "", active = false } = defineProps<{ href?: string; active?: boolean }>();
function onClick(): void {}
</script>

<template>
  <component :is="href ? 'a' : 'button'" class="btn" :class="[{ 'btn--active': active.nope }]" @click.stop="onClick">x</component>
  <component :is="href ? 'a' : 'button'" class="btn" :class="[{ 'btn--active': active.nope }]">no listener</component>
  <button class="btn" :class="[{ 'btn--active': active.nope }]" @click.stop="onClick">plain element</button>
  <Child style="color: red" :style="{ color: active.nope }" />
</template>
"#;
    let packet = packet("src/App.vue", source, true);
    let rows = |key: &str| -> Vec<[usize; 6]> {
        serde_json::from_value(
            key.split('.')
                .fold(packet.clone(), |value, key| value[key].clone()),
        )
        .expect("protocol tuples")
    };
    let (spans, directives) = (rows("mappings"), rows("diagnosticDirectives.directives"));
    let text = packet["text"].as_str().expect("virtual text");
    let mut visible = text
        .match_indices("active.nope")
        .filter(|(generated, _)| {
            !directives.iter().any(|[_, _, start, end, policy, _]| {
                *policy == 0 && (*start..*end).contains(generated)
            })
        })
        .filter_map(|(generated, _)| {
            spans
                .iter()
                .filter(|[start, length, _, original_length, _, _]| {
                    (*start..start + length).contains(&generated) && length == original_length
                })
                .min_by_key(|[_, length, _, _, _, _]| *length)
                .map(|[start, _, original, _, _, _]| original + generated - start)
        })
        .collect::<Vec<_>>();
    visible.sort_unstable();
    let authored = source
        .match_indices("active.nope")
        .map(|(at, _)| at)
        .collect::<Vec<_>>();
    assert_eq!(
        visible, authored,
        "one diagnostic-visible copy per authored value"
    );
}
