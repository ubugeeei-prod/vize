fn packet(path: &str, source: &str, collect: bool) -> Value {
    serde_json::to_value(
        transform_with_diagnostic_ownership(
            Path::new(path),
            source,
            ContentMapperTransformOptions::default(),
            None,
            collect.then(Default::default),
        )
        .expect("complete transform"),
    )
    .expect("complete protocol DTO")
}

fn added_echoes(before: &Value, after: &Value) -> Vec<[usize; 6]> {
    let old = before
        .get("diagnosticDirectives")
        .and_then(|table| table["directives"].as_array())
        .map_or(0, Vec::len);
    let new = after
        .get("diagnosticDirectives")
        .and_then(|table| table["directives"].as_array())
        .map_or(0, Vec::len);
    assert!(new >= old);
    let added = new - old;
    let mut restored = after.clone();
    if old == 0 && before.get("diagnosticDirectives").is_none() {
        restored
            .as_object_mut()
            .expect("DTO object")
            .remove("diagnosticDirectives");
    } else if let Some(table) = restored.get_mut("diagnosticDirectives") {
        table["directives"]
            .as_array_mut()
            .expect("directive tuples")
            .drain(..added);
    }
    assert_eq!(
        restored, *before,
        "all generated bytes, mappings, features, links and authored diagnostics must be unchanged"
    );
    after
        .get("diagnosticDirectives")
        .and_then(|table| table["directives"].as_array())
        .into_iter()
        .flatten()
        .take(added)
        .map(|row| serde_json::from_value(row.clone()).expect("six-element tuple"))
        .collect()
}

#[test]
fn each_slot_inference_copy_has_an_expression_owner_without_changing_navigation() {
    for newline in ["\n", "\r\n"] {
        for prefix in ["", "<!-- 日本 🧭 -->"] {
            // (children, slots, slots with a binding)
            for (children, slots, bound) in [
                ("", 0, 0),
                ("<span>x</span>", 0, 0),
                ("<template #header><span>x</span></template>", 1, 0),
                (
                    "<template #footer=\"{ total }\"><span>{{total}}</span></template>",
                    1,
                    1,
                ),
                (
                    "<template #header><span>x</span></template><template #footer=\"{ total }\"><span>{{total}}</span></template>",
                    2,
                    1,
                ),
            ] {
                let source = MIN
                    .replace("    <template #header><span>x</span></template>", children)
                    .replace("  <Child3", &format!("  {prefix}<Child3"))
                    .replace('\n', newline);
                let before = packet("src/Min.vue", &source, false);
                let after = packet("src/Min.vue", &source, true);
                let echoes = added_echoes(&before, &after);
                // Each slot's template pass copies both fields twice; the props
                // pass annotates a bound slot from that host instead of
                // inferring a second one, so it adds no copies.
                assert_eq!(
                    echoes.len(),
                    1 + 4 * slots,
                    "one bare navigation echo and the per-field slot host copies (bound: {bound})"
                );
                for [original, length, generated, end, policy, _] in echoes {
                    assert_eq!(policy, 0);
                    let owner = source
                        .get(original..original + length)
                        .expect("authored UTF8 boundary");
                    assert!(matches!(owner, "count" | "items[0].length"));
                    let text = after["text"].as_str().expect("virtual text");
                    assert!(text.is_char_boundary(generated) && text.is_char_boundary(end));
                }
            }
        }
    }
}

fn rows(value: &Value) -> Vec<[usize; 6]> {
    serde_json::from_value(value.clone()).expect("protocol tuples")
}

/// Authored offsets of each `needle` copy that the host would report.
fn visible_copies(source: &str, needle: &str) -> Vec<usize> {
    let packet = packet("src/P3.vue", source, true);
    let text = packet["text"].as_str().expect("virtual text");
    let spans = rows(&packet["mappings"]);
    let directives = rows(&packet["diagnosticDirectives"]["directives"]);
    text.match_indices(needle)
        .map(|(generated, _)| generated)
        .filter(|generated| {
            !directives.iter().any(|[_, _, start, end, policy, _]| {
                *policy == 0 && (*start..*end).contains(generated)
            })
        })
        .map(|generated| {
            spans
                .iter()
                .filter(|[start, length, ..]| (*start..start + length).contains(&generated))
                .min_by_key(|[_, length, ..]| *length)
                .map_or(usize::MAX, |[start, _, original, ..]| {
                    original + generated - start
                })
        })
        .collect()
}

#[test]
fn slot_host_copies_of_function_valued_props_stay_unreported() {
    // #10774: slot hosts repeat every prop without mappings. A callback has no
    // proved primary, so its copies reached the host at generated offsets.
    for value in [
        "{ request: () => String(items[0].length) }",
        "{\n        request: () => {\n          const first = items[0].length;\n          return String(first);\n        },\n      }",
    ] {
        for slots in [
            "",
            "<template #form><span>x</span></template>",
            "<template #form><span>x</span></template><template #footer=\"{ total }\">{{ total }}</template>",
        ] {
            let source = format!(
                "<script setup lang=\"ts\">\nimport Child2 from \"./Child2.vue\";\nconst items: string[] = [];\n</script>\n\n<template>\n  <Child2\n      label=\"x\"\n      :ctx=\"{value}\"\n    >{slots}</Child2>\n</template>\n"
            );
            let authored = source.find("items[0]").expect("authored access");
            assert_eq!(visible_copies(&source, "items[0]"), [authored], "{slots}");
        }
    }
}

