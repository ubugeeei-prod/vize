//! Compose AST-owned TSX commas with existing template-ref callee edits.
use super::super::{InferredCall, TemplateRefKeyChecks};
use crate::virtual_ts::VizeSubSpan;
use std::{borrow::Cow, ops::Range};
use vize_carton::append;

enum Edit<'a> {
    Comma(usize),
    Callee(&'a InferredCall),
}

impl Edit<'_> {
    fn range(&self) -> Range<usize> {
        match self {
            Self::Comma(position) => *position..*position,
            Self::Callee(call) => call.callee.clone(),
        }
    }
}

impl TemplateRefKeyChecks<'_> {
    pub(super) fn specialize_tsx_line(
        &self,
        line: &mut Cow<'_, str>,
        start: usize,
        gen_start: usize,
        source_offset: &dyn Fn(usize) -> usize,
    ) -> Option<Vec<VizeSubSpan>> {
        let end = start + line.len();
        // Verify the original retained parameter still occupies this line.
        // Masked module spans and earlier unequal-length export rewrites are
        // not permission to insert at an unrelated generated byte.
        let commas: Vec<_> = self
            .tsx_arrows
            .iter()
            .filter(|arrow| {
                arrow.parameter.start >= start
                    && arrow.position <= end
                    && arrow.position == arrow.parameter.end
                    && line.get(arrow.parameter.start - start..arrow.parameter.end - start)
                        == Some(arrow.source.as_str())
            })
            .collect();
        if commas.is_empty() {
            return None;
        }
        let mut edits: Vec<_> = commas
            .iter()
            .map(|arrow| Edit::Comma(arrow.position))
            .collect();
        edits.extend(
            self.calls
                .iter()
                .filter(|call| {
                    call.callee.start >= start
                        && call.callee.end <= end
                        && line.get(call.callee.start - start..call.callee.end - start)
                            == Some(call.name.as_str())
                })
                .map(Edit::Callee),
        );
        edits.sort_by_key(|edit| (edit.range().start, edit.range().end));
        let mut checked = start;
        for edit in &edits {
            let range = edit.range();
            if range.start < checked || range.end > end {
                return None;
            }
            checked = range.end;
        }
        let mut output = crate::virtual_ts::TextBuf::with_capacity(line.len() + commas.len());
        let mut spans = Vec::new();
        let mut cursor = start;
        for edit in edits {
            let range = edit.range();
            copy(
                &mut output,
                &mut spans,
                line,
                cursor..range.start,
                start,
                gen_start,
                source_offset,
            );
            match edit {
                Edit::Comma(_) => output.push(','),
                Edit::Callee(call) => {
                    if !call.imported {
                        output.push('(');
                    }
                    let callee = if call.imported {
                        self.helper
                    } else {
                        call.name.as_str()
                    };
                    spans.push(VizeSubSpan {
                        gen_range: gen_start + output.len()
                            ..gen_start + output.len() + callee.len(),
                        src_range: source_offset(call.callee.start)..source_offset(call.callee.end),
                    });
                    output.push_str(callee);
                    if !call.imported {
                        append!(output, " as {}Global)", self.helper);
                    }
                }
            }
            cursor = range.end;
        }
        copy(
            &mut output,
            &mut spans,
            line,
            cursor..end,
            start,
            gen_start,
            source_offset,
        );
        *line = Cow::Owned(output.into());
        Some(spans)
    }
}

fn copy(
    output: &mut crate::virtual_ts::TextBuf,
    spans: &mut Vec<VizeSubSpan>,
    line: &str,
    range: Range<usize>,
    start: usize,
    gen_start: usize,
    source_offset: &dyn Fn(usize) -> usize,
) {
    if range.is_empty() {
        return;
    }
    let Some(text) = line.get(range.start - start..range.end - start) else {
        return;
    };
    spans.push(VizeSubSpan {
        gen_range: gen_start + output.len()..gen_start + output.len() + text.len(),
        src_range: source_offset(range.start)..source_offset(range.end),
    });
    output.push_str(text);
}

