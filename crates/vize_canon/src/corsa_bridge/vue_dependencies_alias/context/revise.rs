//! Carry a prepared revision to the host's next buffer.

use std::path::{Path, PathBuf};

use vize_carton::FxHashMap;

use super::{AliasContext, ContextFingerprint};
use crate::batch::ModuleSpecifierFactsCache;
use crate::corsa_bridge::types::CorsaBridgeError;
use crate::corsa_bridge::vue_document::CorsaProjectEnvironment;

impl AliasContext {
    /// The host's cached revision with `content` registered in place of its
    /// previous buffer, stamped with the disk inputs it was built from.
    /// `None` when only a build can produce this revision.
    #[expect(clippy::disallowed_types, reason = "cached revisions are shared")]
    pub(super) fn revise_cached(
        source_path: &Path,
        content: &str,
        overlays: &FxHashMap<PathBuf, &str>,
        fingerprint: &mut ContextFingerprint,
        environment: CorsaProjectEnvironment<'_>,
    ) -> Result<Option<Self>, CorsaBridgeError> {
        let host = vize_carton::path::canonicalize_non_verbatim(source_path);
        let __diag = crate::corsa_bridge::preparation_trace::Phase::start("alias_take_revisable", 1);
        let (stamped, context, refreshed) = {
            let mut cache = environment.editor_session.cache();
            let Some((stamped, context)) = cache.take_revisable(source_path, fingerprint) else {
                return Ok(None);
            };
            let refreshed = context.mirror.as_ref().map_or_else(Vec::new, |mirror| {
                cache.overlay_sources_to_refresh(
                    mirror.virtual_root(),
                    fingerprint.overlay_identity(),
                    &host,
                    overlays,
                )
            });
            (stamped, context, refreshed)
        };
        __diag.finish();
        // A revision another request still reads is never changed under it.
        let Ok(context) = std::sync::Arc::try_unwrap(context) else {
            return Ok(None);
        };
        let phase = crate::corsa_bridge::preparation_trace::Phase::start("alias_revise", 1);
        let revised = context.revise(&host, content, &refreshed)?;
        phase.finish();
        if revised.is_some() {
            fingerprint.adopt_stamps(&stamped);
        }
        Ok(revised)
    }

    fn revise(
        mut self,
        host: &Path,
        content: &str,
        refreshed_sources: &[PathBuf],
    ) -> Result<Option<Self>, CorsaBridgeError> {
        // The build registers these live members again from their buffers.
        if refreshed_sources != self.refreshed_sources {
            return Ok(None);
        }
        let Some(mirror) = self.mirror.as_mut() else {
            return Ok(None);
        };
        // The build registers a package-route target again from disk.
        if mirror.is_package_route_source(host) {
            return Ok(None);
        }
        mirror
            .register_paths_with_content([(host, content)])
            .map_err(CorsaBridgeError::from)?;
        let mut facts = ModuleSpecifierFactsCache::default();
        if mirror.editor_source_facts(host, &mut facts).as_ref() != Some(&self.host_facts) {
            return Ok(None);
        }
        mirror
            .finalize_package_routes_with_imports(|project| {
                project.finalize_editor_imports_of(host, &mut facts);
            })
            .map_err(CorsaBridgeError::from)?;
        // The graph facts still hold, so the dependency documents stay. Only the
        // host's generated bytes move; a missing mirror document falls back to
        // building the whole surface.
        let generated = self.editor_vue_document(host);
        let fresh = self.materialized_source_for(host);
        let retargeted = if let Some(surface) = self.query_surface.get_mut() {
            if let Some((path, generated)) = generated {
                crate::corsa_bridge::vue_document::build::retarget_host(
                    surface, &path, generated, fresh,
                );
                true
            } else {
                false
            }
        } else {
            false
        };
        if !retargeted {
            self.query_surface = Default::default();
        }
        Ok(Some(self))
    }
}
