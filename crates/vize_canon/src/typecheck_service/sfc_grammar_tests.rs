#![expect(
    clippy::disallowed_types,
    clippy::disallowed_macros,
    reason = "native service tests construct the shared bridge and retain complete diagnostic packets"
)]

use super::{
    CorsaBridge, SfcDiagnosticSeverity, SfcTypeCheckResult, TypeCheckService,
    TypeCheckServiceOptions,
};
#[cfg(unix)]
use crate::corsa_bridge::CorsaBridgeConfig;
#[cfg(unix)]
use level_test_support::original_diagnosing_process as native;
use serde_json::{Value, json};

fn packet(result: &SfcTypeCheckResult) -> Value {
    json!({
        "errorCount": result.error_count,
        "warningCount": result.warning_count,
        "virtualTs": result.virtual_ts,
        "diagnostics": result.diagnostics.iter().map(|diagnostic| json!({
            "message": diagnostic.message,
            "severity": format!("{:?}", diagnostic.severity),
            "start": diagnostic.start,
            "end": diagnostic.end,
            "code": diagnostic.code,
            "related": diagnostic.related.iter().map(|related| json!({
                "message": related.message,
                "filename": related.filename,
                "start": related.start,
                "end": related.end,
            })).collect::<Vec<_>>(),
        })).collect::<Vec<_>>(),
    })
}

#[test]
#[cfg(unix)]
fn adjacent_quoted_attributes_reach_the_native_service_with_identical_output() {
    if !native::enabled() {
        return;
    }
    let root = tempfile::tempdir().unwrap();
    let workspace = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(std::path::Path::parent)
        .unwrap();
    let node_modules = root.path().join("node_modules");
    std::fs::create_dir(&node_modules).unwrap();
    for (name, source) in [
        ("vue", workspace.join("tests/node_modules/vue")),
        ("vite", workspace.join("node_modules/vite")),
    ] {
        std::os::unix::fs::symlink(
            std::fs::canonicalize(source).unwrap(),
            node_modules.join(name),
        )
        .unwrap();
    }
    std::fs::write(
        root.path().join("tsconfig.json"),
        r#"{"compilerOptions":{"strict":true,"target":"ES2022","module":"ESNext","moduleResolution":"Bundler","types":[]},"include":["SfcGrammar.vue.ts"]}"#,
    )
    .unwrap();
    std::fs::write(root.path().join("SfcGrammar.vue.ts"), "export {};\n").unwrap();
    let filename = root.path().join("SfcGrammar.vue");
    let filename = filename.to_str().unwrap();
    let service = TypeCheckService {
        bridge: std::sync::Arc::new(CorsaBridge::with_config(CorsaBridgeConfig {
            corsa_path: Some(native::runtime()),
            working_dir: Some(root.path().to_path_buf()),
            ..Default::default()
        })),
    };
    let options = TypeCheckServiceOptions::default();
    corsa::runtime::block_on(async {
        service.bridge.spawn().await.unwrap();
        let reference = service
            .check_sfc(
                r#"<template><div id="a" class="b">ok</div></template>"#,
                filename,
                &options,
            )
            .await
            .unwrap();
        assert!(reference.virtual_ts.is_some());
        assert_eq!(reference.error_count, 0, "{reference:?}");
        let mut expected = packet(&reference);
        let virtual_ts = reference.virtual_ts.as_ref().unwrap();
        // The class attribute starts one byte earlier in the adjacent input.
        // Only its two source-offset-owned identifier occurrences may differ;
        // retain every other generated byte and the complete native response.
        assert_eq!(virtual_ts.matches("__vize_native_key_12").count(), 2);
        expected["virtualTs"] =
            json!(virtual_ts.replace("__vize_native_key_12", "__vize_native_key_11"));
        let original = include_str!(
            "../../../../tests/_fixtures/differential/typechecker/sfc-entry-grammar-11869/Static.vue.txt"
        );
        for source in [
            original.to_owned(),
            original.replace(r#"id="a"class="b""#, "id='a'class='b'"),
            original.replace(r#"id="a"class="b""#, "id=\"a\"class='b'"),
        ] {
            let actual = service
                .check_sfc(&source, filename, &options)
                .await
                .unwrap();
            assert_eq!(packet(&actual), expected, "{source}");
        }
        service.shutdown().await.unwrap();
    });
}

#[test]
fn adjacent_quoted_attributes_keep_the_exact_malformed_service_diagnostic() {
    let service = TypeCheckService {
        bridge: std::sync::Arc::new(CorsaBridge::new()),
    };
    let result = corsa::runtime::block_on(service.check_sfc(
        include_str!("../../../../tests/_fixtures/differential/typechecker/sfc-entry-grammar-11869/Malformed.vue.txt"),
        "SfcGrammar.vue",
        &TypeCheckServiceOptions::default(),
    ))
    .unwrap();
    assert_eq!(
        packet(&result),
        json!({
            "errorCount": 1,
            "warningCount": 0,
            "virtualTs": null,
            "diagnostics": [{
                "message": "Template parse error: Element is missing end tag.",
                "severity": format!("{:?}", SfcDiagnosticSeverity::Error),
                "start": 10,
                "end": 31,
                "code": "template-parse-error",
                "related": [],
            }],
        })
    );
}
