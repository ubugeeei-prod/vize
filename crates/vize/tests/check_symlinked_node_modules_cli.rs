//! Regression for #3320: `vize check` must report the same diagnostics whether
//! the project's `node_modules` is a real directory or a symlink into an
//! out-of-tree store (pnpm stores, monorepo hoisting shims, worktree CI lanes,
//! containers that bind-mount dependencies).
//!
//! The virtual project is materialized under `<project>/node_modules/.vize`, so
//! a symlinked `node_modules` puts it in the link target. The Corsa CLI then
//! prints relative diagnostic paths against the resolved spelling of its
//! working directory while the project indexes files under the through-link
//! spelling; resolving one against the other dropped every diagnostic and left
//! the file reported as checked with an empty list. Both layouts are pinned
//! here because the dangerous direction is the *absence* of a diagnostic.

#[path = "support/corsa_requirement.rs"]
mod corsa_requirement;

use std::{
    path::{Path, PathBuf},
    process::Command,
};

use vize_s0::cstr;

const TSCONFIG: &str = r#"{
  "compilerOptions": {
    "strict": true,
    "target": "ES2022",
    "module": "ESNext",
    "moduleResolution": "bundler",
    "noEmit": true,
    "skipLibCheck": true
  },
  "include": ["src/**/*.vue"]
}
"#;

const BROKEN_SFC: &str = r#"<script setup lang="ts">
const total: number = "definitely not a number";
</script>

<template>
  <div>{{ total }}</div>
</template>
"#;

/// `node_modules` is a symlink to a store outside the project, so the virtual
/// project — and the Corsa working directory — resolve outside the project root.
#[test]
fn check_reports_diagnostics_with_a_symlinked_node_modules() {
    run_case("symlinked", NodeModulesLayout::SymlinkedStore);
}

/// The same project with `node_modules` as a real directory. Kept alongside the
/// symlinked case so neither layout can start dropping diagnostics silently.
#[test]
fn check_reports_diagnostics_with_a_real_node_modules() {
    run_case("real-dir", NodeModulesLayout::RealDirectory);
}

enum NodeModulesLayout {
    /// `<project>/node_modules` -> `<project>-store` (outside the project).
    SymlinkedStore,
    /// `<project>/node_modules` is a real directory.
    RealDirectory,
}

fn run_case(name: &str, layout: NodeModulesLayout) {
    let Some(corsa_path) = corsa_requirement::required_or_skip(resolve_test_corsa_path()) else {
        eprintln!("skipping {name}: tsgo not found");
        return;
    };
    let Some(vue_package) = workspace_vue_package() else {
        eprintln!("skipping {name}: workspace Vue package missing");
        return;
    };

    let project_root = unique_case_dir(name);
    let store_root = unique_case_dir(&cstr!("{name}-store"));
    let _ = std::fs::remove_dir_all(&project_root);
    let _ = std::fs::remove_dir_all(&store_root);
    std::fs::create_dir_all(project_root.join("src")).unwrap();

    let node_modules = match layout {
        NodeModulesLayout::SymlinkedStore => {
            std::fs::create_dir_all(&store_root).unwrap();
            symlink_path(&store_root, &project_root.join("node_modules")).unwrap();
            store_root.clone()
        }
        NodeModulesLayout::RealDirectory => {
            let node_modules = project_root.join("node_modules");
            std::fs::create_dir_all(&node_modules).unwrap();
            node_modules
        }
    };
    link_vue_packages(&vue_package, &node_modules).unwrap();

    std::fs::write(project_root.join("tsconfig.json"), TSCONFIG).unwrap();
    std::fs::write(project_root.join("src/Broken.vue"), BROKEN_SFC).unwrap();

    let output = Command::new(env!("CARGO_BIN_EXE_vize"))
        .current_dir(&project_root)
        .env("CORSA_PATH", &corsa_path)
        .args([
            "check",
            "--tsconfig",
            "tsconfig.json",
            "src",
            "--format",
            "json",
        ])
        .output()
        .unwrap();

    let stdout = std::string::String::from_utf8(output.stdout).unwrap();
    let stderr = std::string::String::from_utf8_lossy(&output.stderr).into_owned();
    let json: serde_json::Value = serde_json::from_str(&stdout)
        .unwrap_or_else(|error| panic!("{name}: invalid JSON ({error})\n{stdout}\n{stderr}"));
    let diagnostics = json["files"]
        .as_array()
        .unwrap_or_else(|| panic!("{name}: no files reported\n{stdout}"))
        .iter()
        .flat_map(|file| file["diagnostics"].as_array().into_iter().flatten())
        .filter_map(|diagnostic| diagnostic.as_str())
        .collect::<Vec<_>>();

    assert_eq!(
        json["fileCount"],
        serde_json::json!(1),
        "{name}: the SFC must be checked\n{stdout}\n{stderr}"
    );
    assert!(
        diagnostics
            .iter()
            .any(|diagnostic| diagnostic.contains("[TS2322]")),
        "{name}: the injected type error must be reported, not silently dropped\n{stdout}\n{stderr}"
    );
    assert_eq!(
        json["errorCount"],
        serde_json::json!(1),
        "{name}: exactly the injected error is expected\n{stdout}\n{stderr}"
    );
    assert_eq!(
        output.status.code(),
        Some(1),
        "{name}: a reported error must fail the run\n{stdout}\n{stderr}"
    );

    let _ = std::fs::remove_dir_all(&project_root);
    let _ = std::fs::remove_dir_all(&store_root);
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("workspace root should exist")
        .to_path_buf()
}

fn unique_case_dir(name: &str) -> PathBuf {
    workspace_root()
        .join("target")
        .join("vize-tests")
        .join("tests")
        .join(cstr!("check-symlinked-node-modules-{name}-{}", std::process::id()).as_str())
}

fn resolve_test_corsa_path() -> Option<PathBuf> {
    if let Some(path) = std::env::var_os("CORSA_PATH") {
        let path = PathBuf::from(path);
        if path.exists() {
            return Some(path);
        }
    }
    let root = workspace_root();
    [
        root.join("node_modules/.bin/tsgo"),
        root.join("examples/vite-musea/node_modules/.bin/tsgo"),
    ]
    .into_iter()
    .find(|candidate| candidate.exists())
}

fn workspace_vue_package() -> Option<PathBuf> {
    let root = workspace_root();
    [
        root.join("node_modules/vue"),
        root.join("tests/node_modules/vue"),
        root.join("playground/node_modules/vue"),
    ]
    .into_iter()
    .find(|candidate| candidate.exists())
}

fn link_vue_packages(vue_package: &Path, node_modules: &Path) -> std::io::Result<()> {
    symlink_path(vue_package, &node_modules.join("vue"))?;
    let vue_namespace = vue_package
        .parent()
        .map(|parent| parent.join("@vue"))
        .filter(|path| path.exists());
    if let Some(vue_namespace) = vue_namespace {
        symlink_path(&vue_namespace, &node_modules.join("@vue"))?;
    }
    Ok(())
}

fn symlink_path(source: &Path, target: &Path) -> std::io::Result<()> {
    if let Some(parent) = target.parent() {
        std::fs::create_dir_all(parent)?;
    }
    if target.is_symlink() || target.is_file() {
        std::fs::remove_file(target)?;
    } else if target.exists() {
        std::fs::remove_dir_all(target)?;
    }
    #[cfg(unix)]
    {
        std::os::unix::fs::symlink(source, target)
    }
    #[cfg(windows)]
    {
        std::os::windows::fs::symlink_dir(source, target)
    }
}
