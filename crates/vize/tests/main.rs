/// `autotests = false` would silently skip a new top-level test file; every one
/// must be declared above.
#[test]
fn every_top_level_test_file_is_a_declared_module() {
    let declared: std::collections::BTreeSet<&str> = include_str!("main.rs")
        .lines()
        .filter_map(|line| line.strip_prefix("pub mod ").or(line.strip_prefix("mod ")))
        .filter_map(|line| line.strip_suffix(';'))
        .collect();
    let directory = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests");
    let mut files = std::collections::BTreeSet::new();
    for entry in std::fs::read_dir(directory).expect("tests directory must be readable") {
        let name = entry.expect("tests entry must be readable").file_name();
        let name = name.to_str().expect("test file names are UTF-8").to_owned();
        if let Some(module) = name.strip_suffix(".rs")
            && module != "main"
        {
            files.insert(module.to_owned());
        }
    }
    let missing: Vec<&String> = files
        .iter()
        .filter(|file| !declared.contains(file.as_str()))
        .collect();
    assert!(
        missing.is_empty(),
        "declare these test files in tests/main.rs: {missing:?}"
    );
}

