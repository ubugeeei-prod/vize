#![cfg(test)]
#![expect(clippy::disallowed_macros, reason = "fixtures use std strings")]
#![expect(clippy::disallowed_types, reason = "fixtures use std strings")]

//! Vize resolves packages and `types` entries through the ancestor
//! `node_modules` chain exactly as TypeScript does. The fixture lives where no
//! ancestor provides packages, installs a package only above the app, and
//! installs `dup` and `@types/shared-globals` at both levels so the nearest
//! install must win.

use crate::support::{corsa_path, corsa_requirement};

use std::path::{Path, PathBuf};
use std::process::Command;

const PROBE: &str = r#"import { aboveOnly } from "above-only";
import { version } from "dup";
export const above: "above" = aboveOnly;
export const near: "near" = version;
export const far: "far" = farGlobal;
export const shared: "near" = sharedGlobal;
export const wrongVersion: "far" = version;
export const wrongShared: "far" = sharedGlobal;
"#;

/// Each `types` setting with the `(line, column, code)` TypeScript reports for
/// `PROBE`. The two `wrong*` lines prove the nearest install was read.
const CASES: &[(&str, &[(u32, u32, &str)])] = &[
    (
        r#"["far-globals", "shared-globals"]"#,
        &[(7, 14, "TS2322"), (8, 14, "TS2322")],
    ),
    (r#"["*"]"#, &[(7, 14, "TS2322"), (8, 14, "TS2322")]),
    (
        "[]",
        &[
            (5, 27, "TS2304"),
            (6, 31, "TS2304"),
            (7, 14, "TS2322"),
            (8, 35, "TS2304"),
        ],
    ),
];

fn workspace_root() -> &'static Path {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("workspace root should exist")
}

fn write_file(root: &Path, path: &str, content: &str) {
    let file_path = root.join(path);
    std::fs::create_dir_all(file_path.parent().unwrap()).unwrap();
    std::fs::write(file_path, content).unwrap();
}

fn write_package(root: &Path, dir: &str, declaration: &str) {
    let name = dir.rsplit_once("node_modules/").unwrap().1;
    write_file(
        root,
        &format!("{dir}/package.json"),
        &format!(r#"{{ "name": "{name}", "version": "1.0.0", "types": "index.d.ts" }}"#),
    );
    write_file(root, &format!("{dir}/index.d.ts"), declaration);
}

fn write_workspace(workspace: &Path) -> PathBuf {
    write_package(
        workspace,
        "node_modules/above-only",
        "export declare const aboveOnly: \"above\";\n",
    );
    write_package(
        workspace,
        "node_modules/dup",
        "export declare const version: \"far\";\n",
    );
    write_package(
        workspace,
        "node_modules/@types/far-globals",
        "declare const farGlobal: \"far\";\n",
    );
    write_package(
        workspace,
        "node_modules/@types/shared-globals",
        "declare const sharedGlobal: \"far\";\n",
    );
    write_package(
        workspace,
        "apps/web/node_modules/dup",
        "export declare const version: \"near\";\n",
    );
    write_package(
        workspace,
        "apps/web/node_modules/@types/shared-globals",
        "declare const sharedGlobal: \"near\";\n",
    );
    let app = workspace.join("apps/web");
    write_file(
        &app,
        "package.json",
        r#"{ "name": "web", "private": true, "type": "module" }"#,
    );
    write_file(&app, "src/probe.ts", PROBE);
    write_file(
        &app,
        "src/Probe.vue",
        &format!("<script setup lang=\"ts\">\n{PROBE}</script>\n\n<template><div /></template>\n"),
    );
    app
}

fn write_tsconfig(app: &Path, types: &str) {
    write_file(
        app,
        "tsconfig.json",
        &format!(
            r#"{{
  "compilerOptions": {{
    "target": "ESNext",
    "module": "ESNext",
    "moduleResolution": "bundler",
    "strict": true,
    "noEmit": true,
    "types": {types}
  }},
  "include": ["src/**/*.ts", "src/**/*.vue"]
}}"#
        ),
    );
}

/// `(line, column, code)` from `src/probe.ts(7,14): error TS2322: ...` lines.
fn typescript_diagnostics(output: &str) -> Vec<(u32, u32, String)> {
    output
        .lines()
        .filter_map(|line| {
            let rest = line.strip_prefix("src/probe.ts(")?;
            let (position, rest) = rest.split_once("): error ")?;
            let (line, column) = position.split_once(',')?;
            let code = rest.split_once(':')?.0;
            Some((line.parse().ok()?, column.parse().ok()?, code.to_owned()))
        })
        .collect()
}

/// `(line, column, code)` from Vize's `error:7:14 [TS2322] ...` entries.
fn vize_diagnostics(json: &serde_json::Value, file: &str) -> Vec<(u32, u32, String)> {
    json["files"]
        .as_array()
        .and_then(|files| {
            files.iter().find(|entry| {
                entry["file"]
                    .as_str()
                    .is_some_and(|path| Path::new(path).ends_with(file))
            })
        })
        .and_then(|entry| entry["diagnostics"].as_array())
        .map(|diagnostics| {
            diagnostics
                .iter()
                .filter_map(|diagnostic| {
                    let rest = diagnostic.as_str()?.strip_prefix("error:")?;
                    let (line, rest) = rest.split_once(':')?;
                    let (column, rest) = rest.split_once(" [")?;
                    let code = rest.split_once(']')?.0;
                    Some((line.parse().ok()?, column.parse().ok()?, code.to_owned()))
                })
                .collect()
        })
        .unwrap_or_default()
}

#[test]
fn check_walks_ancestor_node_modules_like_typescript() {
    let Some(corsa) = corsa_requirement::required_or_skip(corsa_path::resolve(workspace_root()))
    else {
        return;
    };
    let workspace = std::env::temp_dir()
        .join("vize-tests")
        .join(format!("ancestor-node-modules-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&workspace);
    if let Some(ancestor) = workspace
        .ancestors()
        .find(|ancestor| ancestor.join("node_modules").exists())
    {
        panic!("{} provides packages to the fixture", ancestor.display());
    }
    let app = write_workspace(&workspace);

    for (types, expected) in CASES {
        write_tsconfig(&app, types);
        let expected: Vec<(u32, u32, String)> = expected
            .iter()
            .map(|(line, column, code)| (*line, *column, (*code).to_owned()))
            .collect();

        let typescript = Command::new(&corsa)
            .current_dir(&app)
            .args(["-p", "tsconfig.json", "--pretty", "false"])
            .output()
            .unwrap();
        let typescript = String::from_utf8(typescript.stdout).unwrap();
        assert_eq!(
            typescript_diagnostics(&typescript),
            expected,
            "TypeScript no longer reports the fixture's expectation for types {types}:\n{typescript}"
        );

        let output = Command::new(env!("CARGO_BIN_EXE_vize"))
            .current_dir(&app)
            .env("CORSA_PATH", &corsa)
            .args(["check", "--no-config", "--format", "json"])
            .output()
            .unwrap();
        let stdout = String::from_utf8(output.stdout).unwrap();
        let stderr = String::from_utf8(output.stderr).unwrap();
        let json: serde_json::Value = serde_json::from_str(&stdout)
            .unwrap_or_else(|error| panic!("{error}\n{stdout}\n{stderr}"));
        assert_eq!(
            vize_diagnostics(&json, "src/probe.ts"),
            expected,
            "types {types}:\n{stdout}\n{stderr}"
        );
        let shifted: Vec<(u32, u32, String)> = expected
            .iter()
            .map(|(line, column, code)| (line + 1, *column, code.clone()))
            .collect();
        assert_eq!(
            vize_diagnostics(&json, "src/Probe.vue"),
            shifted,
            "types {types}:\n{stdout}\n{stderr}"
        );
    }

    let _ = std::fs::remove_dir_all(&workspace);
}
