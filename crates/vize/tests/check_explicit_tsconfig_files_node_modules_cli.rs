#![cfg(test)]
#![expect(clippy::disallowed_macros, reason = "fixtures use std strings")]
#![expect(clippy::disallowed_types, reason = "fixtures use std strings")]

#[path = "support/corsa_requirement.rs"]
mod corsa_requirement;

use std::{path::Path, process::Command};

fn workspace_root() -> &'static Path {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("workspace root should exist")
}

fn unique_case_dir() -> std::path::PathBuf {
    workspace_root()
        .join("target/vize-tests/tests")
        .join(format!(
            "explicit-tsconfig-files-node-modules-{}",
            std::process::id()
        ))
}

fn write_file(root: &Path, path: &str, content: &str) {
    let file_path = root.join(path);
    if let Some(parent) = file_path.parent() {
        std::fs::create_dir_all(parent).unwrap();
    }
    std::fs::write(file_path, content).unwrap();
}

fn resolve_test_corsa_path() -> Option<std::path::PathBuf> {
    let sibling_cache = workspace_root().parent()?.join("corsa-bind/.cache/tsgo");
    if sibling_cache.exists() {
        return Some(sibling_cache);
    }
    let workspace_bin = workspace_root().join("node_modules/.bin/tsgo");
    workspace_bin.exists().then_some(workspace_bin)
}

/// A shared tsconfig preset lists `../node_modules/vue/jsx.d.ts` in `files`.
/// From the consuming package that entry resolves under an ancestor
/// `node_modules`, so the retained-files filter used to drop it on explicit
/// runs (`vize check src/a.tsx`) while default runs kept it (#6685). Without
/// it every JSX element reports TS7026 (`JSX.IntrinsicElements` missing).
fn write_fixture(workspace: &Path) {
    write_file(
        workspace,
        "preset/package.json",
        r#"{ "name": "@repro/preset", "private": true }"#,
    );
    write_file(
        workspace,
        "preset/config/tsconfig.json",
        r#"{
  "compilerOptions": {
    "target": "ES2022",
    "module": "ESNext",
    "moduleResolution": "bundler",
    "strict": true,
    "skipLibCheck": true,
    "noEmit": true,
    "jsx": "preserve",
    "types": []
  },
  "files": ["../node_modules/vue/jsx.d.ts"]
}"#,
    );
    write_file(
        workspace,
        "preset/node_modules/vue/package.json",
        r#"{ "name": "vue", "types": "index.d.ts" }"#,
    );
    write_file(
        workspace,
        "preset/node_modules/vue/index.d.ts",
        "export {};\n",
    );
    write_file(
        workspace,
        "preset/node_modules/vue/jsx.d.ts",
        r#"declare global {
  namespace JSX {
    interface IntrinsicElements {
      [name: string]: unknown;
    }
  }
}

export {};
"#,
    );
    write_file(
        workspace,
        "app/package.json",
        r#"{ "name": "@repro/app", "private": true }"#,
    );
    write_file(
        workspace,
        "app/tsconfig.json",
        r#"{ "extends": "../preset/config/tsconfig.json", "include": ["src/**/*"] }"#,
    );
    write_file(
        workspace,
        "app/src/a.tsx",
        "export const el = <div class=\"x\">hi</div>;\n",
    );
}

fn run_check(app: &Path, corsa_path: &Path, patterns: &[&str]) -> (bool, String, String) {
    let mut args = vec!["check"];
    args.extend_from_slice(patterns);
    args.extend_from_slice(
        [
            "--no-config",
            "--tsconfig",
            "tsconfig.json",
            "--format",
            "json",
        ]
        .as_slice(),
    );
    let output = Command::new(env!("CARGO_BIN_EXE_vize"))
        .current_dir(app)
        .env("CORSA_PATH", corsa_path)
        .args(args)
        .output()
        .unwrap();
    (
        output.status.success(),
        std::string::String::from_utf8(output.stdout).unwrap(),
        std::string::String::from_utf8(output.stderr).unwrap(),
    )
}

#[test]
fn explicit_check_keeps_tsconfig_files_entry_under_ancestor_node_modules() {
    let Some(corsa_path) = corsa_requirement::required_or_skip(resolve_test_corsa_path()) else {
        return;
    };

    let workspace = unique_case_dir();
    let _ = std::fs::remove_dir_all(&workspace);
    write_fixture(&workspace);
    let app = workspace.join("app");

    // Default run: already fixed by #6685, kept here as the parity reference.
    let (success, stdout, stderr) = run_check(&app, &corsa_path, &[]);
    assert!(success, "default run failed:\n{stdout}\n{stderr}");
    let json: serde_json::Value = serde_json::from_str(&stdout).unwrap();
    assert_eq!(json["errorCount"], 0, "{stdout}\n{stderr}");

    // Explicit run: the same `files` entry must stay a program member.
    let (success, stdout, stderr) = run_check(&app, &corsa_path, &["src/a.tsx"]);
    assert!(
        success,
        "explicit run dropped the tsconfig `files` entry under node_modules:\n{stdout}\n{stderr}"
    );
    let json: serde_json::Value = serde_json::from_str(&stdout).unwrap();
    assert_eq!(json["errorCount"], 0, "{stdout}\n{stderr}");
    assert_eq!(json["warningCount"], 0, "{stdout}\n{stderr}");
    assert_eq!(json["fileCount"], 1, "{stdout}\n{stderr}");

    let _ = std::fs::remove_dir_all(&workspace);
}
