#![cfg(test)]
#![expect(clippy::disallowed_types, reason = "fixtures use std strings")]
//! `vize check` keeps a cached project mirror with one link per top-level
//! `node_modules` entry. Removing a package between runs leaves that mirror
//! link dangling; the next run must drop it instead of failing. On Windows the
//! links are directory junctions, and unlinking a dangling one as a file failed
//! every later check with `Access is denied. (os error 5)` (#13088).
use crate::support::corsa_path;
use crate::support::corsa_requirement;
use crate::support::vue_stub;

use std::{
    path::{Path, PathBuf},
    process::Command,
};

use vize_l0::cstr;

const APP: &str = r#"<script setup lang="ts">
const label = "ok";
</script>

<template>
  <p>{{ label }}</p>
</template>
"#;

struct CheckRun {
    status: Option<i32>,
    stdout: String,
    stderr: String,
}

fn check(root: &Path, corsa_path: &str) -> CheckRun {
    let output = Command::new(env!("CARGO_BIN_EXE_vize"))
        .current_dir(root)
        .env("CORSA_PATH", corsa_path)
        .args(["check", "--format", "json"])
        .output()
        .unwrap();
    CheckRun {
        status: output.status.code(),
        stdout: std::str::from_utf8(&output.stdout).unwrap().into(),
        stderr: std::str::from_utf8(&output.stderr).unwrap().into(),
    }
}

fn assert_clean(run: &CheckRun, step: &str) {
    assert_eq!(
        run.status,
        Some(0),
        "{step}\nstdout:\n{}\nstderr:\n{}",
        run.stdout,
        run.stderr
    );
    let json: serde_json::Value = serde_json::from_str(&run.stdout).unwrap_or_else(|error| {
        panic!(
            "{step}: invalid JSON: {error}\nstdout:\n{}\nstderr:\n{}",
            run.stdout, run.stderr
        )
    });
    assert_eq!(json["errorCount"], 0, "{step}\n{}", run.stdout);
}

#[test]
fn removing_a_package_between_checks_drops_its_stale_mirror_link() {
    let Some(corsa_path) =
        corsa_requirement::required_or_skip::<String>(corsa_path::resolve(&workspace_root()))
    else {
        return;
    };
    let case_id = cstr!("check-removed-package-{}", std::process::id());
    let root = workspace_root()
        .join("target")
        .join("vize-tests")
        .join("tests")
        .join(case_id.as_str());
    let _ = std::fs::remove_dir_all(&root);
    std::fs::create_dir_all(root.join("src")).unwrap();
    let _cleanup = Cleanup(root.clone());
    vue_stub::install_vue_jsx_type_stub(&root);
    std::fs::write(
        root.join("tsconfig.json"),
        r#"{
  "compilerOptions": { "strict": true, "target": "ES2022", "module": "ESNext", "moduleResolution": "bundler", "noEmit": true, "skipLibCheck": true },
  "include": ["src/**/*.ts", "src/**/*.vue"]
}"#,
    )
    .unwrap();
    std::fs::write(root.join("src/App.vue"), APP).unwrap();
    let extra = root.join("node_modules/extra");

    assert_clean(&check(&root, &corsa_path), "1: never installed");
    std::fs::create_dir_all(&extra).unwrap();
    assert_clean(&check(&root, &corsa_path), "2: installed");
    std::fs::remove_dir(&extra).unwrap();
    assert_clean(&check(&root, &corsa_path), "3: removed");
    assert_clean(&check(&root, &corsa_path), "4: still removed");
    std::fs::create_dir_all(&extra).unwrap();
    assert_clean(&check(&root, &corsa_path), "5: installed again");
}

struct Cleanup(PathBuf);

impl Drop for Cleanup {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .expect("workspace root should exist")
        .to_path_buf()
}
