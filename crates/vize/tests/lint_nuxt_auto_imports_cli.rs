//! `vize lint` accepts the names Nuxt auto-imports into templates.
#![cfg(test)]

use crate::support::vite_config;
use serde_json::{Value, json};
use std::{
    fs,
    path::{Path, PathBuf},
    process::{Command, Output},
};

const RULE: &str = "vue/no-undefined-refs";

/// The shape Nuxt writes to `<buildDir>/types/imports.d.ts`.
const GENERATED_IMPORTS: &str = r#"// Generated by auto imports
export {}
declare global {
  const defineComponent: typeof import('vue').defineComponent
  const formatCount: typeof import('../../app/utils/format').formatCount
  const useRoute: typeof import('nuxt/app').useRoute
}
// for vue template auto import
import { UnwrapRef } from 'vue'
declare module 'vue' {
  interface ComponentCustomProperties {
    readonly defineComponent: UnwrapRef<typeof import('vue')['defineComponent']>
    readonly formatCount: UnwrapRef<typeof import('../../app/utils/format')['formatCount']>
    readonly useRoute: UnwrapRef<typeof import('nuxt/app')['useRoute']>
  }
}
"#;

const PAGE: &str = r#"<script setup lang="ts">
const count = 1;
</script>

<template>
  <p>{{ formatCount(count) }} {{ formatCuont(count) }} {{ fromUnplugin(count) }}</p>
</template>
"#;

/// An Options API page whose component is an auto-imported `defineComponent`.
const OPTIONS_PAGE: &str = r#"<script lang="ts">
export default defineComponent({
  setup() {
    const route = useRoute();
    return { route };
  },
  computed: {
    upper(): string {
      return this.route.path.toUpperCase();
    },
  },
});
</script>

<template>
  <p>{{ route.path }} {{ upper }} {{ formatCount(7) }} {{ lower }}</p>
</template>
"#;

fn write(root: &Path, relative: &str, source: &str) {
    let path = root.join(relative);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, source).unwrap();
}

/// A project directory whose spelling matches the working directory the CLI
/// reports, so messages that name it compare exactly.
fn project() -> (tempfile::TempDir, PathBuf) {
    let directory = tempfile::tempdir().unwrap();
    let root = directory.path().canonicalize().unwrap();
    write(&root, "package.json", r#"{"private":true}"#);
    write(&root, "app/pages/index.vue", PAGE);
    write(&root, "app/pages/about.vue", OPTIONS_PAGE);
    (directory, root)
}

fn nuxt_project() -> (tempfile::TempDir, PathBuf) {
    let (directory, root) = project();
    write(
        &root,
        "nuxt.config.ts",
        "export default defineNuxtConfig({});\n",
    );
    write(
        &root,
        "node_modules/nuxt/package.json",
        r#"{"name":"nuxt"}"#,
    );
    (directory, root)
}

fn lint(root: &Path, config: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_vize"))
        .current_dir(root)
        .args(["lint", "app"])
        .args(config)
        .args(["--format", "json", "--help-level", "none"])
        .output()
        .unwrap()
}

/// Every finding of the rule as `[file, line, column, message]`.
fn undefined_refs(output: &Output) -> Vec<Value> {
    let report: Value = serde_json::from_slice(&output.stdout).unwrap();
    report
        .as_array()
        .unwrap()
        .iter()
        .flat_map(|file| {
            file["messages"]
                .as_array()
                .unwrap()
                .iter()
                .filter(|message| message["ruleId"] == RULE)
                .map(move |message| {
                    json!([
                        file["file"],
                        message["line"],
                        message["column"],
                        message["message"]
                    ])
                })
        })
        .collect()
}

fn undefined(file: &str, line: u32, column: u32, name: &str) -> Value {
    let message = vize_l0::cstr!("[vize:{RULE}] Variable '{name}' is not defined");
    json!([file, line, column, message.as_str()])
}

#[test]
fn generated_declarations_name_the_auto_imports_and_typos_stay_reported() {
    let (_directory, root) = nuxt_project();
    write(&root, ".nuxt/types/imports.d.ts", GENERATED_IMPORTS);

    let output = lint(&root, &["--no-config"]);
    assert_eq!(std::str::from_utf8(&output.stderr).unwrap(), "");
    assert_eq!(
        undefined_refs(&output),
        [
            undefined("app/pages/about.vue", 16, 59, "lower"),
            undefined("app/pages/index.vue", 6, 34, "formatCuont"),
            undefined("app/pages/index.vue", 6, 59, "fromUnplugin"),
        ]
    );
}

#[test]
fn configured_globals_join_the_generated_names() {
    let (_directory, root) = nuxt_project();
    write(&root, ".nuxt/types/imports.d.ts", GENERATED_IMPORTS);
    vite_config::write(
        &root,
        r#"{"linter":{"ruleOptions":{"vue/no-undefined-refs":{"globals":["fromUnplugin"]}}}}"#,
    );

    let output = lint(&root, &["--config", "vite.config.mjs"]);
    assert_eq!(std::str::from_utf8(&output.stderr).unwrap(), "");
    assert_eq!(
        undefined_refs(&output),
        [
            undefined("app/pages/about.vue", 16, 59, "lower"),
            undefined("app/pages/index.vue", 6, 34, "formatCuont"),
        ]
    );
}

#[test]
fn a_custom_build_dir_is_where_the_declarations_are_read() {
    let (_directory, root) = nuxt_project();
    write(
        &root,
        "nuxt.config.ts",
        "export default defineNuxtConfig({ buildDir: \".cache/nuxt\" });\n",
    );
    write(&root, ".cache/nuxt/types/imports.d.ts", GENERATED_IMPORTS);

    let output = lint(&root, &["--no-config"]);
    assert_eq!(std::str::from_utf8(&output.stderr).unwrap(), "");
    assert_eq!(undefined_refs(&output).len(), 3);
}

#[test]
fn a_project_without_generated_declarations_skips_the_rule_and_says_so() {
    let (_directory, root) = nuxt_project();

    let output = lint(&root, &["--no-config"]);
    let expected = vize_l0::cstr!(
        "[vize] Skipping vue/no-undefined-refs in {}: Nuxt has not generated {} yet, so \
         auto-imported names cannot be told from undefined ones. Run `nuxi prepare` to generate \
         it.\n",
        root.display(),
        root.join(".nuxt/types/imports.d.ts").display()
    );
    assert_eq!(std::str::from_utf8(&output.stderr).unwrap(), expected);
    assert_eq!(undefined_refs(&output), Vec::<Value>::new());
}

#[test]
fn a_project_that_is_not_nuxt_reads_nothing_and_reports_as_before() {
    let (_directory, root) = project();
    // Declarations left behind by another tool are not Nuxt's without Nuxt.
    write(&root, ".nuxt/types/imports.d.ts", GENERATED_IMPORTS);

    let output = lint(&root, &["--no-config"]);
    assert_eq!(std::str::from_utf8(&output.stderr).unwrap(), "");
    assert_eq!(
        undefined_refs(&output),
        [
            undefined("app/pages/about.vue", 16, 38, "formatCount"),
            undefined("app/pages/about.vue", 16, 59, "lower"),
            undefined("app/pages/index.vue", 6, 9, "formatCount"),
            undefined("app/pages/index.vue", 6, 34, "formatCuont"),
            undefined("app/pages/index.vue", 6, 59, "fromUnplugin"),
        ]
    );
}
