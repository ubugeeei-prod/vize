use super::{NuxtRoots, declared_names, template_globals};
use std::{fs, path::Path};

/// The shape Nuxt's import module writes: both declaration forms, a type
/// re-export block and nothing else.
const GENERATED: &str = r#"// Generated by auto imports
export {}
declare global {
  const $fetch: typeof import('../fetch').$fetch
  const formatCount: typeof import('../../app/utils/format').formatCount
  const useColor: typeof import('../../app/composables/states').useColor
}
// for type re-export
declare global {
  // @ts-ignore
  export type { ColorName } from '../../app/composables/states'
  import('../../app/composables/states')
}
// for vue template auto import
import { UnwrapRef } from 'vue'
declare module 'vue' {
  interface ComponentCustomProperties {
    readonly $fetch: UnwrapRef<typeof import('../fetch')['$fetch']>
    readonly formatCount: UnwrapRef<typeof import('../../app/utils/format')['formatCount']>
    readonly useColor: UnwrapRef<typeof import('../../app/composables/states')['useColor']>
  }
}
"#;

fn write(root: &Path, relative: &str, source: &str) {
    let path = root.join(relative);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, source).unwrap();
}

#[test]
fn both_generated_declaration_forms_name_an_auto_import() {
    assert_eq!(
        declared_names(GENERATED),
        [
            "$fetch",
            "formatCount",
            "useColor",
            "$fetch",
            "formatCount",
            "useColor"
        ]
    );
    assert_eq!(
        declared_names(
            "export {}\ndeclare global {\n  const shout: (value: string) => string\n}\n"
        ),
        ["shout"]
    );
    assert_eq!(
        declared_names(
            "declare module 'vue' {\n  interface ComponentCustomProperties {\n    readonly 'shout': () => void\n  }\n  interface GlobalComponents {\n    Card: unknown\n  }\n}\n"
        ),
        ["shout"]
    );
}

#[test]
fn disabled_auto_imports_and_type_re_exports_name_nothing() {
    for source in [
        "// Generated by auto imports\n// Implicit auto importing is disabled, you can use explicitly import from `#imports` instead.",
        "export {}\ndeclare global {\n  // @ts-ignore\n  export type { ColorName } from '../states'\n  import('../states')\n}\n",
        "export const formatCount: () => string\ninterface ComponentCustomProperties { shout: () => void }\n",
    ] {
        assert_eq!(declared_names(source), [""; 0], "{source}");
    }
}

#[test]
fn the_generated_directory_follows_a_literal_build_dir() {
    let project = tempfile::tempdir().unwrap();
    let root = project.path();
    write(
        root,
        "nuxt.config.ts",
        "export default defineNuxtConfig({})\n",
    );
    assert_eq!(
        template_globals(root),
        Err(root.join(".nuxt/types/imports.d.ts"))
    );
    write(root, ".nuxt/types/imports.d.ts", GENERATED);
    assert_eq!(template_globals(root).unwrap().len(), 6);

    write(
        root,
        "nuxt.config.ts",
        "export default defineNuxtConfig({ buildDir: 'build/nuxt' })\n",
    );
    assert_eq!(
        template_globals(root),
        Err(root.join("build/nuxt/types/imports.d.ts"))
    );
    write(
        root,
        "build/nuxt/types/imports.d.ts",
        "export {}\ndeclare global {\n  const shout: () => void\n}\n",
    );
    assert_eq!(template_globals(root).unwrap(), ["shout"]);

    // A computed directory cannot be read from the config, so the default
    // location stays the best evidence.
    write(
        root,
        "nuxt.config.ts",
        "export default defineNuxtConfig({ buildDir: process.env.OFF ? '.nuxt-off' : '.nuxt' })\n",
    );
    assert_eq!(template_globals(root).unwrap().len(), 6);
}

#[test]
fn the_nearest_config_owns_a_directory_until_another_package_starts() {
    let project = tempfile::tempdir().unwrap();
    let root = project.path();
    write(root, "apps/web/nuxt.config.ts", "export default {}\n");
    write(root, "apps/web/package.json", "{}");
    write(root, "apps/web/app/pages/index.vue", "");
    write(root, "apps/web/packages/ui/package.json", "{}");
    write(root, "apps/web/packages/ui/src/Button.vue", "");
    write(root, "apps/docs/nuxt.config.mjs", "export default {}\n");
    write(root, "apps/docs/pages/index.vue", "");
    write(root, "apps/plain/src/App.vue", "");

    let mut roots = NuxtRoots::default();
    assert_eq!(roots.nearest(&root.join("apps/web/app/pages")), Some(0));
    assert_eq!(roots.nearest(&root.join("apps/web/app")), Some(0));
    assert_eq!(roots.nearest(&root.join("apps/web")), Some(0));
    assert_eq!(roots.nearest(&root.join("apps/web/packages/ui/src")), None);
    assert_eq!(roots.nearest(&root.join("apps/docs/pages")), Some(1));
    assert_eq!(roots.nearest(&root.join("apps/plain/src")), None);
    assert_eq!(
        roots.into_dirs(),
        [root.join("apps/web"), root.join("apps/docs")]
    );
}
