import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";
import {
  changedMembers,
  packBrowserPackage,
} from "../../tools/commands/levels/packed-browser-equivalence.ts";
import { capture } from "../../tools/support/compat/npm/wasm-responses.ts";

test("compares actual npm archive contents, including additions and generated bytes", () => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), "vize-packed-test-"));
  try {
    const source = path.join(temp, "source");
    fs.mkdirSync(source);
    fs.writeFileSync(
      path.join(source, "package.json"),
      JSON.stringify({ name: "@vizejs/wasm", version: "1.0.0", files: ["*.wasm", "*.js"] }),
    );
    fs.writeFileSync(path.join(source, "module.wasm"), Buffer.from([0, 97, 115, 109]));
    fs.writeFileSync(path.join(source, "local.txt"), "unpacked build log");
    const base = packBrowserPackage(source, path.join(temp, "base"));
    fs.writeFileSync(path.join(source, "local.txt"), "different build log");
    const identical = packBrowserPackage(source, path.join(temp, "same"));
    assert.deepEqual(base, identical);
    fs.writeFileSync(path.join(source, "module.wasm"), Buffer.from([0, 97, 115, 108]));
    fs.writeFileSync(path.join(source, "glue.js"), "export {}");
    const different = packBrowserPackage(source, path.join(temp, "head"));
    assert.notEqual(different.sha256, base.sha256);
    assert.deepEqual(changedMembers(base, different), ["glue.js", "module.wasm"]);
    assert.deepEqual(changedMembers(different, base), ["glue.js", "module.wasm"]);
  } finally {
    fs.rmSync(temp, { recursive: true, force: true });
  }
});

test("response evidence distinguishes diagnostics, thrown values and observable layout", () => {
  const fail = (message: string) => {
    throw new RangeError(message);
  };
  assert.deepEqual(
    capture(() => fail("bad offset")),
    capture(() => fail("bad offset")),
  );
  assert.notDeepEqual(
    capture(() => fail("bad offset")),
    capture(() => fail("bad range")),
  );
  assert.notDeepEqual(
    capture(() => {
      throw undefined;
    }),
    capture(() => undefined),
  );
  assert.notDeepEqual(
    capture(() => ({})),
    capture(() => ({ map: undefined })),
  );
  assert.notDeepEqual(
    capture(() => ({ a: 1, b: 2 })),
    capture(() => ({ b: 2, a: 1 })),
  );
});
