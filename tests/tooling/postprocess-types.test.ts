import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";

import { postprocessGeneratedTypes } from "../../tools/support/tasks/postprocess-types.ts";
import { repoRoot, runToolCommand } from "./_helpers/tool-commands.ts";

const script = "tools/support/tasks/postprocess-types.ts";

const scratchRoot = path.join(repoRoot, "target", "vize-tests", "tooling-tests");

function createFixtureRoot(): string {
  fs.mkdirSync(scratchRoot, { recursive: true });
  const root = fs.mkdtempSync(path.join(scratchRoot, "postprocess-types-"));
  fs.mkdirSync(path.join(root, "npm", "cli", "src", "types"), { recursive: true });
  return root;
}

function generatedTypesPath(root: string): string {
  return path.join(root, "npm", "cli", "src", "types", "generated.ts");
}

test("postprocess-types script applies generated config type patches", () => {
  const root = createFixtureRoot();
  const generatedPath = generatedTypesPath(root);
  fs.writeFileSync(
    generatedPath,
    `/* eslint-disable */
/**
 * This file was automatically generated by json-schema-to-typescript.
 * DO NOT MODIFY IT BY HAND. Instead, modify the source JSONSchema file,
 * and run json-schema-to-typescript to regenerate this file.
 */

export interface VizeConfig {
  /**
   * JSON Schema reference for editor autocompletion
   */
  $schema?: string;
  musea?: MuseaA11YConfig;
}

export interface VitePluginConfig {
  include?: string | string[];
  exclude?: string | string[];
}

export interface MuseaA11YConfig {}
`,
  );

  const result = runToolCommand(script, [], {
    env: {
      VIZE_REPO_ROOT: root,
    },
  });
  assert.equal(result.status, 0, `${result.stderr}\n${result.stdout}`.trim());

  const expected = `/* eslint-disable */
/**
 * This file was automatically generated by json-schema-to-typescript.
 * DO NOT MODIFY IT BY HAND. Instead, modify the source JSONSchema file,
 * and run json-schema-to-typescript to regenerate this file.
 */

export type LintPreset = NonNullable<LinterConfig["preset"]>;

export type RuleSeverity = "off" | "warn" | "error";

export type RuleCategory = "correctness" | "suspicious" | "style" | "perf" | "a11y" | "security";

export interface VizeConfig {
  musea?: MuseaA11yConfig;
}

export interface VitePluginConfig {
  include?: string | RegExp | (string | RegExp)[];
  exclude?: string | RegExp | (string | RegExp)[];
}

export interface MuseaA11yConfig {}
`;

  assert.equal(fs.readFileSync(generatedPath, "utf8"), expected);

  const secondResult = runToolCommand(script, [], {
    env: {
      VIZE_REPO_ROOT: root,
    },
  });
  assert.equal(secondResult.status, 0, `${secondResult.stderr}\n${secondResult.stdout}`.trim());
  assert.equal(fs.readFileSync(generatedPath, "utf8"), expected);
});

test("postprocess-types reports its output and patches only the first schema property", () => {
  const root = createFixtureRoot();
  const generatedPath = generatedTypesPath(root);
  const schema =
    "  /**\n   * JSON Schema reference for editor autocompletion\n   */\n  $schema?: string;\n";
  fs.writeFileSync(generatedPath, `${schema}${schema}MuseaA11YConfig MuseaA11YConfig\n`);

  const result = runToolCommand(script, [], {
    cwd: path.dirname(root),
    env: { VIZE_REPO_ROOT: path.basename(root) },
  });

  assert.equal(result.status, 0, result.stderr);
  assert.equal(result.stdout, `Post-processed generated types: ${generatedPath}\n`);
  assert.equal(
    fs.readFileSync(generatedPath, "utf8"),
    `${schema}MuseaA11yConfig MuseaA11yConfig\n`,
  );
  assert.equal(
    postprocessGeneratedTypes("export type LintPreset = x;"),
    "export type LintPreset = x;",
  );
  assert.equal(postprocessGeneratedTypes("no marker"), "no marker");
});

test("postprocess-types finds the repository root from a nested directory", () => {
  const root = createFixtureRoot();
  fs.writeFileSync(path.join(root, "Cargo.toml"), "");
  fs.writeFileSync(path.join(root, "npm", "cli", "package.json"), "{}");
  fs.writeFileSync(generatedTypesPath(root), "interface A { include?: string | string[]; }\n");
  const nested = path.join(root, "npm", "cli", "src");
  // A nested Cargo manifest without the CLI package is not the repository root.
  fs.writeFileSync(path.join(nested, "Cargo.toml"), "");

  const result = runToolCommand(script, [], { cwd: nested, env: { VIZE_REPO_ROOT: undefined } });

  assert.equal(result.status, 0, result.stderr);
  assert.equal(
    result.stdout,
    `Post-processed generated types: ${generatedTypesPath(fs.realpathSync(root))}\n`,
  );
  assert.equal(
    fs.readFileSync(generatedTypesPath(root), "utf8"),
    "interface A { include?: string | RegExp | (string | RegExp)[]; }\n",
  );
});

test("postprocess-types reports missing roots, unreadable and unwritable declarations", () => {
  const root = createFixtureRoot();
  const outside = fs.mkdtempSync(path.join(os.tmpdir(), "postprocess-types-outside-"));
  try {
    const unlocated = runToolCommand(script, [], {
      cwd: outside,
      env: { VIZE_REPO_ROOT: undefined },
    });
    assert.deepEqual(
      [unlocated.status, unlocated.stdout],
      [1, "Failed to locate the repository root for postprocess_types\n"],
    );
  } finally {
    fs.rmSync(outside, { recursive: true, force: true });
  }

  const unreadable = runToolCommand(script, [], { env: { VIZE_REPO_ROOT: root } });
  assert.deepEqual(
    [unreadable.status, unreadable.stdout],
    [1, `Failed to read ${generatedTypesPath(root)}\n`],
  );

  if (process.platform !== "win32" && process.getuid?.() !== 0) {
    fs.writeFileSync(generatedTypesPath(root), "MuseaA11YConfig");
    fs.chmodSync(generatedTypesPath(root), 0o444);
    const unwritable = runToolCommand(script, [], { env: { VIZE_REPO_ROOT: root } });
    assert.deepEqual(
      [unwritable.status, unwritable.stdout],
      [1, `Failed to write ${generatedTypesPath(root)}\n`],
    );
    assert.equal(fs.readFileSync(generatedTypesPath(root), "utf8"), "MuseaA11YConfig");
  }
});

test("public config schemas and generated declarations omit custom config inheritance", () => {
  const schema = JSON.parse(
    fs.readFileSync(path.join(repoRoot, "npm/cli/schemas/vize.config.schema.json"), "utf8"),
  );
  for (const config of [schema, schema.definitions.VizeConfigEntry]) {
    assert.equal(config.additionalProperties, false);
    assert.ok(!Object.hasOwn(config.properties, "extends"));
    assert.ok(Object.hasOwn(config.properties, "compiler"));
    assert.ok(Object.hasOwn(config.properties, "typeChecker"));
  }
  const declarations = fs.readFileSync(generatedTypesPath(repoRoot), "utf8");
  assert.doesNotMatch(declarations, /extends\??:/);
  for (const file of ["VizeConfig.pkl", "vize.pkl", "jsonschema/generate.pkl"]) {
    const source = fs.readFileSync(path.join(repoRoot, "npm/cli/pkl", file), "utf8");
    assert.doesNotMatch(source, /ConfigExtends|configExtendsDef|`extends`:/);
  }
});
