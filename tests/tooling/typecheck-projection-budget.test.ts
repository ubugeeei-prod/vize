import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";

import {
  assertProjectionBudget,
  checkerBusyMs,
  checkMsByFile,
  probeBytesByFile,
  projectionReport,
  renderProjection,
} from "../../tools/benchmarks/scripts/typecheck-corpus-pair-projection.ts";
import {
  assertOwnedProjectionBudget,
  compareOwnedProjections,
  ownedProbeRows,
} from "../../tools/benchmarks/scripts/typecheck-owned-pair-projection.ts";

test("projection proof rejects missing, errored and unstable transforms and fails every violation", () => {
  const line = (bytes: number, file = "A.vue", sourceBytes = 20, templateBytes = 8) =>
    JSON.stringify({
      pid: 1,
      fileName: `/input/${file}`,
      bytes,
      sourceBytes,
      templateBytes,
    }) + "\n";
  const base = ownedProbeRows(line(12), "/input", 1, ["A.vue"]),
    vue = ownedProbeRows(line(10), "/input", 1, ["A.vue"]);
  const overBudget = compareOwnedProjections(base, base, vue);
  assert.equal(overBudget.violations.length, 1);
  assert.throws(() => assertOwnedProjectionBudget(overBudget), /A\.vue/u);
  assert.doesNotThrow(() =>
    assertOwnedProjectionBudget(
      compareOwnedProjections(base, ownedProbeRows(line(9), "/input", 1, ["A.vue"]), vue),
    ),
  );
  assert.throws(
    () => ownedProbeRows(line(12), "/input", 2, ["A.vue", "B.vue"]),
    /not every expected SFC reached the mapper/u,
  );
  assert.throws(
    () => ownedProbeRows(line(12) + line(13), "/input", 1, ["A.vue"]),
    /unstable repeated projection: A\.vue/u,
  );
  assert.throws(
    () =>
      ownedProbeRows(
        JSON.stringify({ pid: 1, fileName: "/input/A.vue", error: "failed" }),
        "/input",
        1,
        ["A.vue"],
      ),
    /mapper transform failed/u,
  );
  assert.throws(
    () =>
      compareOwnedProjections(base, ownedProbeRows(line(12, "B.vue"), "/input", 1, ["B.vue"]), vue),
    /head\/Vue transformed SFC set differs/u,
  );
  assert.throws(
    () =>
      compareOwnedProjections(
        base,
        ownedProbeRows(line(9, "A.vue", 21), "/input", 1, ["A.vue"]),
        vue,
      ),
    /authored SFC\/template bytes differ/u,
  );
});

test("the projection report ranks authored and generated bytes with traced check time", (t) => {
  const directory = mkdtempSync(join(tmpdir(), "typecheck-projection-budget-"));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  const root = join(directory, "project");
  const record = (file: string, bytes: number) =>
    JSON.stringify({
      pid: 1,
      fileName: join(root, file),
      bytes,
      sourceBytes: file === "A.vue" ? 80 : 50,
      templateBytes: file === "A.vue" ? 30 : 20,
    });
  const bytes = (entries: [string, number][]) =>
    probeBytesByFile(entries.map(([file, size]) => record(file, size)).join("\n"), root);
  const traces = join(directory, "traces");
  mkdirSync(traces);
  writeFileSync(
    join(traces, "trace.json"),
    JSON.stringify([
      { ph: "X", name: "checkSourceFile", ts: 0, dur: 4000, args: { path: join(root, "A.vue") } },
      {
        ph: "B",
        name: "checkSourceFile",
        ts: 10,
        pid: 1,
        tid: 2,
        args: { path: join(root, "B.vue") },
      },
      { ph: "B", name: "checkExpression", ts: 20, pid: 1, tid: 2 },
      { ph: "E", name: "checkSourceFile", ts: 2010, pid: 1, tid: 2 },
      { ph: "X", name: "checkSourceFile", ts: 0, dur: 9000, args: { path: "/elsewhere/lib.d.ts" } },
    ]),
  );
  const check = checkMsByFile(traces, root);
  assert.deepEqual(
    [...check],
    [
      ["A.vue", 4],
      ["B.vue", 2],
    ],
  );
  assert.deepEqual(checkerBusyMs(traces), [13, 2]);
  const report = projectionReport("demo", {
    base: {
      bytes: bytes([
        ["A.vue", 300],
        ["B.vue", 100],
      ]),
      check,
    },
    head: {
      bytes: bytes([
        ["A.vue", 200],
        ["B.vue", 100],
      ]),
      check,
      busy: [13, 2],
    },
    vue: {
      bytes: bytes([
        ["A.vue", 150],
        ["B.vue", 120],
      ]),
      check: new Map(),
    },
  });
  assert.deepEqual(report.totals.head, { bytes: 300, checkMs: 6 });
  assert.deepEqual(report.totals.vue, { bytes: 270, checkMs: null });
  assert.deepEqual(report.authored, { sourceBytes: 130, templateBytes: 50 });
  assert.equal(report.headAtMostVue, 1);
  assert.deepEqual(report.violations, ["A.vue"]);
  assert.throws(() => assertProjectionBudget([report]), /demo\/A\.vue/u);
  const markdown = renderProjection(report);
  assert.doesNotThrow(() => renderProjection(report));
  assert.match(markdown, /A\.vue/u);

  const withinBudget = projectionReport("passing", {
    base: {
      bytes: bytes([
        ["A.vue", 180],
        ["B.vue", 100],
      ]),
      check,
    },
    head: {
      bytes: bytes([
        ["A.vue", 140],
        ["B.vue", 100],
      ]),
      check,
    },
    vue: {
      bytes: bytes([
        ["A.vue", 150],
        ["B.vue", 120],
      ]),
      check: new Map(),
    },
  });
  assert.doesNotThrow(() => assertProjectionBudget([withinBudget]));
  assert.throws(
    () =>
      projectionReport("missing", {
        base: { bytes: bytes([["A.vue", 180]]), check },
        head: {
          bytes: bytes([
            ["A.vue", 140],
            ["B.vue", 100],
          ]),
          check,
        },
        vue: {
          bytes: bytes([
            ["A.vue", 150],
            ["B.vue", 120],
          ]),
          check: new Map(),
        },
      }),
    /SFC set differs/u,
  );
});
