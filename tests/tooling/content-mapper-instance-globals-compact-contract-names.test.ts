import assert from "node:assert/strict";
import { test } from "node:test";

import {
  readGlobalsFixture,
  sha,
  type Transform,
} from "./support/content-mapper-instance-globals-10617.ts";
import { selectPacketGoldens } from "./support/content-mapper-instance-globals-packets-10617.ts";

type Row = [number, number, number, number, number, number];
type Result = Transform & {
  mappings: Row[];
  diagnosticDirectives: { directives: Row[]; unusedExpectDirectiveDiagnostics: unknown[] };
};

const CURRENT = "source-packets-current-a21f72c9e8f2.json";
const PREVIOUS = "source-packets-current-c6a6c571b090.json";
const CHANGED = [
  "lf/slot-shadow",
  "lf/mixed-slot-scope",
  "crlf-unicode/slot-shadow",
  "crlf-unicode/mixed-slot-scope",
];
const LEGACY_CONTRACT_NAME =
  /(?<![\w$])__([A-Za-z_$][\w$]*?)_(Component|Props|ValueProps|CheckProps|CheckTail|Check)_(\d+)(?![\w$])/gu;

/** `__Child_Component_0` → `__VComp0`, with every renamed byte range of `text`. */
function compact(text: string): { text: string; edits: Array<[number, number, number]> } {
  const edits: Array<[number, number, number]> = [];
  const renamed = text.replace(LEGACY_CONTRACT_NAME, (name, _component, role, index, at) => {
    const next = `__V${role === "Component" ? "Comp" : role}${index}`;
    const start = Buffer.byteLength(text.slice(0, at));
    edits.push([start, Buffer.byteLength(name), Buffer.byteLength(next)]);
    return next;
  });
  return { text: renamed, edits };
}

/** A generated byte offset after the renames; an offset inside a renamed name has none. */
function shifted(edits: Array<[number, number, number]>, offset: number): number {
  let delta = 0;
  for (const [start, before, after] of edits) {
    if (offset <= start) break;
    assert.ok(offset >= start + before, `offset ${offset} falls inside a renamed name`);
    delta += after - before;
  }
  return offset + delta;
}

test("CURRENT only respells the per-usage contract aliases as compact __V names", () => {
  const { authority, files, cases } = readGlobalsFixture();
  assert.equal(authority.currentSourcePackets, CURRENT);
  const current = selectPacketGoldens(authority, files, cases)!;
  const previous = selectPacketGoldens(
    { ...authority, currentSourcePackets: PREVIOUS },
    files,
    cases,
  )!;
  const provenance = JSON.parse(files.get(current.provenance as string)!);
  assert.equal(provenance.pullRequest, 12646);
  assert.equal(provenance.producer.sourceRevision, "a21f72c9e8f26addb6c4c6082986fcf3070178ef");
  assert.deepEqual(provenance.previousPopulation, {
    path: PREVIOUS,
    bytes: Buffer.byteLength(files.get(PREVIOUS)!),
    sha256: sha(files.get(PREVIOUS)!),
  });
  assert.deepEqual(provenance.successorPopulation, {
    path: CURRENT,
    bytes: Buffer.byteLength(files.get(CURRENT)!),
    sha256: sha(files.get(CURRENT)!),
  });
  assert.deepEqual(
    provenance.capturedQualification.gapIds,
    CHANGED.map((label) => `whole-packet/${label}`),
  );

  const observed: string[] = [];
  for (const [index, packet] of current.packets.entries()) {
    const old = previous.packets[index]!;
    assert.equal(packet.label, old.label);
    assert.equal(packet.sourceSha256, old.sourceSha256);
    assert.equal(packet.globalsSha256, old.globalsSha256);
    if (!CHANGED.includes(packet.label)) {
      assert.deepEqual(packet.result, old.result, packet.label);
      continue;
    }
    observed.push(packet.label);
    const before = old.result as Result;
    const after = packet.result as Result;
    const { text, edits } = compact(before.text);
    assert.equal(edits.length, 14, `${packet.label} renames every contract alias occurrence`);
    const at = (offset: number) => shifted(edits, offset);
    const mappings = before.mappings.map(
      ([generated, length, ...rest]) =>
        [at(generated), at(generated + length) - at(generated), ...rest] as Row,
    );
    const directives = before.diagnosticDirectives.directives.map(
      ([a, b, from, to, ...rest]) => [a, b, at(from), at(to), ...rest] as Row,
    );
    assert.deepEqual(after, {
      ...before,
      text,
      mappings,
      diagnosticDirectives: { ...before.diagnosticDirectives, directives },
    });
  }
  assert.deepEqual(observed, CHANGED);
});
