import assert from "node:assert/strict";

type CurrentPacketProvenance = {
  artifact: {
    repository: string;
    run: number;
    job: number;
    id: number;
    name: string;
    digest: string;
    bytes: number;
  };
  capturedQualification: {
    totalOutcomes: number;
    passedOutcomes: number;
    gapCount: number;
    status: string;
    fullPacketQualification: boolean;
    hostMatrixQualification: boolean;
    gapIds: string[];
  };
  review: {
    completePackets: number;
    allNonWholePacketOutcomesPassed: boolean;
    qualificationCredit: boolean;
    nativeAcceptanceCredit: boolean;
    publicPackageAcceptanceCredit: boolean;
    performanceCredit: boolean;
    reason: string;
  };
};

/** Packets whose component type has no fallthrough surface stay byte-identical. */
const unchangedCases = [
  "v-for-source",
  "loop-shadow",
  "expect-owned-interpolation",
  "ignore-owned-interpolation",
  "expect-owned-foreign-sibling",
  "ignore-owned-foreign-sibling",
  "mixed-loop-scope",
  "mixed-slot-scope",
];

export function currentPacketChanges(labels: readonly string[]): string[] {
  return labels.filter((label) => !unchangedCases.includes(label.slice(label.indexOf("/") + 1)));
}

/** Only the Options API packet exports an authored default component (#13113). */
export function authoredComponentPacketChanges(labels: readonly string[]): string[] {
  return labels.filter((label) => label.endsWith("/options-own-method"));
}

export function assertCurrentPacketProvenance(
  provenance: CurrentPacketProvenance,
  labels: readonly string[],
): void {
  assert.deepEqual(provenance.artifact, {
    repository: "ubugeeei-prod/vize",
    run: 43895142413,
    job: 133399750546,
    id: 14240220954,
    name: "instance-globals-10617-026787445f98a058d741022b1a0c60cfbd1270f1-1",
    digest: "sha256:abdaf19d7ee51d14f795ff9d9ac1ee3deaacb47b2a31a5e488092836681db56d",
    bytes: 18672241,
  });
  const changed = authoredComponentPacketChanges(labels);
  assert.equal(labels.length, 80);
  assert.equal(changed.length, 2);
  assert.deepEqual(provenance.capturedQualification, {
    totalOutcomes: 499,
    passedOutcomes: 497,
    gapCount: 2,
    status: "unqualified",
    fullPacketQualification: false,
    hostMatrixQualification: false,
    gapIds: changed.map((label) => `whole-packet/${label}`),
  });
  assert.deepEqual(provenance.review, {
    completePackets: 80,
    allNonWholePacketOutcomesPassed: true,
    qualificationCredit: false,
    nativeAcceptanceCredit: false,
    publicPackageAcceptanceCredit: false,
    performanceCredit: false,
    reason:
      "Only the LF and CRLF/Unicode options-own-method whole packets changed: their Options API component type binds the authored default export by inference (`$AuthoredComponent extends infer A extends object ? … & A & …`, #13113), one generated byte shorter, with every later coordinate moved by the edit; diagnostics, directives, and all other fields stayed exact, the other 78 complete results were byte-identical, and all 497 semantic, protocol, mapping-geometry, and real-host controls passed; this record retains the observed postimages without assigning acceptance credit to the stale-golden run.",
  });
}
