import assert from "node:assert/strict";
import { test } from "node:test";
import {
  relocatePacket,
  type Assets,
} from "../../../tools/support/compat/content-mapper/constructor-projection-parity.ts";
import {
  certifyFallthroughSourceFields,
  currentAttrValueKeySet,
  previousAttrValueKeySet,
} from "../../../tools/support/compat/content-mapper/shared-usage-gates-transition.ts";

/** #12793: the raw fallthrough source fields and the key-set `$AttrValue` replacement. */
export function registerSharedUsageGateChecks(assets: Assets): void {
  test("raw fallthrough source fields cover generated components and ignore helper patterns", () => {
    const marker = " readonly __vizeHasFallthroughProps: true;";
    const prefix = " readonly __vizeComponentMarker: true; readonly __vizeRawProps?: Props;";
    const helper = `type Helper<C> = C extends { readonly __vizeComponentMarker: true;${marker} } ? C : never;`;
    const before = Buffer.from(
      `type A = {${prefix}${marker} };\n${helper}\ntype B = {${prefix}${marker} };`,
    );
    const after = Buffer.from(
      `type A = {${prefix} readonly __vizeFallthroughSource?: AProps;${marker} };\n` +
        `${helper}\ntype B = {${prefix} readonly __vizeFallthroughSource?: BProps;${marker} };`,
    );
    const edits = certifyFallthroughSourceFields(before, after);
    assert.equal(edits.length, 2);
    assert.deepEqual(
      edits.map((edit) => edit.replacement.toString()),
      [
        " readonly __vizeFallthroughSource?: AProps;",
        " readonly __vizeFallthroughSource?: BProps;",
      ],
    );
    assert.deepEqual(certifyFallthroughSourceFields(after, after), []);
    assert.throws(
      () =>
        certifyFallthroughSourceFields(
          before,
          Buffer.from(after.toString().replace(" readonly __vizeFallthroughSource?: AProps;", "")),
        ),
      /each fallthrough marker/,
    );
  });

  test("key-set attr value helper is one exact certified replacement", () => {
    const packet = (text: string) => ({ text, mappings: [], diagnostics: [] });
    const proof = relocatePacket(
      packet(previousAttrValueKeySet),
      packet(currentAttrValueKeySet),
      "",
      assets,
    );
    assert.equal(proof.edits.length, 1);
    assert.equal(proof.edits[0]?.start, 0);
    assert.throws(
      () =>
        relocatePacket(
          packet(previousAttrValueKeySet),
          packet(currentAttrValueKeySet.replace("unknown", "never")),
          "",
          assets,
        ),
      /complete generated bytes|certified key-set attr value transition/,
    );
  });
}
