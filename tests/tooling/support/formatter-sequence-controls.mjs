// Independent runtime contracts; formatter output is never the oracle.
const state = { a: 2, b: 3, count: 0, text: "seed" };
const event = (
  id,
  expression,
  eventHtml = "<button>2</button>",
  data = state,
  body = "{{ count }}",
  quote = '"',
) => ({
  id,
  file: `${id}.vue`,
  source: `<template>\n  <button @click=${quote}${expression}${quote}>${body}</button>\n</template>\n`,
  states: [data],
  html: [body.includes("text") ? "<button>seed:0</button>" : "<button>0</button>"],
  eventHtml: [eventHtml],
});

